-- Deploy only in DEV. The test ID is deliberately kept outside GOLD.XREF.
CREATE TABLE IF NOT EXISTS AUDIT_DB.MONITORING.ADDRESSCHANGE_PILOT_TRACKING_DEV (
    TEST_KEY VARCHAR NOT NULL,
    D365_GUID VARCHAR NOT NULL,
    CAPTURED_AT TIMESTAMP_LTZ NOT NULL
);

CREATE PROCEDURE AUDIT_DB.MONITORING.SP_CAPTURE_ADDRESSCHANGE_PILOT_DEV(
    P_D365_GUID VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_GUID VARCHAR;
    V_ROWS NUMBER DEFAULT 0;
    V_MATCHES NUMBER DEFAULT 0;
    INVALID_ID EXCEPTION (-20001, 'Invalid Address Change pilot ID.');
    CAPTURE_CONFLICT EXCEPTION (-20002, 'Address Change pilot tracking conflicts or is duplicated.');
BEGIN
    V_GUID := LOWER(TRIM(P_D365_GUID));
    IF (V_GUID IS NULL OR NOT REGEXP_LIKE(
        V_GUID, '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
    )) THEN
        RAISE INVALID_ID;
    END IF;

    BEGIN TRANSACTION;
    BEGIN
        SELECT COUNT(*),
            COALESCE(COUNT_IF(LOWER(TRIM(D365_GUID)) = :V_GUID), 0)
        INTO :V_ROWS, :V_MATCHES
        FROM AUDIT_DB.MONITORING.ADDRESSCHANGE_PILOT_TRACKING_DEV
        WHERE TEST_KEY = 'ADDRESSCHANGE_TEST:8478';

        IF (V_ROWS > 1 OR (V_ROWS = 1 AND V_MATCHES <> 1)) THEN
            RAISE CAPTURE_CONFLICT;
        END IF;

        IF (V_ROWS = 0) THEN
            INSERT INTO AUDIT_DB.MONITORING.ADDRESSCHANGE_PILOT_TRACKING_DEV (
                TEST_KEY, D365_GUID, CAPTURED_AT
            )
            VALUES ('ADDRESSCHANGE_TEST:8478', :V_GUID, CURRENT_TIMESTAMP());
        END IF;

        COMMIT;
        RETURN 'CAPTURED';
    EXCEPTION
        WHEN OTHER THEN
            ROLLBACK;
            RAISE;
    END;
END;
$$;
