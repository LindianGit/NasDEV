-- Deploy in DEV as the object owner or an authorised grant administrator.
CREATE TABLE IF NOT EXISTS AUDIT_DB.MONITORING.CONSENT_PILOT_TRACKING_DEV (
    TEST_KEY VARCHAR NOT NULL,
    D365_GUID VARCHAR NOT NULL,
    CAPTURED_AT TIMESTAMP_LTZ NOT NULL
);

CREATE PROCEDURE AUDIT_DB.MONITORING.SP_CAPTURE_CONSENT_PILOT_DEV(
    P_D365_GUID VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_GUID VARCHAR;
    V_ROWS NUMBER DEFAULT 0;
    V_MATCHES NUMBER DEFAULT 0;
    INVALID_ID EXCEPTION (-20001, 'Unexpected Consent pilot ID.');
    CAPTURE_CONFLICT EXCEPTION (-20002, 'Consent pilot tracking conflicts or is duplicated.');
BEGIN
    V_GUID := LOWER(TRIM(P_D365_GUID));
    IF (V_GUID IS NULL OR V_GUID <> '9d1fdf0d-00cd-40a0-a40d-8e06e6053af8') THEN
        RAISE INVALID_ID;
    END IF;

    BEGIN TRANSACTION;
    BEGIN
        SELECT COUNT(*),
            COALESCE(COUNT_IF(LOWER(TRIM(D365_GUID)) = :V_GUID), 0)
        INTO :V_ROWS, :V_MATCHES
        FROM AUDIT_DB.MONITORING.CONSENT_PILOT_TRACKING_DEV
        WHERE TEST_KEY = 'CONSENT_TEST:2273445';

        IF (V_ROWS > 1 OR (V_ROWS = 1 AND V_MATCHES <> 1)) THEN
            RAISE CAPTURE_CONFLICT;
        END IF;

        IF (V_ROWS = 0) THEN
            INSERT INTO AUDIT_DB.MONITORING.CONSENT_PILOT_TRACKING_DEV (
                TEST_KEY, D365_GUID, CAPTURED_AT
            )
            VALUES ('CONSENT_TEST:2273445', :V_GUID, CURRENT_TIMESTAMP());
        END IF;

        COMMIT;
        RETURN 'CAPTURED';
    EXCEPTION
        WHEN OTHER THEN
            ROLLBACK;
            RAISE;
    END;
END;
$$;

GRANT USAGE ON DATABASE AUDIT_DB TO ROLE R_NAS_ETL_DEV;
GRANT USAGE ON SCHEMA AUDIT_DB.MONITORING TO ROLE R_NAS_ETL_DEV;
GRANT SELECT ON TABLE AUDIT_DB.MONITORING.CONSENT_PILOT_TRACKING_DEV
TO ROLE R_NAS_ETL_DEV;
GRANT USAGE ON PROCEDURE AUDIT_DB.MONITORING.SP_CAPTURE_CONSENT_PILOT_DEV(VARCHAR)
TO ROLE R_NAS_ETL_DEV;
