-- Deploy in DEV as the object owner or an authorised grant administrator.
-- Synthetic creation only; never capture the planned ID before target proof.
CREATE TABLE IF NOT EXISTS AUDIT_DB.MONITORING.POSTCODE_PILOT_TRACKING_DEV (
    TEST_KEY VARCHAR NOT NULL,
    D365_GUID VARCHAR NOT NULL,
    CAPTURED_AT TIMESTAMP_LTZ NOT NULL
);

CREATE PROCEDURE AUDIT_DB.MONITORING.SP_CAPTURE_POSTCODE_PILOT_DEV(
    P_D365_GUID VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_GUID VARCHAR;
    V_ROWS NUMBER DEFAULT 0;
    V_MATCHES NUMBER DEFAULT 0;
    INVALID_ID EXCEPTION (-20001, 'Unexpected Postcode pilot ID.');
    CAPTURE_CONFLICT EXCEPTION (-20002, 'Postcode pilot tracking conflicts or is duplicated.');
BEGIN
    V_GUID := LOWER(TRIM(P_D365_GUID));
    IF (V_GUID IS NULL OR V_GUID <> '6d60ded3-97a2-409a-bb8f-d62abb08315d') THEN
        RAISE INVALID_ID;
    END IF;

    BEGIN TRANSACTION;
    BEGIN
        SELECT COUNT(*),
            COALESCE(COUNT_IF(
                TEST_KEY = 'POSTCODE_TEST:DEV-001'
                AND LOWER(TRIM(D365_GUID)) = :V_GUID
            ), 0)
        INTO :V_ROWS, :V_MATCHES
        FROM AUDIT_DB.MONITORING.POSTCODE_PILOT_TRACKING_DEV
        WHERE TEST_KEY = 'POSTCODE_TEST:DEV-001'
           OR LOWER(TRIM(D365_GUID)) = :V_GUID;

        IF (V_ROWS > 1 OR (V_ROWS = 1 AND V_MATCHES <> 1)) THEN
            RAISE CAPTURE_CONFLICT;
        END IF;

        IF (V_ROWS = 0) THEN
            INSERT INTO AUDIT_DB.MONITORING.POSTCODE_PILOT_TRACKING_DEV (
                TEST_KEY, D365_GUID, CAPTURED_AT
            )
            VALUES ('POSTCODE_TEST:DEV-001', :V_GUID, CURRENT_TIMESTAMP());
        END IF;

        COMMIT;
        RETURN 'CAPTURED';
    EXCEPTION
        WHEN OTHER THEN
            ROLLBACK;
            RAISE;
    END;
END;
$$;

