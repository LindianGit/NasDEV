create or replace TABLE AUDIT_DB.CONFIG.PIPELINE_WATERMARK (
	PIPELINE_ID VARCHAR(100) NOT NULL,
	SOURCE_INSTANCE VARCHAR(100) NOT NULL,
	ENTITY_ID VARCHAR(200) NOT NULL,
	WATERMARK_VALUE VARCHAR(500),
	WATERMARK_TYPE VARCHAR(20) DEFAULT 'TIMESTAMP',
	LAST_RUN_START TIMESTAMP_LTZ(9),
	LAST_RUN_END TIMESTAMP_LTZ(9),
	LAST_RUN_STATUS VARCHAR(20),
	LAST_RUN_ROWS NUMBER(38,0),
	LAST_RUN_ID VARCHAR(200),
	AUTH_TOKEN_EXPIRES_AT TIMESTAMP_LTZ(9),
	AUTH_REFRESH_TOKEN_EXPIRES_AT TIMESTAMP_LTZ(9),
	PREVIOUS_WATERMARK VARCHAR(500),
	CONSECUTIVE_FAILURES NUMBER(38,0) DEFAULT 0,
	LAST_ERROR_MESSAGE VARCHAR(16777216),
	CREATED TIMESTAMP_LTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	MODIFIED TIMESTAMP_LTZ(9),
	constraint PK_PIPELINE_WATERMARK primary key (PIPELINE_ID, SOURCE_INSTANCE, ENTITY_ID),
	constraint FK_PIPELINE_WATERMARK_METADATA foreign key (PIPELINE_ID, SOURCE_INSTANCE, ENTITY_ID) references AUDIT_DB.CONFIG.PIPELINE_METADATA(PIPELINE_ID,SOURCE_INSTANCE,ENTITY_ID)
);