-- Read-only diagnostic: find the closest single-split cash Gifts with both links.
-- These are not approved for dispatch; live Dynamics checks and other safety
-- gates still apply even when this diagnostic reports no blockers.
WITH LINKED AS (
    SELECT
        T.RE_GIFT_ID,
        T.RE_IMPORT_ID,
        T.RE_GIFT_TYPE_CODE,
        T.D365_TARGET,
        T.DONOR_TYPE,
        T.RE_CONSTITUENT_ID AS GIFT_CONSTITUENT_ID,
        T.RE_GIFT_DATE,
        T.RE_AMOUNT,
        T.POSSIBLE_MATCHES_BY_GIFT_ID,
        T.POSSIBLE_MATCHES_BY_IMPORT_ID,
        L.RE_SPLIT_ID,
        L.RE_CONSTITUENT_ID AS SPLIT_CONSTITUENT_ID,
        L.RE_CAMPAIGN_ID,
        L.RE_APPEAL_ID,
        L.RE_PACKAGE_ID,
        L.RE_SPLIT_AMOUNT,
        L.PARENT_ROWS,
        L.PARENT_TARGET
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_MSNFP_TRANSACTION AS T
    INNER JOIN INTEGRATION_DB.DYNAMICS.VW_D365_MSNFP_DESIGNATEDCREDIT AS L
        ON T.RE_GIFT_ID = L.RE_GIFT_ID
    WHERE T.RE_GIFT_TYPE_CODE = 1
      AND T.SPLIT_COUNT = 1
      AND T.DONOR_D365_ID IS NOT NULL
      AND L.DESIGNATION_D365_ID IS NOT NULL
),

GIFT_COUNTS AS (
    SELECT ID, COUNT(*) AS ROWS_PER_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_GIFTS
    WHERE ID IN (SELECT RE_GIFT_ID FROM LINKED)
    GROUP BY ID
),

SPLIT_COUNTS AS (
    SELECT ID, COUNT(*) AS ROWS_PER_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_GIFTSPLITS
    WHERE ID IN (SELECT RE_SPLIT_ID FROM LINKED)
    GROUP BY ID
),

GIFT_TYPE_MAP AS (
    SELECT RE_GIFT_TYPE_CODE, COUNT(DISTINCT D365_TARGET) AS TARGET_COUNT
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_REF_GIFT_TYPE
    GROUP BY RE_GIFT_TYPE_CODE
),

XREF_KEYS AS (
    SELECT DISTINCT GOLDEN_RECORD_ID
    FROM MDM_DB.GOLD.XREF
    WHERE SOURCE_SYSTEM = 'DYNAMICS'
),

CHECKED AS (
    SELECT
        L.RE_GIFT_ID,
        L.RE_SPLIT_ID,
        L.RE_GIFT_DATE,
        L.RE_AMOUNT,
        L.RE_SPLIT_AMOUNT,
        A.RE_CAMPAIGN_ID,
        A.RE_APPEAL_ID,
        A.RE_PACKAGE_ID,
        A.STATUS AS ATTRIBUTION_STATUS,
        A.BLOCKERS AS ATTRIBUTION_BLOCKERS,
        ARRAY_CONSTRUCT_COMPACT(
            IFF(COALESCE(G.ROWS_PER_ID, 0) <> 1, 'GIFT_ID_NOT_UNIQUE', NULL),
            IFF(COALESCE(S.ROWS_PER_ID, 0) <> 1, 'SPLIT_ID_NOT_UNIQUE', NULL),
            IFF(COALESCE(M.TARGET_COUNT, 0) <> 1
                OR COALESCE(L.D365_TARGET, '') <> 'TRANSACTION',
                'GIFT_TYPE_NOT_UNAMBIGUOUS', NULL),
            IFF(COALESCE(L.DONOR_TYPE, '') NOT IN ('contact', 'account'),
                'DONOR_TYPE_INVALID', NULL),
            IFF(COALESCE(L.PARENT_ROWS, 0) <> 1
                OR COALESCE(L.PARENT_TARGET, '') <> 'TRANSACTION',
                'PARENT_NOT_UNAMBIGUOUS', NULL),
            IFF((L.RE_CAMPAIGN_ID IS NOT NULL
                OR L.RE_APPEAL_ID IS NOT NULL
                OR L.RE_PACKAGE_ID IS NOT NULL)
                AND COALESCE(A.STATUS, '') <> 'RESOLVED_IN_EXTRACT',
                'ATTRIBUTION_UNRESOLVED', NULL),
            IFF(NULLIF(TRIM(TO_VARCHAR(L.GIFT_CONSTITUENT_ID)), '') IS NULL
                OR COALESCE(TRIM(TO_VARCHAR(L.GIFT_CONSTITUENT_ID)), '')
                    <> COALESCE(TRIM(TO_VARCHAR(L.SPLIT_CONSTITUENT_ID)), ''),
                'CONSTITUENT_MISMATCH', NULL),
            IFF(NOT COALESCE(REGEXP_LIKE(TO_VARCHAR(L.RE_GIFT_ID), '[0-9]+'), FALSE)
                OR NOT COALESCE(REGEXP_LIKE(TO_VARCHAR(L.RE_SPLIT_ID), '[0-9]+'), FALSE),
                'SOURCE_ID_FORMAT', NULL),
            IFF(NOT COALESCE(REGEXP_LIKE(
                    TO_VARCHAR(L.RE_AMOUNT), '[0-9]+([.][0-9]{1,2})?'
                ), FALSE)
                OR NOT COALESCE(REGEXP_LIKE(
                    TO_VARCHAR(L.RE_SPLIT_AMOUNT), '[0-9]+([.][0-9]{1,2})?'
                ), FALSE),
                'AMOUNT_FORMAT', NULL),
            IFF(TRY_TO_DATE(LEFT(TRIM(L.RE_GIFT_DATE), 10), 'YYYY-MM-DD') IS NULL,
                'INVALID_GIFT_DATE', NULL),
            IFF(TRY_TO_DECIMAL(TO_VARCHAR(L.RE_AMOUNT), 38, 2) IS NULL
                OR TRY_TO_DECIMAL(TO_VARCHAR(L.RE_AMOUNT), 38, 2) <= 0
                OR TRY_TO_DECIMAL(TO_VARCHAR(L.RE_SPLIT_AMOUNT), 38, 2) IS NULL
                OR TRY_TO_DECIMAL(TO_VARCHAR(L.RE_AMOUNT), 38, 2)
                    <> TRY_TO_DECIMAL(TO_VARCHAR(L.RE_SPLIT_AMOUNT), 38, 2),
                'AMOUNTS_INVALID_OR_UNEQUAL', NULL),
            IFF(COALESCE(L.POSSIBLE_MATCHES_BY_GIFT_ID, -1) <> 0
                OR COALESCE(L.POSSIBLE_MATCHES_BY_IMPORT_ID, 0) <> 0,
                'POSSIBLE_DYNAMICS_MATCH', NULL),
            IFF(XG.GOLDEN_RECORD_ID IS NOT NULL OR XS.GOLDEN_RECORD_ID IS NOT NULL
                OR IG.SOURCE_RECORD_ID IS NOT NULL OR ISPLIT.SOURCE_RECORD_ID IS NOT NULL,
                'ALREADY_CAPTURED', NULL)
        ) AS BLOCKERS
    FROM LINKED AS L
    LEFT JOIN GIFT_COUNTS AS G ON L.RE_GIFT_ID = G.ID
    LEFT JOIN SPLIT_COUNTS AS S ON L.RE_SPLIT_ID = S.ID
    LEFT JOIN GIFT_TYPE_MAP AS M ON L.RE_GIFT_TYPE_CODE = M.RE_GIFT_TYPE_CODE
    LEFT JOIN INTEGRATION_DB.DYNAMICS.VW_D365_GIFT_PILOT_ATTRIBUTION_DEV AS A
        ON L.RE_GIFT_ID = A.RE_GIFT_ID AND L.RE_SPLIT_ID = A.RE_SPLIT_ID
    LEFT JOIN XREF_KEYS AS XG
        ON XG.GOLDEN_RECORD_ID = 'TRANSACTION:' || TO_VARCHAR(L.RE_GIFT_ID)
    LEFT JOIN XREF_KEYS AS XS
        ON XS.GOLDEN_RECORD_ID = 'DESIGNATEDCREDIT:' || TO_VARCHAR(L.RE_SPLIT_ID)
    LEFT JOIN MDM_DB.GOLD.GIFT_D365_IDENTITY AS IG
        ON IG.ENTITY_ID = 'TRANSACTION'
        AND IG.SOURCE_RECORD_ID = TO_VARCHAR(L.RE_GIFT_ID)
    LEFT JOIN MDM_DB.GOLD.GIFT_D365_IDENTITY AS ISPLIT
        ON ISPLIT.ENTITY_ID = 'DESIGNATEDCREDIT'
        AND ISPLIT.SOURCE_RECORD_ID = TO_VARCHAR(L.RE_SPLIT_ID)
)

SELECT
    RE_GIFT_ID,
    RE_SPLIT_ID,
    RE_GIFT_DATE,
    RE_AMOUNT,
    RE_SPLIT_AMOUNT,
    RE_CAMPAIGN_ID,
    RE_APPEAL_ID,
    RE_PACKAGE_ID,
    ATTRIBUTION_STATUS,
    ATTRIBUTION_BLOCKERS,
    ARRAY_SIZE(BLOCKERS) AS BLOCKER_COUNT,
    ARRAY_TO_STRING(BLOCKERS, ', ') AS BLOCKERS
FROM CHECKED
ORDER BY BLOCKER_COUNT, RE_GIFT_ID, RE_SPLIT_ID
LIMIT 5;
