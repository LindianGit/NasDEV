-- Tests for INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION
-- Run each block on its own. Blocks marked PASS/FAIL return RESULT = 'PASS' or 'FAIL'.
-- Blocks marked INFO return numbers to read and record.
-- Test ids match the test plan.

-- 1.1 PASS/FAIL: no row without a second person
SELECT IFF(COUNT(*) = 0, 'PASS', 'FAIL') AS RESULT, COUNT(*) AS BAD_ROWS
FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION
WHERE RE_RELATION_CONSTITUENT_ID IS NULL OR RE_CONSTITUENT_ID IS NULL;

-- 1.2 PASS/FAIL: no self links
SELECT IFF(COUNT(*) = 0, 'PASS', 'FAIL') AS RESULT, COUNT(*) AS BAD_ROWS
FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION
WHERE RE_CONSTITUENT_ID = RE_RELATION_CONSTITUENT_ID;

-- 1.3 INFO: view row count. Expect about 110k to 150k.
SELECT COUNT(*) AS VIEW_ROWS FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION;

-- 1.4 INFO: source rows that are dropped. Expect 211206 with no second person.
SELECT
    COUNT(*) AS SOURCE_ROWS,
    COUNT_IF(RELATION_CONSTITUENT_ID IS NULL) AS NO_SECOND_PERSON,
    COUNT_IF(RELATION_CONSTITUENT_ID IS NOT NULL) AS WITH_BOTH_PEOPLE
FROM RAW.RAISERS_EDGE.VW_ODS_T_RELATIONSHIPS;

-- 2.1 PASS/FAIL: no pair appears twice
SELECT IFF(COUNT(*) = 0, 'PASS', 'FAIL') AS RESULT, COUNT(*) AS DUPLICATE_PAIRS
FROM (
    SELECT
        LEAST(RE_CONSTITUENT_ID, RE_RELATION_CONSTITUENT_ID) AS A,
        GREATEST(RE_CONSTITUENT_ID, RE_RELATION_CONSTITUENT_ID) AS B
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION
    GROUP BY 1, 2
    HAVING COUNT(*) > 1
);

-- 2.2 PASS/FAIL: every mirrored pair in the source gives exactly one view row
WITH SRC_PAIRS AS (
    SELECT DISTINCT
        LEAST(R.CONSTITUENT_ID, R.RELATION_CONSTITUENT_ID) AS A,
        GREATEST(R.CONSTITUENT_ID, R.RELATION_CONSTITUENT_ID) AS B
    FROM RAW.RAISERS_EDGE.VW_ODS_T_RELATIONSHIPS AS R
    INNER JOIN RAW.RAISERS_EDGE.VW_ODS_T_RELATIONSHIPS AS M
        ON R.CONSTITUENT_ID = M.RELATION_CONSTITUENT_ID
        AND R.RELATION_CONSTITUENT_ID = M.CONSTITUENT_ID
    WHERE R.CONSTITUENT_ID <> R.RELATION_CONSTITUENT_ID
),
VIEW_PAIRS AS (
    SELECT
        LEAST(RE_CONSTITUENT_ID, RE_RELATION_CONSTITUENT_ID) AS A,
        GREATEST(RE_CONSTITUENT_ID, RE_RELATION_CONSTITUENT_ID) AS B,
        COUNT(*) AS N
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION
    GROUP BY 1, 2
)
SELECT
    IFF(COUNT_IF(V.N IS DISTINCT FROM 1) = 0, 'PASS', 'FAIL') AS RESULT,
    COUNT(*) AS MIRRORED_PAIRS,
    COUNT_IF(V.N IS NULL) AS MISSING_FROM_VIEW,
    COUNT_IF(V.N > 1) AS DUPLICATED_IN_VIEW
FROM SRC_PAIRS AS S
LEFT JOIN VIEW_PAIRS AS V
    ON S.A = V.A AND S.B = V.B;

-- 2.3 INFO: pairs with different link types. Look at which row won.
WITH MULTI AS (
    SELECT
        LEAST(CONSTITUENT_ID, RELATION_CONSTITUENT_ID) AS A,
        GREATEST(CONSTITUENT_ID, RELATION_CONSTITUENT_ID) AS B
    FROM RAW.RAISERS_EDGE.VW_ODS_T_RELATIONSHIPS
    WHERE RELATION_CONSTITUENT_ID IS NOT NULL
    GROUP BY 1, 2
    HAVING COUNT(DISTINCT TRIM(RELATION_DESCRIPTION)) > 1
)
SELECT
    LEAST(R.CONSTITUENT_ID, R.RELATION_CONSTITUENT_ID) AS A,
    GREATEST(R.CONSTITUENT_ID, R.RELATION_CONSTITUENT_ID) AS B,
    R.ID,
    R.RELATION_DESCRIPTION,
    R.RECIP_RELATION_DESCRIPTION,
    R.DATE_FROM,
    V.RE_RELATIONSHIP_ID IS NOT NULL AS KEPT_IN_VIEW
FROM RAW.RAISERS_EDGE.VW_ODS_T_RELATIONSHIPS AS R
INNER JOIN MULTI AS M
    ON LEAST(R.CONSTITUENT_ID, R.RELATION_CONSTITUENT_ID) = M.A
    AND GREATEST(R.CONSTITUENT_ID, R.RELATION_CONSTITUENT_ID) = M.B
LEFT JOIN INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION AS V
    ON R.ID = V.RE_RELATIONSHIP_ID
ORDER BY A, B, R.ID
LIMIT 60;

-- 2.4 PASS/FAIL: when one row of a pair has role names and another has none,
-- the kept row has at least one role name
WITH PAIR_STATS AS (
    SELECT
        LEAST(CONSTITUENT_ID, RELATION_CONSTITUENT_ID) AS A,
        GREATEST(CONSTITUENT_ID, RELATION_CONSTITUENT_ID) AS B
    FROM RAW.RAISERS_EDGE.VW_ODS_T_RELATIONSHIPS
    WHERE RELATION_CONSTITUENT_ID IS NOT NULL
        AND CONSTITUENT_ID <> RELATION_CONSTITUENT_ID
    GROUP BY 1, 2
    HAVING MAX(IFF(NULLIF(TRIM(RELATION_DESCRIPTION), '') IS NOT NULL, 1, 0)) = 1
        AND MIN(IFF(NULLIF(TRIM(RELATION_DESCRIPTION), '') IS NULL, 1, 0)) = 1
)
SELECT
    IFF(COUNT_IF(V.ROLE1_NAME IS NULL AND V.ROLE2_NAME IS NULL) = 0, 'PASS', 'FAIL') AS RESULT,
    COUNT(*) AS PAIRS_TESTED,
    COUNT_IF(V.ROLE1_NAME IS NULL AND V.ROLE2_NAME IS NULL) AS KEPT_ROW_HAS_NO_ROLES
FROM PAIR_STATS AS P
INNER JOIN INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION AS V
    ON LEAST(V.RE_CONSTITUENT_ID, V.RE_RELATION_CONSTITUENT_ID) = P.A
    AND GREATEST(V.RE_CONSTITUENT_ID, V.RE_RELATION_CONSTITUENT_ID) = P.B;

-- 3.1 / 3.2 / 3.3 PASS/FAIL: dates are parsed by length
SELECT
    IFF(COUNT_IF(EXPECTED_START IS DISTINCT FROM V.EFFECTIVE_START) = 0, 'PASS', 'FAIL') AS RESULT,
    COUNT(*) AS ROWS_TESTED,
    COUNT_IF(EXPECTED_START IS DISTINCT FROM V.EFFECTIVE_START) AS MISMATCHES
FROM (
    SELECT
        ID,
        CASE LENGTH(TRIM(DATE_FROM))
            WHEN 8 THEN TRY_TO_DATE(TRIM(DATE_FROM), 'YYYYMMDD')
            WHEN 6 THEN TRY_TO_DATE(TRIM(DATE_FROM) || '01', 'YYYYMMDD')
            WHEN 4 THEN TRY_TO_DATE(TRIM(DATE_FROM) || '0101', 'YYYYMMDD')
        END AS EXPECTED_START
    FROM RAW.RAISERS_EDGE.VW_ODS_T_RELATIONSHIPS
) AS S
INNER JOIN INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION AS V
    ON S.ID = V.RE_RELATIONSHIP_ID;

-- 3.1 / 3.2 INFO: eyeball year-only and year-month rows
SELECT R.ID, R.DATE_FROM, V.EFFECTIVE_START, R.DATE_TO, V.EFFECTIVE_END
FROM RAW.RAISERS_EDGE.VW_ODS_T_RELATIONSHIPS AS R
INNER JOIN INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION AS V
    ON R.ID = V.RE_RELATIONSHIP_ID
WHERE LENGTH(TRIM(R.DATE_FROM)) IN (4, 6) OR LENGTH(TRIM(R.DATE_TO)) IN (4, 6)
LIMIT 30;

-- 3.4 PASS/FAIL: a non-blank date that cannot be parsed becomes NULL, never a wrong date
SELECT
    IFF(COUNT_IF(V.EFFECTIVE_START IS NOT NULL) = 0, 'PASS', 'FAIL') AS RESULT,
    COUNT(*) AS BAD_DATE_ROWS_IN_VIEW
FROM RAW.RAISERS_EDGE.VW_ODS_T_RELATIONSHIPS AS R
INNER JOIN INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION AS V
    ON R.ID = V.RE_RELATIONSHIP_ID
WHERE LENGTH(TRIM(R.DATE_FROM)) NOT IN (4, 6, 8) AND TRIM(R.DATE_FROM) <> '';

-- 3.5 INFO: end before start. Expect few or none. List them.
SELECT RE_RELATIONSHIP_ID, EFFECTIVE_START, EFFECTIVE_END
FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION
WHERE EFFECTIVE_END < EFFECTIVE_START
LIMIT 50;

-- 4.1 INFO: record types
SELECT RECORD1_TYPE, RECORD2_TYPE, COUNT(*) AS ROWS_N
FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION
GROUP BY 1, 2
ORDER BY ROWS_N DESC;

-- 4.2 INFO: trace one row by hand. Pick any id from the view, then compare
-- the golden record and D365 ids with VW_D365_CONNECTION.
SELECT V.RE_RELATIONSHIP_ID, V.RE_CONSTITUENT_ID, V.RECORD1_D365_ID,
       X.GOLDEN_RECORD_ID, IDS.D365_CONTACT_ID, IDS.D365_ACCOUNT_ID
FROM (
    SELECT *
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION
    WHERE RECORD1_D365_ID IS NOT NULL
    LIMIT 5
) AS V
INNER JOIN MDM_DB.GOLD.XREF AS X
    ON X.SOURCE_SYSTEM = 'RAISERS_EDGE'
    AND X.SOURCE_RECORD_ID = TO_VARCHAR(V.RE_CONSTITUENT_ID)
INNER JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS AS IDS
    ON X.GOLDEN_RECORD_ID = IDS.GOLDEN_RECORD_ID;

-- 4.3 PASS/FAIL: RE ids that sit in one golden record resolve to the same D365 id
WITH MERGED AS (
    SELECT GOLDEN_RECORD_ID
    FROM MDM_DB.GOLD.XREF
    WHERE SOURCE_SYSTEM = 'RAISERS_EDGE'
    GROUP BY 1
    HAVING COUNT(*) > 1
),
SIDE AS (
    SELECT X.GOLDEN_RECORD_ID, V.RECORD1_D365_ID AS D365_ID
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION AS V
    INNER JOIN MDM_DB.GOLD.XREF AS X
        ON X.SOURCE_SYSTEM = 'RAISERS_EDGE'
        AND X.SOURCE_RECORD_ID = TO_VARCHAR(V.RE_CONSTITUENT_ID)
    INNER JOIN MERGED AS M
        ON X.GOLDEN_RECORD_ID = M.GOLDEN_RECORD_ID
    WHERE V.RECORD1_D365_ID IS NOT NULL
)
SELECT
    IFF(COUNT(*) = 0, 'PASS', 'FAIL') AS RESULT,
    COUNT(*) AS GOLDEN_RECORDS_WITH_MORE_THAN_ONE_D365_ID
FROM (
    SELECT GOLDEN_RECORD_ID
    FROM SIDE
    GROUP BY 1
    HAVING COUNT(DISTINCT D365_ID) > 1
);

-- 4.4 INFO: how many rows lack a D365 id at either end
SELECT
    COUNT(*) AS TOTAL,
    COUNT_IF(RECORD1_D365_ID IS NULL) AS NO_ID_RECORD1,
    COUNT_IF(RECORD2_D365_ID IS NULL) AS NO_ID_RECORD2,
    COUNT_IF(RECORD1_D365_ID IS NULL OR RECORD2_D365_ID IS NULL) AS NO_ID_EITHER
FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION;

-- 5.1 / 5.2 PASS/FAIL: role ids match the Dynamics roles table, ignoring case and padding
SELECT
    IFF(COUNT_IF(R.CONNECTIONROLEID IS NOT NULL
                 AND V.ROLE1_D365_ID IS DISTINCT FROM R.CONNECTIONROLEID) = 0, 'PASS', 'FAIL') AS RESULT,
    COUNT(*) AS ROWS_WITH_ROLE1,
    COUNT_IF(V.ROLE1_D365_ID IS NOT NULL) AS RESOLVED
FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION AS V
LEFT JOIN (
    SELECT UPPER(TRIM(NAME)) AS NAME_KEY, CONNECTIONROLEID
    FROM RAW.DYNAMICS.VW_ODS_CONNECTIONROLES
    QUALIFY ROW_NUMBER() OVER (PARTITION BY UPPER(TRIM(NAME)) ORDER BY CREATEDON, CONNECTIONROLEID) = 1
) AS R
    ON UPPER(V.ROLE1_NAME) = R.NAME_KEY
WHERE V.ROLE1_NAME IS NOT NULL;

-- 5.3 INFO: role names RE has that Dynamics lacks (these rows are held)
SELECT ROLE_NAME, COUNT(*) AS ROWS_N
FROM (
    SELECT ROLE1_NAME AS ROLE_NAME FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION
    WHERE ROLE1_NAME IS NOT NULL AND ROLE1_D365_ID IS NULL
    UNION ALL
    SELECT ROLE2_NAME FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION
    WHERE ROLE2_NAME IS NOT NULL AND ROLE2_D365_ID IS NULL
)
GROUP BY 1
ORDER BY ROWS_N DESC;

-- 5.4 INFO: rows with a blank role name
SELECT
    COUNT_IF(ROLE1_NAME IS NULL) AS NO_ROLE1,
    COUNT_IF(ROLE2_NAME IS NULL) AS NO_ROLE2,
    COUNT_IF(HOLD_REASON LIKE '%NO_ROLE1%') AS FLAGGED_NO_ROLE1,
    COUNT_IF(HOLD_REASON LIKE '%NO_ROLE2%') AS FLAGGED_NO_ROLE2
FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION;

-- 6.1 INFO: load action and hold reasons. Expect all HOLD while both gates are open.
SELECT LOAD_ACTION, COUNT(*) AS ROWS_N
FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION
GROUP BY 1;

SELECT HOLD_REASON, COUNT(*) AS ROWS_N
FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION
GROUP BY 1
ORDER BY ROWS_N DESC
LIMIT 30;

-- 6.2 / 6.3 PASS/FAIL: reasons are consistent with the action
SELECT
    IFF(COUNT_IF(LOAD_ACTION = 'HOLD' AND HOLD_REASON IS NULL) = 0
        AND COUNT_IF(LOAD_ACTION = 'CREATE' AND HOLD_REASON IS NOT NULL) = 0, 'PASS', 'FAIL') AS RESULT,
    COUNT_IF(LOAD_ACTION = 'HOLD' AND HOLD_REASON IS NULL) AS HOLD_WITHOUT_REASON,
    COUNT_IF(LOAD_ACTION = 'CREATE' AND HOLD_REASON IS NOT NULL) AS CREATE_WITH_REASON
FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION;

-- 6.4 MANUAL: gates are open, so no row is CREATE. To test the CREATE path,
-- copy the view definition to a scratch view with the GATES CTE returning NULL,
-- then repeat 6.1. Do not change VW_D365_REF_LOAD_GATE.
SELECT GATE_CODE, IS_OPEN
FROM INTEGRATION_DB.DYNAMICS.VW_D365_REF_LOAD_GATE
WHERE D365_TABLE = 'connection';

-- 6.5 PASS/FAIL: canvasser flag agrees with HOLD_REASON
SELECT
    IFF(COUNT_IF(EXPECTED_CANVASSER <> (V.HOLD_REASON LIKE '%CANVASSER%')) = 0, 'PASS', 'FAIL') AS RESULT,
    COUNT(*) AS ROWS_TESTED,
    COUNT_IF(EXPECTED_CANVASSER) AS CANVASSER_ROWS
FROM (
    SELECT
        V.RE_RELATIONSHIP_ID,
        COALESCE(C1.ISCANVASSER, FALSE) OR COALESCE(C2.ISCANVASSER, FALSE) AS EXPECTED_CANVASSER
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION AS V
    LEFT JOIN RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENT AS C1
        ON V.RE_CONSTITUENT_ID = C1.CONSTITUENT_ID
    LEFT JOIN RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENT AS C2
        ON V.RE_RELATION_CONSTITUENT_ID = C2.CONSTITUENT_ID
) AS X
INNER JOIN INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION AS V
    ON X.RE_RELATIONSHIP_ID = V.RE_RELATIONSHIP_ID;

-- 6.6 PASS/FAIL: GDPR-suppressed people are held
SELECT
    IFF(COUNT_IF(V.HOLD_REASON LIKE '%GDPR_SUPPRESSED%') = COUNT(*), 'PASS', 'FAIL') AS RESULT,
    COUNT(*) AS SUPPRESSED_ROWS,
    COUNT_IF(V.LOAD_ACTION = 'CREATE') AS WRONGLY_CREATE
FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION AS V
WHERE EXISTS (
    SELECT 1
    FROM MDM_DB.GOLD.XREF AS X
    INNER JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS AS IDS
        ON X.GOLDEN_RECORD_ID = IDS.GOLDEN_RECORD_ID
    WHERE X.SOURCE_SYSTEM = 'RAISERS_EDGE'
        AND X.SOURCE_RECORD_ID IN (TO_VARCHAR(V.RE_CONSTITUENT_ID), TO_VARCHAR(V.RE_RELATION_CONSTITUENT_ID))
        AND IDS.IS_GDPR_SUPPRESSED
);

-- 7.1 / 7.2 / 7.3 PASS/FAIL: payload shape
SELECT
    IFF(COUNT_IF(TYPEOF(PAYLOAD) <> 'OBJECT') = 0
        AND COUNT_IF(PAYLOAD:record1id IS NULL AND RECORD1_D365_ID IS NOT NULL) = 0
        AND COUNT_IF(PAYLOAD:record2id IS NULL AND RECORD2_D365_ID IS NOT NULL) = 0
        AND COUNT_IF(PAYLOAD:statecode::NUMBER <> IFF(EFFECTIVE_END IS NULL, 0, 1)) = 0, 'PASS', 'FAIL') AS RESULT,
    COUNT_IF(TYPEOF(PAYLOAD) <> 'OBJECT') AS NOT_OBJECT,
    COUNT_IF(PAYLOAD:statecode::NUMBER <> IFF(EFFECTIVE_END IS NULL, 0, 1)) AS WRONG_STATECODE
FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION;

-- 7.2 INFO: keys present in the payload
SELECT DISTINCT F.VALUE::STRING AS PAYLOAD_KEY
FROM (SELECT PAYLOAD FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONNECTION LIMIT 1000) AS V,
    LATERAL FLATTEN(INPUT => OBJECT_KEYS(V.PAYLOAD)) AS F;

