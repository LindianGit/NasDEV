CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_ADDRESSCHANGE_PILOT_PREVIEW_DEV AS

-- Synthetic-only DEV preview; it does not demonstrate real address mapping.
-- Recheck the live Account and test marker before dispatch.
WITH SOURCE AS (
    SELECT
        ID AS RE_CONSTITUENT_ADDRESS_ID,
        TRIM(CONSTITUENT_ID) AS RE_CONSTITUENT_ID,
        ADDRESS_ID,
        TRY_TO_DATE(LEFT(TRIM(DATE_TO), 10)) AS END_DATE,
        COUNT(*) OVER () AS SOURCE_ROWS
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTADDRESSES
    WHERE ID = 8478
),
ADDRESS_IDS AS (
    SELECT ID, COUNT(*) AS ADDRESS_ROWS
    FROM RAW.RAISERS_EDGE.VW_ODS_T_ADDRESSES
    WHERE ID IN (SELECT ADDRESS_ID FROM SOURCE)
    GROUP BY ID
),
RE_PARTY AS (
    SELECT
        TRIM(X.SOURCE_RECORD_ID) AS RE_CONSTITUENT_ID,
        COUNT(DISTINCT X.GOLDEN_RECORD_ID) AS GOLDEN_RECORDS,
        MIN(X.GOLDEN_RECORD_ID) AS GOLDEN_RECORD_ID,
        COUNT_IF(G.GOLDEN_RECORD_ID IS NULL OR G.IS_GDPR_SUPPRESSED IS NULL)
            AS UNKNOWN_PRIVACY_ROWS,
        COUNT_IF(G.IS_GDPR_SUPPRESSED = TRUE) AS SUPPRESSED_ROWS,
        COUNT(DISTINCT LOWER(NULLIF(TRIM(G.D365_CONTACT_ID), ''))) AS CONTACT_IDS,
        COUNT(DISTINCT LOWER(NULLIF(TRIM(G.D365_ACCOUNT_ID), ''))) AS ACCOUNT_IDS,
        MIN(LOWER(NULLIF(TRIM(G.D365_ACCOUNT_ID), ''))) AS ACCOUNT_ID
    FROM MDM_DB.GOLD.XREF X
    LEFT JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS G
        ON G.GOLDEN_RECORD_ID = X.GOLDEN_RECORD_ID
    WHERE X.SOURCE_SYSTEM = 'RAISERS_EDGE'
      AND TRIM(X.SOURCE_RECORD_ID) IN (SELECT RE_CONSTITUENT_ID FROM SOURCE)
    GROUP BY TRIM(X.SOURCE_RECORD_ID)
),
DYNAMICS_PARTY AS (
    SELECT
        GOLDEN_RECORD_ID,
        COUNT(DISTINCT CASE WHEN STANDARDISED_ID LIKE 'D365-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), '')) END) AS CONTACT_IDS,
        COUNT(DISTINCT CASE WHEN STANDARDISED_ID LIKE 'D365C-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), '')) END) AS ACCOUNT_IDS,
        MIN(CASE WHEN STANDARDISED_ID LIKE 'D365C-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), '')) END) AS ACCOUNT_ID
    FROM MDM_DB.GOLD.XREF
    WHERE SOURCE_SYSTEM = 'DYNAMICS'
      AND GOLDEN_RECORD_ID IN (SELECT GOLDEN_RECORD_ID FROM RE_PARTY)
    GROUP BY GOLDEN_RECORD_ID
)
SELECT
    S.RE_CONSTITUENT_ADDRESS_ID,
    P.ACCOUNT_ID AS D365_ACCOUNT_ID,
    FALSE AS PREVIEW_DISPATCH_ALLOWED,
    OBJECT_CONSTRUCT(
        'mha_name', 'TEST-ADDRESSCHANGE-8478',
        'mha_address_line1', 'SYNTHETIC TEST ADDRESS 8478',
        'mha_partyid_account@odata.bind', '/accounts(' || P.ACCOUNT_ID || ')'
    ) AS DRAFT_PAYLOAD
FROM SOURCE S
JOIN ADDRESS_IDS A ON A.ID = S.ADDRESS_ID AND A.ADDRESS_ROWS = 1
JOIN RE_PARTY P ON P.RE_CONSTITUENT_ID = S.RE_CONSTITUENT_ID
JOIN DYNAMICS_PARTY D ON D.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
WHERE S.SOURCE_ROWS = 1
  AND S.END_DATE < CURRENT_DATE()
  AND P.GOLDEN_RECORDS = 1
  AND P.UNKNOWN_PRIVACY_ROWS = 0
  AND P.SUPPRESSED_ROWS = 0
  AND P.CONTACT_IDS = 0 AND P.ACCOUNT_IDS = 1
  AND D.CONTACT_IDS = 0 AND D.ACCOUNT_IDS = 1
  AND D.ACCOUNT_ID = P.ACCOUNT_ID
  AND P.ACCOUNT_ID = 'e9054cfe-3359-f111-a825-6045bd0f7c7f'
  AND NOT EXISTS (
      SELECT 1 FROM MDM_DB.GOLD.XREF X
      WHERE X.SOURCE_SYSTEM = 'DYNAMICS'
        AND X.GOLDEN_RECORD_ID IN ('ADDRESSCHANGE:8478', 'ADDRESSCHANGE_TEST:8478')
  )
  AND NOT EXISTS (
      SELECT 1 FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE S
      WHERE S.GOLDEN_RECORD_ID IN ('ADDRESSCHANGE:8478', 'ADDRESSCHANGE_TEST:8478')
  )
  AND NOT EXISTS (
      SELECT 1 FROM AUDIT_DB.MONITORING.ADDRESSCHANGE_PILOT_TRACKING_DEV T
      WHERE T.TEST_KEY = 'ADDRESSCHANGE_TEST:8478'
  );
