CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_ADDRESSCHANGE_PILOT_REQUESTS_DEV AS

-- One synthetic DEV test, isolated from the real address identity.
-- Do not dispatch until the isolated tracking route is deployed and verified.
-- Recheck live duplicates and the Account; the guards are not atomic.
WITH PILOT AS (
    SELECT
        'ADDRESSCHANGE_TEST:8478' AS GOLDEN_RECORD_ID,
        DRAFT_PAYLOAD AS REQUEST_BODY
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_ADDRESSCHANGE_PILOT_PREVIEW_DEV
    WHERE RE_CONSTITUENT_ADDRESS_ID = 8478
      AND D365_ACCOUNT_ID = 'e9054cfe-3359-f111-a825-6045bd0f7c7f'
      AND ARRAY_SIZE(OBJECT_KEYS(DRAFT_PAYLOAD)) = 3
      AND DRAFT_PAYLOAD:"mha_name"::VARCHAR = 'TEST-ADDRESSCHANGE-8478'
      AND DRAFT_PAYLOAD:"mha_address_line1"::VARCHAR = 'SYNTHETIC TEST ADDRESS 8478'
      AND DRAFT_PAYLOAD:"mha_partyid_account@odata.bind"::VARCHAR =
          '/accounts(e9054cfe-3359-f111-a825-6045bd0f7c7f)'
)
SELECT
    'D365_ADDRESSCHANGE_PILOT' AS PIPELINE_ID,
    M.SOURCE_INSTANCE,
    'ADDRESSCHANGE_TEST' AS ENTITY_ID,
    P.GOLDEN_RECORD_ID,
    CAST(NULL AS VARCHAR) AS TARGET_GUID,
    'POST' AS HTTP_METHOD,
    M.API_BASE_URL || '/mha_addresschanges' AS REQUEST_URL,
    P.REQUEST_BODY,
    M.AUTH_METHOD,
    M.AUTH_CONFIG,
    MD5(TO_VARCHAR(P.REQUEST_BODY)) AS PAYLOAD_MD5
FROM AUDIT_DB.CONFIG.PIPELINE_METADATA AS M
CROSS JOIN PILOT AS P
WHERE M.PIPELINE_ID = 'D365_WRITEBACK'
  AND M.SOURCE_INSTANCE = 'SNOWFLAKE_DEV'
  AND M.ENTITY_ID = 'CAMPAIGN'
  AND M.API_BASE_URL = 'https://nasdatamig.crm11.dynamics.com/api/data/v9.2'
  AND NOT EXISTS (
      SELECT 1 FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE S
      WHERE S.GOLDEN_RECORD_ID IN ('ADDRESSCHANGE:8478', 'ADDRESSCHANGE_TEST:8478')
  )
  AND NOT EXISTS (
      SELECT 1 FROM MDM_DB.GOLD.XREF X
      WHERE X.SOURCE_SYSTEM = 'DYNAMICS'
        AND X.GOLDEN_RECORD_ID IN ('ADDRESSCHANGE:8478', 'ADDRESSCHANGE_TEST:8478')
  )
  AND NOT EXISTS (
      SELECT 1 FROM AUDIT_DB.MONITORING.ADDRESSCHANGE_PILOT_TRACKING_DEV T
      WHERE T.TEST_KEY = 'ADDRESSCHANGE_TEST:8478'
  )
QUALIFY COUNT(*) OVER (PARTITION BY P.GOLDEN_RECORD_ID) = 1;
