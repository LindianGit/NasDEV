CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_CANVASSER_PILOT_PREVIEW_DEV AS

-- This pair is a provisional technical test, not a confirmed canvassing assignment.
WITH SOURCE_RELATIONSHIP AS (
    SELECT
        ID AS RE_RELATIONSHIP_ID,
        TO_VARCHAR(CONSTITUENT_ID) AS CONSTITUENT_ID,
        TO_VARCHAR(RELATION_CONSTITUENT_ID) AS RELATED_CONSTITUENT_ID,
        COUNT(*) OVER () AS SOURCE_MATCHES
    FROM RAW.RAISERS_EDGE.VW_ODS_T_RELATIONSHIPS
    WHERE ID = 189986
),

CONSTITUENTS AS (
    SELECT
        TO_VARCHAR(CONSTITUENT_ID) AS CONSTITUENT_ID,
        COUNT(*) AS SOURCE_MATCHES,
        COUNT_IF(ISCANVASSER = TRUE) AS CANVASSER_MATCHES,
        COUNT_IF(ISCANVASSER = FALSE) AS NON_CANVASSER_MATCHES
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENT
    WHERE TO_VARCHAR(CONSTITUENT_ID) IN ('395086', '672036')
    GROUP BY TO_VARCHAR(CONSTITUENT_ID)
),

RE_PARTY AS (
    SELECT
        TRIM(SOURCE_RECORD_ID) AS RE_CONSTITUENT_ID,
        COUNT(DISTINCT GOLDEN_RECORD_ID) AS GOLDEN_RECORDS,
        MIN(GOLDEN_RECORD_ID) AS GOLDEN_RECORD_ID
    FROM MDM_DB.GOLD.XREF
    WHERE SOURCE_SYSTEM = 'RAISERS_EDGE'
      AND TRIM(SOURCE_RECORD_ID) IN ('395086', '672036')
    GROUP BY TRIM(SOURCE_RECORD_ID)
),

CUSTOMER_IDS AS (
    SELECT
        GOLDEN_RECORD_ID,
        COUNT(DISTINCT CASE
            WHEN STANDARDISED_ID LIKE 'D365-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), ''))
        END) AS CONTACT_IDS,
        MIN(CASE
            WHEN STANDARDISED_ID LIKE 'D365-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), ''))
        END) AS CONTACT_ID,
        COUNT(DISTINCT CASE
            WHEN STANDARDISED_ID LIKE 'D365C-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), ''))
        END) AS ACCOUNT_IDS
    FROM MDM_DB.GOLD.XREF
    WHERE SOURCE_SYSTEM = 'DYNAMICS'
    GROUP BY GOLDEN_RECORD_ID
),

PILOT AS (
    SELECT
        R.*,
        C1.SOURCE_MATCHES AS CANVASSER_SOURCE_MATCHES,
        C1.CANVASSER_MATCHES,
        C2.SOURCE_MATCHES AS CUSTOMER_SOURCE_MATCHES,
        C2.NON_CANVASSER_MATCHES,
        P1.GOLDEN_RECORDS AS CANVASSER_GOLDEN_RECORDS,
        P2.GOLDEN_RECORDS AS CUSTOMER_GOLDEN_RECORDS,
        G1.IS_GDPR_SUPPRESSED AS CANVASSER_SUPPRESSED,
        G2.IS_GDPR_SUPPRESSED AS CUSTOMER_SUPPRESSED,
        LOWER(NULLIF(TRIM(G2.D365_CONTACT_ID), '')) AS EXPOSED_CONTACT_ID,
        LOWER(NULLIF(TRIM(G2.D365_ACCOUNT_ID), '')) AS EXPOSED_ACCOUNT_ID,
        D.CONTACT_IDS,
        D.CONTACT_ID,
        D.ACCOUNT_IDS,
        COUNT(*) OVER () AS JOIN_MATCHES
    FROM SOURCE_RELATIONSHIP AS R
    LEFT JOIN CONSTITUENTS AS C1 ON C1.CONSTITUENT_ID = '395086'
    LEFT JOIN CONSTITUENTS AS C2 ON C2.CONSTITUENT_ID = '672036'
    LEFT JOIN RE_PARTY AS P1 ON P1.RE_CONSTITUENT_ID = C1.CONSTITUENT_ID
    LEFT JOIN RE_PARTY AS P2 ON P2.RE_CONSTITUENT_ID = C2.CONSTITUENT_ID
    LEFT JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS AS G1
        ON G1.GOLDEN_RECORD_ID = P1.GOLDEN_RECORD_ID
    LEFT JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS AS G2
        ON G2.GOLDEN_RECORD_ID = P2.GOLDEN_RECORD_ID
    LEFT JOIN CUSTOMER_IDS AS D ON D.GOLDEN_RECORD_ID = P2.GOLDEN_RECORD_ID
)

SELECT
    RE_RELATIONSHIP_ID,
    CONSTITUENT_ID,
    RELATED_CONSTITUENT_ID,
    '395086' AS RE_CANVASSER_ID,
    '672036' AS RE_CUSTOMER_ID,
    '9b050b25-7103-ed11-82e5-000d3a0cbb18' AS D365_USER_ID,
    CONTACT_ID AS D365_CONTACT_ID,
    CASE
        WHEN SOURCE_MATCHES <> 1 OR JOIN_MATCHES <> 1 THEN 'HOLD_SOURCE_NOT_UNIQUE'
        WHEN NOT (
            (COALESCE(CONSTITUENT_ID, '') = '395086' AND COALESCE(RELATED_CONSTITUENT_ID, '') = '672036')
            OR (COALESCE(CONSTITUENT_ID, '') = '672036' AND COALESCE(RELATED_CONSTITUENT_ID, '') = '395086')
        ) THEN 'HOLD_RELATIONSHIP_CHANGED'
        WHEN COALESCE(CANVASSER_SOURCE_MATCHES, 0) <> 1
            OR COALESCE(CANVASSER_MATCHES, 0) <> 1
            OR COALESCE(CUSTOMER_SOURCE_MATCHES, 0) <> 1
            OR COALESCE(NON_CANVASSER_MATCHES, 0) <> 1
            THEN 'HOLD_CONSTITUENT_FLAGS'
        WHEN COALESCE(CANVASSER_GOLDEN_RECORDS, 0) <> 1
            OR COALESCE(CUSTOMER_GOLDEN_RECORDS, 0) <> 1
            THEN 'HOLD_GOLDEN_RECORD_UNRESOLVED'
        WHEN CANVASSER_SUPPRESSED IS NULL OR CANVASSER_SUPPRESSED
            OR CUSTOMER_SUPPRESSED IS NULL OR CUSTOMER_SUPPRESSED
            THEN 'HOLD_PRIVACY_REVIEW'
        WHEN COALESCE(CONTACT_IDS, 0) <> 1 OR COALESCE(ACCOUNT_IDS, 0) <> 0
            OR EXPOSED_ACCOUNT_ID IS NOT NULL
            THEN 'HOLD_CUSTOMER_UNRESOLVED'
        WHEN CONTACT_ID <> 'f2df31e4-9be0-f111-84ea-70a8a575b5fc'
            OR COALESCE(EXPOSED_CONTACT_ID, '') <> CONTACT_ID
            THEN 'HOLD_CONTACT_CHANGED'
        ELSE 'PILOT_CANDIDATE'
    END AS PREVIEW_STATUS,
    FALSE AS PREVIEW_DISPATCH_ALLOWED,
    OBJECT_CONSTRUCT(
        'mhnas_Canvasser@odata.bind',
            '/systemusers(9b050b25-7103-ed11-82e5-000d3a0cbb18)',
        'mhnas_Customer_contact@odata.bind',
            IFF(CONTACT_ID IS NOT NULL, '/contacts(' || CONTACT_ID || ')', NULL)
    ) AS DRAFT_PAYLOAD
FROM PILOT;
