CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_CONSENT_PILOT_PREVIEW_DEV AS

-- Fixed DEV opt-out only. Any change to the reviewed preference history holds
-- the pilot. Business mapping gates remain open; this is not a full-load view.
WITH ANCHOR AS (
    SELECT MIN(TRIM(CONSTITUENT_ID)) AS RE_CONSTITUENT_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTATTRIBUTES
    WHERE ID = 2273445
    HAVING COUNT(*) = 1
),
EXPECTED_HISTORY AS (
    SELECT COLUMN1 AS ID, COLUMN2 AS ATTRIBUTE_NAME, COLUMN3 AS ATTRIBUTE_VALUE
    FROM VALUES
        (2273444, 'Email Preferences', 'No Political Campaigns'),
        (2273448, 'Email Preferences', 'No Donations'),
        (2273441, 'Postal Preferences', 'No Political Campaigns'),
        (2273445, 'Postal Preferences', 'No Donations'),
        (2273443, 'SMS Preferences', 'No Political Campaigns'),
        (2273447, 'SMS Preferences', 'No Donations'),
        (2273442, 'Telephone Preferences', 'No Political Campaigns'),
        (2273446, 'Telephone Preferences', 'No Donations')
),
HISTORY AS (
    SELECT
        C.RE_CONSTITUENT_ID,
        COUNT(*) AS SOURCE_ROWS,
        COUNT(DISTINCT A.ID) AS DISTINCT_IDS,
        COUNT_IF(
            E.ID IS NOT NULL
            AND TRY_TO_DATE(LEFT(TRIM(A.ATTRIBUTEDATE), 10)) = DATE '2012-08-23'
        ) AS EXPECTED_ROWS
    FROM ANCHOR C
    JOIN RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTATTRIBUTES A
        ON TRIM(A.CONSTITUENT_ID) = C.RE_CONSTITUENT_ID
    LEFT JOIN EXPECTED_HISTORY E
        ON E.ID = A.ID
       AND E.ATTRIBUTE_NAME = A.ATTRIBUTENAME
       AND E.ATTRIBUTE_VALUE = TRIM(A.ATTRIBUTEVALUE)
    WHERE A.ATTRIBUTENAME IN (
        'Email Preferences', 'Postal Preferences',
        'SMS Preferences', 'Telephone Preferences', 'Contact Exclusions'
    )
    GROUP BY C.RE_CONSTITUENT_ID
),
RE_PARTY AS (
    SELECT
        TRIM(X.SOURCE_RECORD_ID) AS RE_CONSTITUENT_ID,
        COUNT(DISTINCT X.GOLDEN_RECORD_ID) AS GOLDEN_RECORDS,
        MIN(X.GOLDEN_RECORD_ID) AS GOLDEN_RECORD_ID,
        COUNT_IF(G.GOLDEN_RECORD_ID IS NULL OR G.IS_GDPR_SUPPRESSED IS NULL)
            AS UNKNOWN_PRIVACY_ROWS,
        COUNT_IF(G.IS_GDPR_SUPPRESSED = TRUE) AS SUPPRESSED_ROWS,
        COUNT(DISTINCT LOWER(NULLIF(TRIM(G.D365_CONTACT_ID), ''))) AS CONTACT_IDS,
        COUNT(DISTINCT LOWER(NULLIF(TRIM(G.D365_ACCOUNT_ID), ''))) AS ACCOUNT_IDS,
        MIN(LOWER(NULLIF(TRIM(G.D365_CONTACT_ID), ''))) AS CONTACT_ID
    FROM MDM_DB.GOLD.XREF X
    LEFT JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS G
        ON G.GOLDEN_RECORD_ID = X.GOLDEN_RECORD_ID
    WHERE X.SOURCE_SYSTEM = 'RAISERS_EDGE'
      AND TRIM(X.SOURCE_RECORD_ID) IN (SELECT RE_CONSTITUENT_ID FROM ANCHOR)
    GROUP BY TRIM(X.SOURCE_RECORD_ID)
),
DYNAMICS_PARTY AS (
    SELECT
        GOLDEN_RECORD_ID,
        COUNT(DISTINCT CASE WHEN STANDARDISED_ID LIKE 'D365-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), '')) END) AS CONTACT_IDS,
        MIN(CASE WHEN STANDARDISED_ID LIKE 'D365-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), '')) END) AS CONTACT_ID,
        COUNT(DISTINCT CASE WHEN STANDARDISED_ID LIKE 'D365C-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), '')) END) AS ACCOUNT_IDS
    FROM MDM_DB.GOLD.XREF
    WHERE SOURCE_SYSTEM = 'DYNAMICS'
      AND GOLDEN_RECORD_ID = 'GR-205748389'
    GROUP BY GOLDEN_RECORD_ID
),
CONSENT_TYPE AS (
    SELECT MIN(LOWER(TRIM(MHA_CONSENTTYPEID))) AS TYPE_ID
    FROM RAW.DYNAMICS.VW_ODS_MHA_CONSENTTYPES
    WHERE UPPER(TRIM(MHA_NAME)) = 'DONATIONS'
    HAVING COUNT(*) = 1
)
SELECT
    2273445 AS SAMPLE_ATTRIBUTE_ID,
    P.CONTACT_ID AS D365_CONTACT_ID,
    T.TYPE_ID AS D365_CONSENT_TYPE_ID,
    FALSE AS PREVIEW_DISPATCH_ALLOWED,
    OBJECT_CONSTRUCT(
        'mha_consentid', '9d1fdf0d-00cd-40a0-a40d-8e06e6053af8',
        'mha_name', 'TEST-CONSENT-2273445',
        'mha_consentfor_contact@odata.bind', '/contacts(' || P.CONTACT_ID || ')',
        'mha_consenttypeid@odata.bind', '/mha_consenttypes(' || T.TYPE_ID || ')',
        'mha_email', 862940001,
        'mha_post', 862940001,
        'mha_sms', 862940001,
        'mha_telephone', 862940001
    ) AS DRAFT_PAYLOAD
FROM HISTORY H
JOIN RE_PARTY P ON P.RE_CONSTITUENT_ID = H.RE_CONSTITUENT_ID
JOIN DYNAMICS_PARTY D ON D.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
CROSS JOIN CONSENT_TYPE T
WHERE H.SOURCE_ROWS = 8 AND H.DISTINCT_IDS = 8 AND H.EXPECTED_ROWS = 8
  AND P.GOLDEN_RECORDS = 1
  AND P.GOLDEN_RECORD_ID = 'GR-205748389'
  AND P.UNKNOWN_PRIVACY_ROWS = 0 AND P.SUPPRESSED_ROWS = 0
  AND P.CONTACT_IDS = 1 AND P.ACCOUNT_IDS = 0
  AND D.CONTACT_IDS = 1 AND D.ACCOUNT_IDS = 0
  AND D.CONTACT_ID = P.CONTACT_ID
  AND P.CONTACT_ID = '1bcce781-9ee0-f111-84ea-002248425074'
  AND T.TYPE_ID = 'b6825be3-c160-f111-a825-7ced8d9cafea';
