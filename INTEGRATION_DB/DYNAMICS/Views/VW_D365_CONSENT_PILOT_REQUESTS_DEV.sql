CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_CONSENT_PILOT_REQUESTS_DEV AS

-- One approved DEV opt-out; recheck live Party/type and existing consents.
-- Reconcile uncertain outcomes, never blindly retry. Guards are not atomic.
WITH PILOT AS (
    SELECT
        'CONSENT_TEST:2273445' AS GOLDEN_RECORD_ID,
        DRAFT_PAYLOAD AS REQUEST_BODY
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_CONSENT_PILOT_PREVIEW_DEV
    WHERE SAMPLE_ATTRIBUTE_ID = 2273445
      AND D365_CONTACT_ID = '1bcce781-9ee0-f111-84ea-002248425074'
      AND D365_CONSENT_TYPE_ID = 'b6825be3-c160-f111-a825-7ced8d9cafea'
      AND ARRAY_SIZE(OBJECT_KEYS(DRAFT_PAYLOAD)) = 8
      AND DRAFT_PAYLOAD:"mha_consentid"::VARCHAR = '9d1fdf0d-00cd-40a0-a40d-8e06e6053af8'
      AND DRAFT_PAYLOAD:"mha_name"::VARCHAR = 'TEST-CONSENT-2273445'
      AND DRAFT_PAYLOAD:"mha_consentfor_contact@odata.bind"::VARCHAR =
          '/contacts(1bcce781-9ee0-f111-84ea-002248425074)'
      AND DRAFT_PAYLOAD:"mha_consenttypeid@odata.bind"::VARCHAR =
          '/mha_consenttypes(b6825be3-c160-f111-a825-7ced8d9cafea)'
      AND DRAFT_PAYLOAD:"mha_email"::NUMBER = 862940001
      AND DRAFT_PAYLOAD:"mha_post"::NUMBER = 862940001
      AND DRAFT_PAYLOAD:"mha_sms"::NUMBER = 862940001
      AND DRAFT_PAYLOAD:"mha_telephone"::NUMBER = 862940001
)
SELECT
    'D365_CONSENT_PILOT' AS PIPELINE_ID,
    M.SOURCE_INSTANCE,
    'CONSENT_TEST' AS ENTITY_ID,
    P.GOLDEN_RECORD_ID,
    CAST(NULL AS VARCHAR) AS TARGET_GUID,
    'POST' AS HTTP_METHOD,
    M.API_BASE_URL || '/mha_consents' AS REQUEST_URL,
    P.REQUEST_BODY,
    M.AUTH_METHOD,
    M.AUTH_CONFIG,
    MD5(TO_VARCHAR(P.REQUEST_BODY)) AS PAYLOAD_MD5
FROM AUDIT_DB.CONFIG.PIPELINE_METADATA M
CROSS JOIN PILOT P
WHERE M.PIPELINE_ID = 'D365_WRITEBACK'
  AND M.SOURCE_INSTANCE = 'SNOWFLAKE_DEV'
  AND M.ENTITY_ID = 'CAMPAIGN'
  AND M.API_BASE_URL = 'https://nasdatamig.crm11.dynamics.com/api/data/v9.2'
  AND NOT EXISTS (
      SELECT 1 FROM AUDIT_DB.MONITORING.CONSENT_PILOT_TRACKING_DEV
      WHERE TEST_KEY = P.GOLDEN_RECORD_ID
         OR LOWER(TRIM(D365_GUID)) = '9d1fdf0d-00cd-40a0-a40d-8e06e6053af8'
  )
  AND NOT EXISTS (
      SELECT 1 FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE
      WHERE GOLDEN_RECORD_ID IN ('CONSENT_TEST:2273445', 'CONSENT:2273445')
  )
  AND NOT EXISTS (
      SELECT 1 FROM MDM_DB.GOLD.XREF
      WHERE SOURCE_SYSTEM = 'DYNAMICS'
        AND (
            GOLDEN_RECORD_ID IN ('CONSENT_TEST:2273445', 'CONSENT:2273445')
            OR LOWER(TRIM(SOURCE_RECORD_ID)) = '9d1fdf0d-00cd-40a0-a40d-8e06e6053af8'
        )
  )
QUALIFY COUNT(*) OVER (PARTITION BY P.GOLDEN_RECORD_ID) = 1;

GRANT SELECT ON VIEW INTEGRATION_DB.DYNAMICS.VW_D365_CONSENT_PILOT_PREVIEW_DEV
TO ROLE R_NAS_ETL_DEV;
GRANT SELECT ON VIEW INTEGRATION_DB.DYNAMICS.VW_D365_CONSENT_PILOT_REQUESTS_DEV
TO ROLE R_NAS_ETL_DEV;
