	GOLDEN_RECORD_ID,
	ACTION,
	D365_CONTACT_ID,
	FIRSTNAME,
	LASTNAME,
	MIDDLENAME,
	MHA_SOURCEID,
	NAS_RECONSTITUENTCODE,
	NAS_RESYSTEMRECORDID,
	MSNFP_CONSTITUENTNUMBER,
	BIRTHDATE,
	MSNFP_DECEASED,
	GENDERCODE,
	MHA_TAXAUTHORITYINVALID,
	OVERRIDDENCREATEDON,
	ADDRESS1_LINE1,
	ADDRESS1_LINE2,
	ADDRESS1_LINE3,
	ADDRESS1_CITY,
	ADDRESS1_STATEORPROVINCE,
	ADDRESS1_COUNTRY,
	ADDRESS1_POSTALCODE,
	ADDRESS1_LATITUDE,
	ADDRESS1_LONGITUDE,
	ADDRESS1_UPSZONE,
	ADDRESS1_ADDRESSTYPECODE,
	ADDRESS2_LINE1,
	ADDRESS2_LINE2,
	ADDRESS2_LINE3,
	ADDRESS2_CITY,
	ADDRESS2_STATEORPROVINCE,
	ADDRESS2_COUNTRY,
	ADDRESS2_POSTALCODE,
