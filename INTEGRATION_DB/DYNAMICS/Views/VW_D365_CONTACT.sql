	TELEPHONE2,
	WEBSITEURL,
	MHA_ISOCOUNTRYID,
	NAS_COUNTRYID,
	PAYLOAD
) as
WITH WINNING_SOURCE_CTE AS (
    -- Most recently updated source per golden record, matches
    -- VW_HS_CONSTITUENT_ENRICHED's WINNING_SOURCE exactly (no secondary
    -- tiebreak)
    SELECT
        X.GOLDEN_RECORD_ID,
        X.SOURCE_SYSTEM,
        X.SOURCE_RECORD_ID,
        X.STANDARDISED_ID,
        ROW_NUMBER() OVER (
            PARTITION BY X.GOLDEN_RECORD_ID
            ORDER BY SR.LAST_UPDATED DESC NULLS LAST
        ) AS RN
    FROM MDM_DB.GOLD.XREF AS X
    INNER JOIN MDM_DB.STAGING.STANDARDISED_RECORDS AS SR
        ON
            X.SOURCE_SYSTEM = SR.SOURCE_SYSTEM
            AND X.SOURCE_RECORD_ID = SR.SOURCE_RECORD_ID
            AND SR._IS_ACTIVE = TRUE
    INNER JOIN MDM_DB.GOLD.GOLDEN_RECORDS AS GR
        ON
            X.GOLDEN_RECORD_ID = GR.GOLDEN_RECORD_ID
            AND GR._IS_ACTIVE = TRUE
),

ADDRESS_RANKED_CTE AS (
    -- Address1 = PREFERRED = -1 row (every constituent with an address
    -- has exactly one, confirmed against live data); remaining rows
    -- ranked by DATE_ADDED DESC, ID DESC
    SELECT
        CA.CONSTITUENT_ID,
        CA.ADDRESSTYPEDESCRIPTION,
        A.ADDRESSLINE1,
        A.ADDRESSLINE2,
        A.ADDRESSLINE3,
        A.ADDRESSLINE4,
        A.CITY,
        A.COUNTYDESCRIPTION,
        A.COUNTRYDESCRIPTION,
        A.POSTCODE,
        A.LATITUDE,
        A.LONGITUDE,
        A.DPS,
        ROW_NUMBER() OVER (
            PARTITION BY CA.CONSTITUENT_ID
            ORDER BY
                IFF(CA.PREFERRED = -1, 0, 1),
                CA.DATE_ADDED DESC,
                CA.ID DESC
        ) AS ADDRESS_RANK
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTADDRESSES AS CA
    LEFT JOIN RAW.RAISERS_EDGE.VW_ODS_T_ADDRESSES AS A
        ON CA.ADDRESS_ID = A.ID
),

ADDRESS1_CTE AS (
    SELECT * FROM ADDRESS_RANKED_CTE
    WHERE ADDRESS_RANK = 1
),

ADDRESS2_CTE AS (
    SELECT * FROM ADDRESS_RANKED_CTE
    WHERE ADDRESS_RANK = 2
),

ADDRESS3_CTE AS (
    SELECT * FROM ADDRESS_RANKED_CTE
    WHERE ADDRESS_RANK = 3
),

MAIDEN_NAME_CTE AS (
    SELECT
        CONSTITUENT_ID,
        ALIASNAME AS MAIDEN_NAME
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTALIASES
    WHERE ALIASTYPEDESCRIPTION = 'Maiden Name'
    QUALIFY
        ROW_NUMBER() OVER (PARTITION BY CONSTITUENT_ID ORDER BY ID DESC)
        = 1
),

NICKNAME_CTE AS (
    SELECT
        CONSTITUENT_ID,
        ALIASNAME AS NICKNAME
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTALIASES
    WHERE ALIASTYPEDESCRIPTION = 'Known Name'
    QUALIFY
        ROW_NUMBER() OVER (PARTITION BY CONSTITUENT_ID ORDER BY ID DESC)
        = 1
),

FACEBOOK_CTE AS (
    SELECT
        CONSTITUENT_ID,
        PHONENUMBER AS FACEBOOK_PROFILE
    FROM RAW.RAISERS_EDGE.VW_ODS_T_PHONENUMBERS
    WHERE PHONETYPEDESCRIPTION = 'Facebook' AND ISACTIVE = 1
    QUALIFY
        ROW_NUMBER()
            OVER (PARTITION BY CONSTITUENT_ID ORDER BY ISPRIMARY DESC, ID DESC)
        = 1
),

INSTAGRAM_CTE AS (
    SELECT
        CONSTITUENT_ID,
        PHONENUMBER AS INSTAGRAM_PROFILE
    FROM RAW.RAISERS_EDGE.VW_ODS_T_PHONENUMBERS
    WHERE PHONETYPEDESCRIPTION = 'Instagram' AND ISACTIVE = 1
    QUALIFY
        ROW_NUMBER()
            OVER (PARTITION BY CONSTITUENT_ID ORDER BY ISPRIMARY DESC, ID DESC)
        = 1
),

LINKEDIN_CTE AS (
    SELECT
        CONSTITUENT_ID,
        PHONENUMBER AS LINKEDIN_PROFILE
    FROM RAW.RAISERS_EDGE.VW_ODS_T_PHONENUMBERS
    WHERE PHONETYPEDESCRIPTION = 'LinkedIn' AND ISACTIVE = 1
    QUALIFY
        ROW_NUMBER()
            OVER (PARTITION BY CONSTITUENT_ID ORDER BY ISPRIMARY DESC, ID DESC)
        = 1
),

TWITTER_CTE AS (
    SELECT
        CONSTITUENT_ID,
        PHONENUMBER AS TWITTER_PROFILE
    FROM RAW.RAISERS_EDGE.VW_ODS_T_PHONENUMBERS
    WHERE PHONETYPEDESCRIPTION = 'Twitter' AND ISACTIVE = 1
    QUALIFY
        ROW_NUMBER()
            OVER (PARTITION BY CONSTITUENT_ID ORDER BY ISPRIMARY DESC, ID DESC)
        = 1
),

-- Email selection rule is unconfirmed
EMAIL2_CTE AS (
    SELECT
        CONSTITUENTID,
        EMAILADDRESS AS EMAIL2
    FROM RAW.RAISERS_EDGE.VW_ODS_T_EMAILADDRESSES
    WHERE TYPEDESCRIPTION = 'Work Email' AND ISACTIVE = 1
    QUALIFY
        ROW_NUMBER()
            OVER (PARTITION BY CONSTITUENTID ORDER BY ISPRIMARY DESC, ID DESC)
        = 1
),

-- EMailAddress3's source is unknown
-- no CTE, resolves NULL

-- WebSiteUrl: ODS_T_PHONENUMBERS truncates URLs at 20 chars, use
-- WEBADDRESSES.ADDRESS instead
WEBSITE_CTE AS (
    SELECT
        CONSTITUENTID,
        ADDRESS AS WEBSITE_URL
    FROM RAW.RAISERS_EDGE.VW_ODS_T_WEBADDRESSES
    WHERE TYPEDESCRIPTION = 'Website' AND ISACTIVE = 1
    QUALIFY ROW_NUMBER() OVER (PARTITION BY CONSTITUENTID ORDER BY ID DESC) = 1
)

SELECT
    GR.GOLDEN_RECORD_ID,

    -- Create/update decision: known D365 GUID means PATCH, else POST
    IFF(IDS.D365_CONTACT_ID IS NULL, 'CREATE', 'UPDATE') AS ACTION,
    IDS.D365_CONTACT_ID,

    NULLIF(GR.FIRST_NAME, '') AS FIRSTNAME,
    NULLIF(GR.LAST_NAME, '') AS LASTNAME,
    NULLIF(GR.MIDDLE_NAME, '') AS MIDDLENAME,

    RE_RAW.CONSTITUENT_ID AS MHA_SOURCEID,
    RE_RAW.CONSTITUENT_ID AS NAS_RECONSTITUENTCODE,
    RE_RAW.SYSTEMRECORDID AS NAS_RESYSTEMRECORDID,

    -- Alternate key: sent on create only, never on update -- whether this
    -- field even accepts writes is still unconfirmed
    IFF(
        IDS.D365_CONTACT_ID IS NULL,
        RE_RAW.CONSTITUENT_ID,
        NULL
    ) AS MSNFP_CONSTITUENTNUMBER,

    TRY_TO_DATE(GR.DATE_OF_BIRTH) AS BIRTHDATE,
    GR.DECEASED AS MSNFP_DECEASED,

    -- GenderCode: '?' has no defined Dynamics target, resolves NULL
    CASE GR.GENDER
        WHEN 'M' THEN 1
        WHEN 'F' THEN 2
    END AS GENDERCODE,

    -- Hardcoded: recalculated later by the Gift Aid process
    TRUE AS MHA_TAXAUTHORITYINVALID,

    TRY_TO_TIMESTAMP_NTZ(RE_RAW.DATEADDED) AS OVERRIDDENCREATEDON,

    -- StateCode/StatusCode omitted: no agreed StatusCode value set for
    -- Contact yet, and the two must be sent together or not at all.
    -- CreatedBy omitted: read-only in Dataverse, cannot be written
    -- regardless of mapping status.

    GR.ADDRESS_LINE1 AS ADDRESS1_LINE1,
    GR.ADDRESS_LINE2 AS ADDRESS1_LINE2,
    NULLIF(CONCAT_WS(', ', GR.ADDRESS_LINE3, GR.ADDRESS_LINE4), '')
        AS ADDRESS1_LINE3,
    GR.CITY AS ADDRESS1_CITY,
    GR.COUNTY AS ADDRESS1_STATEORPROVINCE,
    GR.COUNTRY AS ADDRESS1_COUNTRY,
    GR.POSTCODE AS ADDRESS1_POSTALCODE,
    A1.LATITUDE AS ADDRESS1_LATITUDE,
    A1.LONGITUDE AS ADDRESS1_LONGITUDE,
    A1.DPS AS ADDRESS1_UPSZONE,
    -- AddressTypeCode: resolves NULL for most rows, RE's dominant
    -- 'Home' label has no Dynamics equivalent in any slot; only literal
    -- 'Business' matches. Expected, not a bug.
    OPT1.OPTION_VALUE AS ADDRESS1_ADDRESSTYPECODE,

    A2.ADDRESSLINE1 AS ADDRESS2_LINE1,
    A2.ADDRESSLINE2 AS ADDRESS2_LINE2,
    NULLIF(CONCAT_WS(', ', A2.ADDRESSLINE3, A2.ADDRESSLINE4), '')
        AS ADDRESS2_LINE3,
    A2.CITY AS ADDRESS2_CITY,
    A2.COUNTYDESCRIPTION AS ADDRESS2_STATEORPROVINCE,
    A2.COUNTRYDESCRIPTION AS ADDRESS2_COUNTRY,
    A2.POSTCODE AS ADDRESS2_POSTALCODE,
    A2.LATITUDE AS ADDRESS2_LATITUDE,
    A2.LONGITUDE AS ADDRESS2_LONGITUDE,
    A2.DPS AS ADDRESS2_UPSZONE,
    OPT2.OPTION_VALUE AS ADDRESS2_ADDRESSTYPECODE,

    A3.ADDRESSLINE1 AS ADDRESS3_LINE1,
    A3.ADDRESSLINE2 AS ADDRESS3_LINE2,
    NULLIF(CONCAT_WS(', ', A3.ADDRESSLINE3, A3.ADDRESSLINE4), '')
        AS ADDRESS3_LINE3,
    A3.CITY AS ADDRESS3_CITY,
    A3.COUNTYDESCRIPTION AS ADDRESS3_STATEORPROVINCE,
    A3.COUNTRYDESCRIPTION AS ADDRESS3_COUNTRY,
    A3.POSTCODE AS ADDRESS3_POSTALCODE,
    A3.LATITUDE AS ADDRESS3_LATITUDE,
    A3.LONGITUDE AS ADDRESS3_LONGITUDE,
    A3.DPS AS ADDRESS3_UPSZONE,
    OPT3.OPTION_VALUE AS ADDRESS3_ADDRESSTYPECODE,

    MN.MAIDEN_NAME AS MSNFP_MAIDENNAME,
    NN.NICKNAME,

    FB.FACEBOOK_PROFILE AS MSNFP_FACEBOOKPROFILE,
    IG.INSTAGRAM_PROFILE AS MSNFP_INSTAGRAMPROFILE,
    LI.LINKEDIN_PROFILE AS MSNFP_LINKEDIN,
    TW.TWITTER_PROFILE AS MSNFP_TWITTER,

    MT.MHA_TITLEID AS MHA_TITLE,
    -- nas_ContactTitle: degrades to NULL until ingestion lands
    CT.OPTION_VALUE AS NAS_CONTACTTITLE,

    GR.JOB_TITLE AS JOBTITLE,

    GR.EMAIL AS EMAILADDRESS1,
    E2.EMAIL2 AS EMAILADDRESS2,
    NULL AS EMAILADDRESS3,

    GR.MOBILE_PHONE AS MOBILEPHONE,
    GR.WORK_PHONE AS TELEPHONE1,
    GR.HOME_PHONE AS TELEPHONE2,
    WEB.WEBSITE_URL AS WEBSITEURL,

    -- mha_isocountryid/nas_CountryId: via the golden record's survived
    -- country; both target lookup entities have narrow seeded-row
    -- coverage in Dynamics, so a low hit rate here is expected
    ISO.MHA_ISOCOUNTRYID,
    NC.NAS_COUNTRYID,

    -- PAYLOAD: the Dataverse request body, built from the columns
    -- above (lateral alias reference) so it always matches what this
    -- view already exposes.
    OBJECT_CONSTRUCT(
        'firstname', FIRSTNAME,
        'lastname', LASTNAME,
        'middlename', MIDDLENAME,
        'mha_sourceid', MHA_SOURCEID,
        'nas_reconstituentcode', NAS_RECONSTITUENTCODE,
        'nas_resystemrecordid', NAS_RESYSTEMRECORDID,
        -- create-only, double-guarded: redundant with MSNFP_CONSTITUENTNUMBER's
        -- own column-level IFF above, deliberately -- do not simplify away
        'msnfp_constituentnumber',
        IFF(ACTION = 'CREATE', MSNFP_CONSTITUENTNUMBER, NULL),
        'birthdate', BIRTHDATE,
        'msnfp_deceased', MSNFP_DECEASED,
        'gendercode', GENDERCODE,
        'mha_taxauthorityinvalid', MHA_TAXAUTHORITYINVALID,
        -- create-only, double-guarded: redundant with OVERRIDDENCREATEDON's
        -- own column-level IFF above, deliberately -- do not simplify away.
        -- Rebuilt from source rather than the alias: MT/ISO/NC each carry
        -- their own OVERRIDDENCREATEDON column, which makes the bare
        -- alias ambiguous.
        'overriddencreatedon',
        IFF(
            ACTION = 'CREATE',
            IFF(
                IDS.D365_CONTACT_ID IS NULL,
                TRY_TO_TIMESTAMP_NTZ(RE_RAW.DATEADDED),
                NULL
            ),
            NULL
        ),
        'address1_line1', ADDRESS1_LINE1,
        'address1_line2', ADDRESS1_LINE2,
        'address1_line3', ADDRESS1_LINE3,
        'address1_city', ADDRESS1_CITY,
        'address1_stateorprovince', ADDRESS1_STATEORPROVINCE,
        'address1_country', ADDRESS1_COUNTRY,
        'address1_postalcode', ADDRESS1_POSTALCODE,
        'address1_latitude', ADDRESS1_LATITUDE,
        'address1_longitude', ADDRESS1_LONGITUDE,
        'address1_upszone', ADDRESS1_UPSZONE,
        'address1_addresstypecode', ADDRESS1_ADDRESSTYPECODE,
        'address2_line1', ADDRESS2_LINE1,
        'address2_line2', ADDRESS2_LINE2,
        'address2_line3', ADDRESS2_LINE3,
        'address2_city', ADDRESS2_CITY,
        'address2_stateorprovince', ADDRESS2_STATEORPROVINCE,
        'address2_country', ADDRESS2_COUNTRY,
        'address2_postalcode', ADDRESS2_POSTALCODE,
        'address2_latitude', ADDRESS2_LATITUDE,
        'address2_longitude', ADDRESS2_LONGITUDE,
        'address2_upszone', ADDRESS2_UPSZONE,
        'address2_addresstypecode', ADDRESS2_ADDRESSTYPECODE,
        'address3_line1', ADDRESS3_LINE1,
        'address3_line2', ADDRESS3_LINE2,
        'address3_line3', ADDRESS3_LINE3,
        'address3_city', ADDRESS3_CITY,
        'address3_stateorprovince', ADDRESS3_STATEORPROVINCE,
        'address3_country', ADDRESS3_COUNTRY,
        'address3_postalcode', ADDRESS3_POSTALCODE,
        'address3_latitude', ADDRESS3_LATITUDE,
        'address3_longitude', ADDRESS3_LONGITUDE,
        'address3_upszone', ADDRESS3_UPSZONE,
        'address3_addresstypecode', ADDRESS3_ADDRESSTYPECODE,
        'msnfp_maidenname', MSNFP_MAIDENNAME,
        'nickname', NN.NICKNAME,
        'msnfp_facebookprofile', MSNFP_FACEBOOKPROFILE,
        'msnfp_instagramprofile', MSNFP_INSTAGRAMPROFILE,
        'msnfp_linkedin', MSNFP_LINKEDIN,
        'msnfp_twitter', MSNFP_TWITTER,
        -- lookup: navigation property with @odata.bind, never the plain key
        'mha_title@odata.bind', IFF(
            MHA_TITLE IS NOT NULL, '/mha_titles(' || MHA_TITLE || ')', NULL
        ),
        'nas_contacttitle', NAS_CONTACTTITLE,
        'jobtitle', JOBTITLE,
        'emailaddress1', EMAILADDRESS1,
        'emailaddress2', EMAILADDRESS2,
        'emailaddress3', EMAILADDRESS3,
        'mobilephone', MOBILEPHONE,
        'telephone1', TELEPHONE1,
        'telephone2', TELEPHONE2,
        'websiteurl', WEBSITEURL,
        -- lookup: navigation property with @odata.bind, never the plain key
        'mha_isocountryid@odata.bind', IFF(
            ISO.MHA_ISOCOUNTRYID IS NOT NULL,
            '/mha_isocountries(' || ISO.MHA_ISOCOUNTRYID || ')',
            NULL
        ),
        -- lookup: navigation property with @odata.bind, never the plain key
        'nas_countryid@odata.bind', IFF(
            NC.NAS_COUNTRYID IS NOT NULL,
            '/nas_countries(' || NC.NAS_COUNTRYID || ')',
            NULL
        )
    ) AS PAYLOAD

FROM MDM_DB.GOLD.GOLDEN_RECORDS AS GR
INNER JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS AS IDS
    ON GR.GOLDEN_RECORD_ID = IDS.GOLDEN_RECORD_ID
LEFT JOIN RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENT AS RE_RAW
    ON IDS.RE_CONSTITUENT_ID = RE_RAW.CONSTITUENT_ID
LEFT JOIN WINNING_SOURCE_CTE AS WS
    ON
        GR.GOLDEN_RECORD_ID = WS.GOLDEN_RECORD_ID
        AND WS.RN = 1
LEFT JOIN ADDRESS1_CTE AS A1
    ON
        RE_RAW.CONSTITUENT_ID = A1.CONSTITUENT_ID
        AND WS.SOURCE_SYSTEM = 'RAISERS_EDGE'
        AND WS.RN = 1
LEFT JOIN RAW.DYNAMICS.VW_ODS_OPTIONSET_CONTACT_ADDRESS1_ADDRESSTYPECODE AS OPT1
    ON TRIM(UPPER(A1.ADDRESSTYPEDESCRIPTION)) = TRIM(UPPER(OPT1.OPTION_LABEL))
LEFT JOIN ADDRESS2_CTE AS A2
    ON
        RE_RAW.CONSTITUENT_ID = A2.CONSTITUENT_ID
        AND WS.SOURCE_SYSTEM = 'RAISERS_EDGE'
        AND WS.RN = 1
LEFT JOIN RAW.DYNAMICS.VW_ODS_OPTIONSET_CONTACT_ADDRESS2_ADDRESSTYPECODE AS OPT2
    ON TRIM(UPPER(A2.ADDRESSTYPEDESCRIPTION)) = TRIM(UPPER(OPT2.OPTION_LABEL))
LEFT JOIN ADDRESS3_CTE AS A3
    ON
        RE_RAW.CONSTITUENT_ID = A3.CONSTITUENT_ID
        AND WS.SOURCE_SYSTEM = 'RAISERS_EDGE'
        AND WS.RN = 1
LEFT JOIN RAW.DYNAMICS.VW_ODS_OPTIONSET_CONTACT_ADDRESS3_ADDRESSTYPECODE AS OPT3
    ON TRIM(UPPER(A3.ADDRESSTYPEDESCRIPTION)) = TRIM(UPPER(OPT3.OPTION_LABEL))
LEFT JOIN MAIDEN_NAME_CTE AS MN
    ON
        RE_RAW.CONSTITUENT_ID = MN.CONSTITUENT_ID
        AND WS.SOURCE_SYSTEM = 'RAISERS_EDGE'
        AND WS.RN = 1
LEFT JOIN NICKNAME_CTE AS NN
    ON
        RE_RAW.CONSTITUENT_ID = NN.CONSTITUENT_ID
        AND WS.SOURCE_SYSTEM = 'RAISERS_EDGE'
        AND WS.RN = 1
LEFT JOIN FACEBOOK_CTE AS FB
    ON
        RE_RAW.CONSTITUENT_ID = FB.CONSTITUENT_ID
        AND WS.SOURCE_SYSTEM = 'RAISERS_EDGE'
        AND WS.RN = 1
LEFT JOIN INSTAGRAM_CTE AS IG
    ON
        RE_RAW.CONSTITUENT_ID = IG.CONSTITUENT_ID
        AND WS.SOURCE_SYSTEM = 'RAISERS_EDGE'
        AND WS.RN = 1
LEFT JOIN LINKEDIN_CTE AS LI
    ON
        RE_RAW.CONSTITUENT_ID = LI.CONSTITUENT_ID
        AND WS.SOURCE_SYSTEM = 'RAISERS_EDGE'
        AND WS.RN = 1
LEFT JOIN TWITTER_CTE AS TW
    ON
        RE_RAW.CONSTITUENT_ID = TW.CONSTITUENT_ID
        AND WS.SOURCE_SYSTEM = 'RAISERS_EDGE'
        AND WS.RN = 1
LEFT JOIN RAW.DYNAMICS.VW_ODS_MHA_TITLES AS MT
    ON TRIM(UPPER(GR.TITLE)) = TRIM(UPPER(MT.MHA_NAME))
LEFT JOIN RAW.DYNAMICS.VW_ODS_OPTIONSET_CONTACT_NAS_CONTACTTITLE AS CT
    ON TRIM(UPPER(GR.TITLE)) = TRIM(UPPER(CT.OPTION_LABEL))
LEFT JOIN EMAIL2_CTE AS E2
    ON
        RE_RAW.CONSTITUENT_ID = E2.CONSTITUENTID
        AND WS.SOURCE_SYSTEM = 'RAISERS_EDGE'
        AND WS.RN = 1
LEFT JOIN WEBSITE_CTE AS WEB
    ON
        RE_RAW.CONSTITUENT_ID = WEB.CONSTITUENTID
        AND WS.SOURCE_SYSTEM = 'RAISERS_EDGE'
        AND WS.RN = 1
LEFT JOIN RAW.DYNAMICS.VW_ODS_MHA_ISOCOUNTRIES AS ISO
    ON TRIM(UPPER(GR.COUNTRY)) = TRIM(UPPER(ISO.MHA_NAME))
LEFT JOIN RAW.DYNAMICS.VW_ODS_NAS_COUNTRIES AS NC
    ON TRIM(UPPER(GR.COUNTRY)) = TRIM(UPPER(NC.NAS_NAME))
WHERE
    GR._IS_ACTIVE = TRUE
    AND GR.DOMAIN = 'INDIVIDUAL'
    AND IDS.IS_GDPR_SUPPRESSED = FALSE;