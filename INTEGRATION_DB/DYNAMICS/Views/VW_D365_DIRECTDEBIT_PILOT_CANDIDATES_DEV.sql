CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_DIRECTDEBIT_PILOT_CANDIDATES_DEV AS

-- Read-only technical-pilot candidates; this view cannot dispatch a request.
-- Regular Giving status is not proof of the underlying mandate's status.
WITH GIFTS AS (
    SELECT
        ID,
        NULLIF(TRIM(CONSTITUENT_ID), '') AS RE_CONSTITUENT_ID,
        NULLIF(TRIM(REFERENCE_NUMBER), '') AS REFERENCE_NUMBER,
        PAYMENTMETHODDESCRIPTION,
        GIFTTYPEDESCRIPTION,
        COUNT(*) OVER (PARTITION BY ID) AS SOURCE_ID_ROWS
    FROM RAW.RAISERS_EDGE.VW_ODS_T_GIFTS
),
DIRECT_GIFTS AS (
    SELECT
        *,
        COUNT(*) OVER (PARTITION BY UPPER(REFERENCE_NUMBER)) AS REFERENCE_ROWS
    FROM GIFTS
    WHERE UPPER(TRIM(PAYMENTMETHODDESCRIPTION)) = 'DIRECT DEBIT'
      AND GIFTTYPEDESCRIPTION = 'Recurring Gift'
      AND REFERENCE_NUMBER IS NOT NULL
),
REGULAR_GIVING AS (
    SELECT
        ID,
        COUNT(*) AS ROWS_PER_ID,
        MIN(NULLIF(TRIM(CONSTITUENT_ID), '')) AS RE_CONSTITUENT_ID,
        MIN(STATUS) AS STATUS
    FROM RAW.RAISERS_EDGE.VW_ODS_T_REGULARGIVING
    GROUP BY ID
),
RE_PARTY AS (
    SELECT
        TRIM(X.SOURCE_RECORD_ID) AS RE_CONSTITUENT_ID,
        COUNT(DISTINCT X.GOLDEN_RECORD_ID) AS GOLDEN_RECORDS,
        MIN(X.GOLDEN_RECORD_ID) AS GOLDEN_RECORD_ID,
        COUNT_IF(G.GOLDEN_RECORD_ID IS NULL OR G.IS_GDPR_SUPPRESSED IS NULL)
            AS UNKNOWN_PRIVACY_ROWS,
        COUNT_IF(G.IS_GDPR_SUPPRESSED = TRUE) AS SUPPRESSED_ROWS,
        COUNT(DISTINCT LOWER(NULLIF(TRIM(G.D365_CONTACT_ID), ''))) AS CONTACT_IDS,
        COUNT(DISTINCT LOWER(NULLIF(TRIM(G.D365_ACCOUNT_ID), ''))) AS ACCOUNT_IDS,
        MIN(LOWER(NULLIF(TRIM(G.D365_CONTACT_ID), ''))) AS CONTACT_ID
    FROM MDM_DB.GOLD.XREF X
    LEFT JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS G
        ON G.GOLDEN_RECORD_ID = X.GOLDEN_RECORD_ID
    WHERE X.SOURCE_SYSTEM = 'RAISERS_EDGE'
    GROUP BY TRIM(X.SOURCE_RECORD_ID)
),
DYNAMICS_PARTY AS (
    SELECT
        GOLDEN_RECORD_ID,
        COUNT(DISTINCT CASE WHEN STANDARDISED_ID LIKE 'D365-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), '')) END) AS CONTACT_IDS,
        MIN(CASE WHEN STANDARDISED_ID LIKE 'D365-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), '')) END) AS CONTACT_ID,
        COUNT(DISTINCT CASE WHEN STANDARDISED_ID LIKE 'D365C-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), '')) END) AS ACCOUNT_IDS
    FROM MDM_DB.GOLD.XREF
    WHERE SOURCE_SYSTEM = 'DYNAMICS'
    GROUP BY GOLDEN_RECORD_ID
)
SELECT
    G.ID AS RE_RECURRING_GIFT_ID,
    LENGTH(G.REFERENCE_NUMBER) AS REFERENCE_LENGTH,
    R.STATUS AS REGULAR_GIVING_STATUS,
    'CONTACT' AS PAYER_TYPE,
    'DRAFT' AS PROPOSED_TECHNICAL_STATUS,
    FALSE AS PREVIEW_DISPATCH_ALLOWED
FROM DIRECT_GIFTS G
JOIN REGULAR_GIVING R
    ON R.ID = G.ID
   AND R.ROWS_PER_ID = 1
   AND R.RE_CONSTITUENT_ID = G.RE_CONSTITUENT_ID
JOIN RE_PARTY P
    ON P.RE_CONSTITUENT_ID = G.RE_CONSTITUENT_ID
JOIN DYNAMICS_PARTY D
    ON D.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
WHERE G.ID IS NOT NULL
  AND G.SOURCE_ID_ROWS = 1
  AND G.REFERENCE_ROWS = 1
  AND LENGTH(G.REFERENCE_NUMBER) <= 18
  AND LENGTH('TEST-DD-' || TO_VARCHAR(G.ID)) <= 18
  AND UPPER(TRIM(R.STATUS)) = 'ACTIVE'
  AND P.GOLDEN_RECORDS = 1
  AND P.UNKNOWN_PRIVACY_ROWS = 0
  AND P.SUPPRESSED_ROWS = 0
  AND P.CONTACT_IDS = 1
  AND P.ACCOUNT_IDS = 0
  AND D.CONTACT_IDS = 1
  AND D.ACCOUNT_IDS = 0
  AND D.CONTACT_ID = P.CONTACT_ID
  AND REGEXP_LIKE(D.CONTACT_ID, '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}')
  AND NOT EXISTS (
      SELECT 1 FROM MDM_DB.GOLD.XREF X
      WHERE X.SOURCE_SYSTEM = 'DYNAMICS'
        AND X.GOLDEN_RECORD_ID = 'DIRECTDEBIT:' || TO_VARCHAR(G.ID)
  )
  AND NOT EXISTS (
      SELECT 1 FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE S
      WHERE S.ENTITY_ID = 'DIRECTDEBIT'
        AND S.GOLDEN_RECORD_ID = 'DIRECTDEBIT:' || TO_VARCHAR(G.ID)
  );
