CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_DIRECTDEBIT_PILOT_PREVIEW_DEV AS

-- Read-only technical preview. The reference and Draft status are synthetic
-- pilot choices, not an assertion about the source mandate.
WITH PILOT_PAYER AS (
    SELECT DISTINCT
        C.RE_RECURRING_GIFT_ID,
        LOWER(NULLIF(TRIM(G.D365_CONTACT_ID), '')) AS D365_CONTACT_ID
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_DIRECTDEBIT_PILOT_CANDIDATES_DEV C
    JOIN RAW.RAISERS_EDGE.VW_ODS_T_GIFTS S
        ON S.ID = C.RE_RECURRING_GIFT_ID
    JOIN MDM_DB.GOLD.XREF X
        ON X.SOURCE_SYSTEM = 'RAISERS_EDGE'
       AND TRIM(X.SOURCE_RECORD_ID) = TRIM(S.CONSTITUENT_ID)
    JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS G
        ON G.GOLDEN_RECORD_ID = X.GOLDEN_RECORD_ID
    WHERE C.RE_RECURRING_GIFT_ID = 224546
      AND G.IS_GDPR_SUPPRESSED = FALSE
      AND NULLIF(TRIM(G.D365_CONTACT_ID), '') IS NOT NULL
)
SELECT
    RE_RECURRING_GIFT_ID,
    D365_CONTACT_ID,
    'TEST-DD-224546' AS SYNTHETIC_REFERENCE,
    'DRAFT' AS PROPOSED_TECHNICAL_STATUS,
    FALSE AS PREVIEW_DISPATCH_ALLOWED,
    OBJECT_CONSTRUCT(
        'mha_reference', 'TEST-DD-224546',
        'mha_payerid_contact@odata.bind', '/contacts(' || D365_CONTACT_ID || ')',
        'statuscode', 1
    ) AS DRAFT_PAYLOAD
FROM PILOT_PAYER
QUALIFY COUNT(*) OVER (PARTITION BY RE_RECURRING_GIFT_ID) = 1;
