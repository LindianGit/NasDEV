CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_DIRECTDEBIT_PILOT_REQUESTS_DEV AS

-- One Draft DEV technical pilot with a synthetic reference. Recheck live
-- duplicates and the payer before dispatch; reconcile uncertain POSTs.
-- These guards are not atomic.
WITH PILOT AS (
    SELECT
        'DIRECTDEBIT:' || TO_VARCHAR(RE_RECURRING_GIFT_ID) AS GOLDEN_RECORD_ID,
        DRAFT_PAYLOAD AS REQUEST_BODY
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_DIRECTDEBIT_PILOT_PREVIEW_DEV
    WHERE RE_RECURRING_GIFT_ID = 224546
      AND D365_CONTACT_ID = 'eaf1ddc5-a8e1-f111-84ea-70a8a575b5fc'
      AND SYNTHETIC_REFERENCE = 'TEST-DD-224546'
      AND DRAFT_PAYLOAD:"statuscode"::NUMBER = 1
      AND DRAFT_PAYLOAD:"mha_reference"::VARCHAR = 'TEST-DD-224546'
      AND DRAFT_PAYLOAD:"mha_payerid_contact@odata.bind"::VARCHAR =
          '/contacts(eaf1ddc5-a8e1-f111-84ea-70a8a575b5fc)'
)
SELECT
    'D365_DIRECTDEBIT_PILOT' AS PIPELINE_ID,
    M.SOURCE_INSTANCE,
    'DIRECTDEBIT' AS ENTITY_ID,
    P.GOLDEN_RECORD_ID,
    CAST(NULL AS VARCHAR) AS TARGET_GUID,
    'POST' AS HTTP_METHOD,
    M.API_BASE_URL || '/mha_directdebits' AS REQUEST_URL,
    P.REQUEST_BODY,
    M.AUTH_METHOD,
    M.AUTH_CONFIG,
    MD5(TO_VARCHAR(P.REQUEST_BODY)) AS PAYLOAD_MD5
FROM AUDIT_DB.CONFIG.PIPELINE_METADATA AS M
CROSS JOIN PILOT AS P
WHERE M.PIPELINE_ID = 'D365_WRITEBACK'
  AND M.SOURCE_INSTANCE = 'SNOWFLAKE_DEV'
  AND M.ENTITY_ID = 'CAMPAIGN'
  AND M.API_BASE_URL = 'https://nasdatamig.crm11.dynamics.com/api/data/v9.2'
  AND NOT EXISTS (
      SELECT 1
      FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE AS S
      WHERE S.ENTITY_ID = 'DIRECTDEBIT'
        AND S.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.XREF AS X
      WHERE X.SOURCE_SYSTEM = 'DYNAMICS'
        AND X.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
  )
QUALIFY COUNT(*) OVER (PARTITION BY P.GOLDEN_RECORD_ID) = 1;
