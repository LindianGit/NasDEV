CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_EVENTPARTICIPANT_PILOT_PREVIEW_DEV AS

-- Read-only preview for the DEV candidate. Required fields and lookup metadata
-- were verified in Dynamics DEV; unresolved optional business fields stay omitted.
WITH PARTY AS (
    SELECT
        X.SOURCE_RECORD_ID AS RE_CONSTITUENT_ID,
        COUNT(DISTINCT NULLIF(LOWER(TRIM(G.D365_CONTACT_ID)), '')) AS CONTACT_IDS,
        MIN(NULLIF(LOWER(TRIM(G.D365_CONTACT_ID)), '')) AS D365_CONTACT_ID,
        COUNT(DISTINCT NULLIF(LOWER(TRIM(G.D365_ACCOUNT_ID)), '')) AS ACCOUNT_IDS,
        COUNT_IF(G.GOLDEN_RECORD_ID IS NULL OR G.IS_GDPR_SUPPRESSED IS NULL)
            AS UNKNOWN_GDPR,
        COUNT_IF(G.IS_GDPR_SUPPRESSED = TRUE) AS SUPPRESSED
    FROM MDM_DB.GOLD.XREF AS X
    LEFT JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS AS G
        ON X.GOLDEN_RECORD_ID = G.GOLDEN_RECORD_ID
    WHERE X.SOURCE_SYSTEM = 'RAISERS_EDGE'
      AND X.SOURCE_RECORD_ID = '558745'
    GROUP BY X.SOURCE_RECORD_ID
),

STATUS_MAP AS (
    SELECT
        RE_SOURCE_COLUMN,
        UPPER(TRIM(RE_VALUE)) AS RE_VALUE_KEY,
        COUNT(*) AS MAP_ROWS,
        COUNT(DISTINCT D365_STATUSCODE) AS STATUSCODE_VARIANTS,
        MIN(D365_STATUS_LABEL) AS D365_STATUS_LABEL,
        MIN(D365_STATUSCODE) AS D365_STATUSCODE
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_REF_PARTICIPANT_STATUS
    WHERE MAP_STATUS = 'MAPPED'
      AND D365_STATUSCODE IS NOT NULL
    GROUP BY RE_SOURCE_COLUMN, UPPER(TRIM(RE_VALUE))
),

STATUS_OPTIONS AS (
    SELECT
        OPTION_VALUE AS D365_STATUSCODE,
        COUNT(DISTINCT STATE) AS STATE_VARIANTS,
        MIN(STATE) AS STATECODE
    FROM RAW.DYNAMICS.VW_ODS_METADATA_OPTIONS
    WHERE ENTITY_LOGICALNAME = 'msnfp_eventpackage'
      AND ATTRIBUTE_LOGICALNAME = 'statuscode'
    GROUP BY OPTION_VALUE
),

PILOT_SOURCE AS (
    SELECT
        EP.ID AS RE_EVENT_PARTICIPANT_ID,
        EP.EVENTID AS RE_EVENT_ID,
        E.D365_ID AS D365_EVENT_ID,
        EP.CONSTITUENTID AS RE_CONSTITUENT_ID,
        P.D365_CONTACT_ID,
        P.CONTACT_IDS,
        P.ACCOUNT_IDS,
        P.UNKNOWN_GDPR,
        P.SUPPRESSED,
        EP.STATUSDESCRIPTION,
        EP.PARTICIPATIONDESCRIPTION,
        CASE
            WHEN S.MAP_ROWS = 1 AND S.STATUSCODE_VARIANTS = 1
                THEN S.D365_STATUS_LABEL
            WHEN S.MAP_ROWS IS NULL
                AND PT.MAP_ROWS = 1
                AND PT.STATUSCODE_VARIANTS = 1
                THEN PT.D365_STATUS_LABEL
        END AS D365_STATUS_LABEL,
        CASE
            WHEN S.MAP_ROWS = 1 AND S.STATUSCODE_VARIANTS = 1
                THEN S.D365_STATUSCODE
            WHEN S.MAP_ROWS IS NULL
                AND PT.MAP_ROWS = 1
                AND PT.STATUSCODE_VARIANTS = 1
                THEN PT.D365_STATUSCODE
        END AS D365_STATUSCODE,
        CASE
            WHEN S.MAP_ROWS = 1 AND S.STATUSCODE_VARIANTS = 1
                THEN 'STATUS'
            WHEN S.MAP_ROWS IS NULL
                AND PT.MAP_ROWS = 1
                AND PT.STATUSCODE_VARIANTS = 1
                THEN 'PARTICIPATION'
        END AS STATUS_SOURCE,
        TRY_TO_DATE(LEFT(TO_VARCHAR(EP.DATEADDED), 10)) AS RECORD_CREATED_DATE,
        COUNT(*) OVER (PARTITION BY EP.ID) AS SOURCE_MATCHES
    FROM RAW.RAISERS_EDGE.VW_ODS_T_EVENTPARTICIPANTS AS EP
    LEFT JOIN INTEGRATION_DB.DYNAMICS.VW_D365_MSNFP_EVENT AS E
        ON E.RE_EVENT_ID = EP.EVENTID
    LEFT JOIN PARTY AS P
        ON P.RE_CONSTITUENT_ID = TO_VARCHAR(EP.CONSTITUENTID)
    LEFT JOIN STATUS_MAP AS S
        ON S.RE_SOURCE_COLUMN = 'STATUS'
       AND S.RE_VALUE_KEY = UPPER(TRIM(EP.STATUSDESCRIPTION))
    LEFT JOIN STATUS_MAP AS PT
        ON PT.RE_SOURCE_COLUMN = 'PARTICIPATION'
       AND PT.RE_VALUE_KEY = UPPER(TRIM(EP.PARTICIPATIONDESCRIPTION))
    WHERE EP.ID = 115847
),

PREVIEW AS (
    SELECT
        P.*,
        O.STATE_VARIANTS,
        O.STATECODE
    FROM PILOT_SOURCE AS P
    LEFT JOIN STATUS_OPTIONS AS O
        ON O.D365_STATUSCODE = P.D365_STATUSCODE
)

SELECT
    RE_EVENT_PARTICIPANT_ID,
    RE_EVENT_ID,
    D365_EVENT_ID,
    RE_CONSTITUENT_ID,
    D365_CONTACT_ID,
    STATUSDESCRIPTION,
    PARTICIPATIONDESCRIPTION,
    D365_STATUS_LABEL,
    D365_STATUSCODE,
    STATECODE,
    STATUS_SOURCE,
    CASE
        WHEN SOURCE_MATCHES <> 1 THEN 'HOLD_SOURCE_NOT_UNIQUE'
        WHEN D365_EVENT_ID IS NULL THEN 'HOLD_EVENT_ID_UNRESOLVED'
        WHEN COALESCE(CONTACT_IDS, 0) <> 1 THEN 'HOLD_CONTACT_NOT_UNIQUE'
        WHEN COALESCE(ACCOUNT_IDS, 0) <> 0 THEN 'HOLD_CONTACT_ACCOUNT_AMBIGUITY'
        WHEN COALESCE(UNKNOWN_GDPR, 0) <> 0 OR COALESCE(SUPPRESSED, 0) <> 0
            THEN 'HOLD_PRIVACY_REVIEW'
        WHEN D365_STATUSCODE IS NULL THEN 'HOLD_STATUS_UNMAPPED'
        WHEN COALESCE(STATE_VARIANTS, 0) <> 1 THEN 'HOLD_STATUS_STATE_UNRESOLVED'
        ELSE 'PREVIEW_ONLY_NOT_DISPATCHABLE'
    END AS PREVIEW_STATUS,
    FALSE AS DISPATCH_ALLOWED,
    'msnfp_identifier business rule; msnfp_date; Appeal/Campaign/Package; participant attributes and added fields'
        AS OPEN_MAPPINGS,
    OBJECT_CONSTRUCT(
        'mha_source', 'RE',
        'mha_sourceid', TO_VARCHAR(RE_EVENT_PARTICIPANT_ID),
        'msnfp_EventId@odata.bind',
            IFF(
                D365_EVENT_ID IS NOT NULL,
                '/msnfp_events(' || D365_EVENT_ID || ')',
                NULL
            ),
        'msnfp_CustomerId_contact@odata.bind',
            IFF(
                D365_CONTACT_ID IS NOT NULL,
                '/contacts(' || D365_CONTACT_ID || ')',
                NULL
            ),
        'statecode', IFF(STATE_VARIANTS = 1, STATECODE, NULL),
        'statuscode', D365_STATUSCODE,
        'overriddencreatedon',
            TO_CHAR(RECORD_CREATED_DATE, 'YYYY-MM-DD')
    ) AS DRAFT_PAYLOAD
FROM PREVIEW;
