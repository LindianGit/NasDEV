CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_EVENTPARTICIPANT_PILOT_REQUESTS_DEV AS

-- One DEV participant using only confirmed mappings. Reconcile uncertain POSTs before retrying.
WITH PILOT AS (
    SELECT
        'EVENTPARTICIPANT:' || TO_VARCHAR(RE_EVENT_PARTICIPANT_ID) AS GOLDEN_RECORD_ID,
        DRAFT_PAYLOAD AS REQUEST_BODY
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_EVENTPARTICIPANT_PILOT_PREVIEW_DEV
    WHERE PREVIEW_STATUS = 'PREVIEW_ONLY_NOT_DISPATCHABLE'
      AND RE_EVENT_PARTICIPANT_ID = 115847
),

REQUESTS AS (
    SELECT
        P.GOLDEN_RECORD_ID,
        P.REQUEST_BODY,
        MD5(TO_VARCHAR(P.REQUEST_BODY)) AS PAYLOAD_MD5
    FROM PILOT AS P
)

SELECT
    'D365_EVENTPARTICIPANT_PILOT' AS PIPELINE_ID,
    M.SOURCE_INSTANCE,
    'EVENTPARTICIPANT' AS ENTITY_ID,
    R.GOLDEN_RECORD_ID,
    CAST(NULL AS VARCHAR) AS TARGET_GUID,
    'POST' AS HTTP_METHOD,
    M.API_BASE_URL || '/msnfp_eventpackages' AS REQUEST_URL,
    R.REQUEST_BODY,
    M.AUTH_METHOD,
    M.AUTH_CONFIG,
    R.PAYLOAD_MD5
FROM AUDIT_DB.CONFIG.PIPELINE_METADATA AS M
CROSS JOIN REQUESTS AS R
WHERE M.PIPELINE_ID = 'D365_WRITEBACK'
  AND M.SOURCE_INSTANCE = 'SNOWFLAKE_DEV'
  AND M.ENTITY_ID = 'CAMPAIGN'
  AND M.API_BASE_URL = 'https://nasdatamig.crm11.dynamics.com/api/data/v9.2'
  AND NOT EXISTS (
      SELECT 1
      FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE AS S
      WHERE S.ENTITY_ID = 'EVENTPARTICIPANT'
        AND S.GOLDEN_RECORD_ID = R.GOLDEN_RECORD_ID
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.XREF AS X
      WHERE X.SOURCE_SYSTEM = 'DYNAMICS'
        AND X.GOLDEN_RECORD_ID = R.GOLDEN_RECORD_ID
  )
  AND NOT EXISTS (
      SELECT 1
      FROM RAW.DYNAMICS.VW_ODS_MSNFP_EVENTPACKAGES AS D
      WHERE TRIM(D.MHA_SOURCEID) = '115847'
  )
QUALIFY COUNT(*) OVER (PARTITION BY R.GOLDEN_RECORD_ID) = 1;
