CREATE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_EVENTTYPE_BATCH_REQUESTS_DEV AS

-- DEV preview only until an isolated, sequential sender is validated.
-- Reconcile failed or uncertain creates before retrying.
WITH CANDIDATES AS (
    SELECT
        RE_EVENT_TYPE,
        UPPER(TRIM(RE_EVENT_TYPE)) AS RE_EVENT_TYPE_KEY,
        'EVENTTYPE:' || MD5(UPPER(TRIM(RE_EVENT_TYPE))) AS GOLDEN_RECORD_ID,
        LOWER(UUID_STRING(
            'e26a2593-0dc6-4989-aa17-7844b5258823',
            'EVENTTYPE:' || UPPER(TRIM(RE_EVENT_TYPE))
        )) AS PLANNED_D365_GUID,
        PAYLOAD
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_MHA_EVENTTYPE
    WHERE UPPER(TRIM(RE_EVENT_TYPE)) <> 'EXTERNAL TRAINING'
      AND RE_NAME_VARIANTS = 1
      AND D365_MATCH_COUNT = 0
      AND LOAD_ACTION = 'HOLD'
      AND HOLD_REASON = 'DEV_PREVIEW_ONLY'
      AND PAYLOAD:"mha_eventcategory"::NUMBER = 862940001
),
REQUESTS AS (
    SELECT
        C.*,
        OBJECT_INSERT(
            C.PAYLOAD, 'mha_eventtypeid', C.PLANNED_D365_GUID, TRUE
        ) AS REQUEST_BODY
    FROM CANDIDATES AS C
)
SELECT
    'D365_EVENTTYPE_BATCH' AS PIPELINE_ID,
    M.SOURCE_INSTANCE,
    'EVENTTYPE' AS ENTITY_ID,
    R.GOLDEN_RECORD_ID,
    CAST(NULL AS VARCHAR) AS TARGET_GUID,
    'POST' AS HTTP_METHOD,
    M.API_BASE_URL || '/mha_eventtypes' AS REQUEST_URL,
    R.REQUEST_BODY,
    M.AUTH_METHOD,
    M.AUTH_CONFIG,
    MD5(TO_VARCHAR(R.REQUEST_BODY)) AS PAYLOAD_MD5,
    R.RE_EVENT_TYPE
FROM AUDIT_DB.CONFIG.PIPELINE_METADATA AS M
CROSS JOIN REQUESTS AS R
WHERE M.PIPELINE_ID = 'D365_WRITEBACK'
  AND M.SOURCE_INSTANCE = 'SNOWFLAKE_DEV'
  AND M.ENTITY_ID = 'CAMPAIGN'
  AND M.API_BASE_URL = 'https://nasdatamig.crm11.dynamics.com/api/data/v9.2'
  AND NOT EXISTS (
      SELECT 1
      FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE AS S
      WHERE S.ENTITY_ID = 'EVENTTYPE'
        AND S.GOLDEN_RECORD_ID = R.GOLDEN_RECORD_ID
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.XREF AS X
      WHERE X.SOURCE_SYSTEM = 'DYNAMICS'
        AND (
            X.GOLDEN_RECORD_ID = R.GOLDEN_RECORD_ID
            OR (
                X.GOLDEN_RECORD_ID LIKE 'EVENTTYPE:%'
                AND LOWER(TRIM(X.SOURCE_RECORD_ID)) = R.PLANNED_D365_GUID
            )
        )
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.EVENTTYPE_D365_IDENTITY_DEV AS I
      WHERE I.RE_EVENT_TYPE_KEY = R.RE_EVENT_TYPE_KEY
         OR I.D365_GUID = R.PLANNED_D365_GUID
  )
  AND NOT EXISTS (
      SELECT 1
      FROM RAW.DYNAMICS.VW_ODS_MHA_EVENTTYPES AS D
      WHERE LOWER(TRIM(D.MHA_EVENTTYPEID)) = R.PLANNED_D365_GUID
  )
QUALIFY COUNT(*) OVER (PARTITION BY R.GOLDEN_RECORD_ID) = 1;
