CREATE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_EVENTTYPE_PILOT_REQUESTS_DEV AS

-- One DEV test only. Reconcile any failed or uncertain POST before retrying.
WITH PILOT AS (
    SELECT
        'EVENTTYPE:' || MD5(UPPER(TRIM(RE_EVENT_TYPE))) AS GOLDEN_RECORD_ID,
        OBJECT_INSERT(
            PAYLOAD,
            'mha_eventtypeid',
            'f081f432-5624-4864-892f-e2e233179fe4',
            TRUE
        ) AS REQUEST_BODY
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_MHA_EVENTTYPE
    WHERE RE_EVENT_TYPE = 'External Training'
      AND RE_NAME_VARIANTS = 1
      AND D365_MATCH_COUNT = 0
      AND LOAD_ACTION = 'HOLD'
      AND HOLD_REASON = 'DEV_PREVIEW_ONLY'
      AND PAYLOAD:"mha_eventcategory"::NUMBER = 862940001
)
SELECT
    'D365_EVENTTYPE_PILOT' AS PIPELINE_ID,
    M.SOURCE_INSTANCE,
    'EVENTTYPE' AS ENTITY_ID,
    P.GOLDEN_RECORD_ID,
    CAST(NULL AS VARCHAR) AS TARGET_GUID,
    'POST' AS HTTP_METHOD,
    M.API_BASE_URL || '/mha_eventtypes' AS REQUEST_URL,
    P.REQUEST_BODY,
    M.AUTH_METHOD,
    M.AUTH_CONFIG,
    MD5(TO_VARCHAR(P.REQUEST_BODY)) AS PAYLOAD_MD5
FROM AUDIT_DB.CONFIG.PIPELINE_METADATA AS M
CROSS JOIN PILOT AS P
WHERE M.PIPELINE_ID = 'D365_WRITEBACK'
  AND M.SOURCE_INSTANCE = 'SNOWFLAKE_DEV'
  AND M.ENTITY_ID = 'CAMPAIGN'
  AND M.API_BASE_URL = 'https://nasdatamig.crm11.dynamics.com/api/data/v9.2'
  AND NOT EXISTS (
      SELECT 1
      FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE AS S
      WHERE S.ENTITY_ID = 'EVENTTYPE'
        AND S.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.XREF AS X
      WHERE X.SOURCE_SYSTEM = 'DYNAMICS'
        AND X.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.EVENTTYPE_D365_IDENTITY_DEV AS I
      WHERE I.RE_EVENT_TYPE_KEY = 'EXTERNAL TRAINING'
         OR I.D365_GUID = 'f081f432-5624-4864-892f-e2e233179fe4'
  )
QUALIFY COUNT(*) OVER (PARTITION BY P.GOLDEN_RECORD_ID) = 1;
