CREATE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_EVENT_BATCH_REQUESTS_DEV AS

-- DEV preview only. Reconcile failed or uncertain POSTs before another run.
WITH SOURCE_EVENTS AS (
    SELECT
        E.*,
        COUNT(*) OVER (PARTITION BY E.RE_EVENT_ID) AS ID_COUNT,
        COUNT(*) OVER (PARTITION BY UPPER(TRIM(E.RE_EVENT_REF))) AS REF_COUNT
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_MSNFP_EVENT AS E
),
CANDIDATES AS (
    SELECT
        TO_VARCHAR(RE_EVENT_ID) AS RE_EVENT_ID,
        TRIM(RE_EVENT_REF) AS RE_EVENT_REF,
        'EVENT:' || TO_VARCHAR(RE_EVENT_ID) AS GOLDEN_RECORD_ID,
        LOWER(UUID_STRING(
            'c3baf199-821e-4e30-8aac-5375c34fd684',
            'EVENT:' || TO_VARCHAR(RE_EVENT_ID)
        )) AS PLANNED_D365_GUID,
        PAYLOAD
    FROM SOURCE_EVENTS
    WHERE LOAD_ACTION = 'CREATE'
      AND RE_EVENT_ID IS NOT NULL
      AND REGEXP_LIKE(TO_VARCHAR(RE_EVENT_ID), '[0-9]+')
      AND NULLIF(TRIM(RE_EVENT_REF), '') IS NOT NULL
      AND MSNFP_NAME IS NOT NULL
      AND ID_COUNT = 1
      AND REF_COUNT = 1
),
REQUESTS AS (
    SELECT
        C.*,
        OBJECT_INSERT(
            C.PAYLOAD, 'msnfp_eventid', C.PLANNED_D365_GUID, TRUE
        ) AS REQUEST_BODY
    FROM CANDIDATES AS C
)
SELECT
    'D365_EVENT_BATCH' AS PIPELINE_ID,
    M.SOURCE_INSTANCE,
    'EVENT' AS ENTITY_ID,
    R.GOLDEN_RECORD_ID,
    CAST(NULL AS VARCHAR) AS TARGET_GUID,
    'POST' AS HTTP_METHOD,
    M.API_BASE_URL || '/msnfp_events' AS REQUEST_URL,
    R.REQUEST_BODY,
    M.AUTH_METHOD,
    M.AUTH_CONFIG,
    MD5(TO_VARCHAR(R.REQUEST_BODY)) AS PAYLOAD_MD5,
    R.RE_EVENT_ID,
    R.RE_EVENT_REF,
    R.PLANNED_D365_GUID
FROM AUDIT_DB.CONFIG.PIPELINE_METADATA AS M
CROSS JOIN REQUESTS AS R
WHERE M.PIPELINE_ID = 'D365_WRITEBACK'
  AND M.SOURCE_INSTANCE = 'SNOWFLAKE_DEV'
  AND M.ENTITY_ID = 'CAMPAIGN'
  AND M.API_BASE_URL = 'https://nasdatamig.crm11.dynamics.com/api/data/v9.2'
  AND NOT EXISTS (
      SELECT 1
      FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE AS S
      WHERE S.ENTITY_ID = 'EVENT'
        AND S.GOLDEN_RECORD_ID = R.GOLDEN_RECORD_ID
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.XREF AS X
      WHERE X.SOURCE_SYSTEM = 'DYNAMICS'
        AND (
            X.GOLDEN_RECORD_ID = R.GOLDEN_RECORD_ID
            OR (
                X.GOLDEN_RECORD_ID LIKE 'EVENT:%'
                AND LOWER(TRIM(X.SOURCE_RECORD_ID)) = R.PLANNED_D365_GUID
            )
        )
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.EVENT_D365_IDENTITY_DEV AS I
      WHERE I.RE_EVENT_ID = R.RE_EVENT_ID
         OR I.D365_GUID = R.PLANNED_D365_GUID
  )
  AND NOT EXISTS (
      SELECT 1
      FROM RAW.DYNAMICS.VW_ODS_MSNFP_EVENTS AS D
      WHERE LOWER(TRIM(D.MSNFP_EVENTID)) = R.PLANNED_D365_GUID
  )
QUALIFY COUNT(*) OVER (PARTITION BY R.GOLDEN_RECORD_ID) = 1;
