CREATE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_EVENT_PILOT_REQUESTS_DEV AS

-- One DEV Event only. Reconcile any failed or uncertain POST before retrying.
WITH PILOT AS (
    SELECT
        'EVENT:14' AS GOLDEN_RECORD_ID,
        OBJECT_INSERT(
            PAYLOAD,
            'msnfp_eventid',
            '609825fb-8311-46a9-85c8-b372cbba3ae0',
            TRUE
        ) AS REQUEST_BODY
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_MSNFP_EVENT
    WHERE RE_EVENT_ID = 14
      AND UPPER(TRIM(RE_EVENT_REF)) = 'LM 2008 ORGANISATIONS'
      AND LOAD_ACTION = 'CREATE'
)
SELECT
    'D365_EVENT_PILOT' AS PIPELINE_ID,
    M.SOURCE_INSTANCE,
    'EVENT' AS ENTITY_ID,
    P.GOLDEN_RECORD_ID,
    CAST(NULL AS VARCHAR) AS TARGET_GUID,
    'POST' AS HTTP_METHOD,
    M.API_BASE_URL || '/msnfp_events' AS REQUEST_URL,
    P.REQUEST_BODY,
    M.AUTH_METHOD,
    M.AUTH_CONFIG,
    MD5(TO_VARCHAR(P.REQUEST_BODY)) AS PAYLOAD_MD5
FROM AUDIT_DB.CONFIG.PIPELINE_METADATA AS M
CROSS JOIN PILOT AS P
WHERE M.PIPELINE_ID = 'D365_WRITEBACK'
  AND M.SOURCE_INSTANCE = 'SNOWFLAKE_DEV'
  AND M.ENTITY_ID = 'CAMPAIGN'
  AND M.API_BASE_URL = 'https://nasdatamig.crm11.dynamics.com/api/data/v9.2'
  AND NOT EXISTS (
      SELECT 1
      FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE AS S
      WHERE S.ENTITY_ID = 'EVENT'
        AND S.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.XREF AS X
      WHERE X.SOURCE_SYSTEM = 'DYNAMICS'
        AND (
            X.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
            OR (
                X.GOLDEN_RECORD_ID LIKE 'EVENT:%'
                AND LOWER(TRIM(X.SOURCE_RECORD_ID)) = '609825fb-8311-46a9-85c8-b372cbba3ae0'
            )
        )
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.EVENT_D365_IDENTITY_DEV AS I
      WHERE I.RE_EVENT_ID = '14'
         OR I.D365_GUID = '609825fb-8311-46a9-85c8-b372cbba3ae0'
  )
  AND NOT EXISTS (
      SELECT 1
      FROM RAW.DYNAMICS.VW_ODS_MSNFP_EVENTS AS D
      WHERE LOWER(TRIM(D.MSNFP_EVENTID)) = '609825fb-8311-46a9-85c8-b372cbba3ae0'
  )
QUALIFY COUNT(*) OVER (PARTITION BY P.GOLDEN_RECORD_ID) = 1;
