CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_FUNDRAISINGPAGE_PILOT_REQUESTS_DEV AS

-- One DEV pilot from the Events mapping path. Only the verified
-- VirginMoneyGiving host is mapped; unrecognized hosts are held.
WITH PILOT_SOURCE_CANDIDATES AS (
    SELECT
        A.ID AS SOURCE_ATTRIBUTE_ID,
        CASE
            WHEN REGEXP_LIKE(
                LOWER(REGEXP_SUBSTR(
                    TRIM(A.VALUE),
                    '^https?://([^/:?#]+)',
                    1,
                    1,
                    'e',
                    1
                )),
                '(^|[.])virginmoneygiving[.]com$'
            ) THEN 'VirginMoneyGiving.com'
        END AS PLATFORM_VALUE,
        TRIM(A.VALUE) AS PAGE_URL
    FROM RAW.RAISERS_EDGE.VW_ODS_T_EVENTPARTICIPANTATTRIBUTES AS A
    WHERE
        UPPER(TRIM(A.CATEGORY)) = 'FUNDRAISER WEBSITE PAGE'
        AND NULLIF(TRIM(A.VALUE), '') IS NOT NULL
        AND (
            UPPER(TRIM(A.VALUE)) LIKE 'HTTP://%'
            OR UPPER(TRIM(A.VALUE)) LIKE 'HTTPS://%'
        )
        AND LENGTH(TRIM(A.VALUE)) <= 100
),

PILOT_SOURCE AS (
    SELECT
        SOURCE_ATTRIBUTE_ID,
        PLATFORM_VALUE,
        PAGE_URL
    FROM PILOT_SOURCE_CANDIDATES
    WHERE PLATFORM_VALUE IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (ORDER BY SOURCE_ATTRIBUTE_ID) = 1
),

PILOT AS (
    SELECT
        'FUNDRAISINGPAGE:PARTICIPANTATTRIBUTE:' || SOURCE_ATTRIBUTE_ID::VARCHAR
            AS GOLDEN_RECORD_ID,
        OBJECT_CONSTRUCT(
            'mhnas_name', PLATFORM_VALUE,
            'mhnas_link', PAGE_URL
        ) AS REQUEST_BODY
    FROM PILOT_SOURCE
)

SELECT
    'D365_FUNDRAISINGPAGE_PILOT' AS PIPELINE_ID,
    M.SOURCE_INSTANCE,
    'FUNDRAISINGPAGE' AS ENTITY_ID,
    P.GOLDEN_RECORD_ID,
    CAST(NULL AS VARCHAR) AS TARGET_GUID,
    'POST' AS HTTP_METHOD,
    M.API_BASE_URL || '/mhnas_fundraisingpages' AS REQUEST_URL,
    P.REQUEST_BODY,
    M.AUTH_METHOD,
    M.AUTH_CONFIG,
    MD5(TO_VARCHAR(P.REQUEST_BODY)) AS PAYLOAD_MD5
FROM AUDIT_DB.CONFIG.PIPELINE_METADATA AS M
CROSS JOIN PILOT AS P
WHERE M.PIPELINE_ID = 'D365_WRITEBACK'
  AND M.SOURCE_INSTANCE = 'SNOWFLAKE_DEV'
  AND M.ENTITY_ID = 'CAMPAIGN'
  AND M.API_BASE_URL = 'https://nasdatamig.crm11.dynamics.com/api/data/v9.2'
  AND NOT EXISTS (
      SELECT 1
      FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE AS S
      WHERE S.ENTITY_ID = 'FUNDRAISINGPAGE'
        AND S.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.XREF AS X
      WHERE X.SOURCE_SYSTEM = 'DYNAMICS'
        AND X.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
  )
QUALIFY COUNT(*) OVER (PARTITION BY P.GOLDEN_RECORD_ID) = 1;
