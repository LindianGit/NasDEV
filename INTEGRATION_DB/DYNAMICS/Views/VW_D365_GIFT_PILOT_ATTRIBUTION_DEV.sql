CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_GIFT_PILOT_ATTRIBUTION_DEV AS

-- DEV screening only. A resolved extract match is not a live check.
WITH RE_CAMPAIGNS AS (
    SELECT
        ID,
        COUNT(*) AS ROWS_PER_ID,
        MIN(UPPER(NULLIF(TRIM(CAMPAIGNCODE), ''))) AS CODE_KEY
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CAMPAIGNS
    GROUP BY ID
),
RE_CAMPAIGN_CODES AS (
    SELECT UPPER(TRIM(CAMPAIGNCODE)) AS CODE_KEY, COUNT(*) AS MATCHES
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CAMPAIGNS
    WHERE NULLIF(TRIM(CAMPAIGNCODE), '') IS NOT NULL
    GROUP BY UPPER(TRIM(CAMPAIGNCODE))
),
D365_CAMPAIGNS AS (
    SELECT
        UPPER(TRIM(CODENAME)) AS CODE_KEY,
        COUNT(*) AS MATCHES,
        MIN(NULLIF(TRIM(CAMPAIGNID), '')) AS D365_ID
    FROM RAW.DYNAMICS.VW_ODS_CAMPAIGNS
    WHERE NULLIF(TRIM(CODENAME), '') IS NOT NULL
    GROUP BY UPPER(TRIM(CODENAME))
),
RE_APPEALS AS (
    SELECT ID, COUNT(*) AS ROWS_PER_ID, MIN(CAMPAIGNCODE) AS CAMPAIGN_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_APPEALS
    GROUP BY ID
),
D365_APPEALS AS (
    SELECT
        TRIM(MHA_SOURCEID) AS SOURCE_ID,
        COUNT(*) AS MATCHES,
        MIN(NULLIF(TRIM(MSNFP_APPEALID), '')) AS D365_ID
    FROM RAW.DYNAMICS.VW_ODS_MSNFP_APPEALS
    WHERE NULLIF(TRIM(MHA_SOURCEID), '') IS NOT NULL
    GROUP BY TRIM(MHA_SOURCEID)
),
RE_PACKAGES AS (
    SELECT ID, COUNT(*) AS ROWS_PER_ID, MIN(APPEALID) AS APPEAL_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_PACKAGES
    GROUP BY ID
),
D365_PACKAGES AS (
    SELECT
        TRIM(MHA_SOURCEID) AS SOURCE_ID,
        COUNT(*) AS MATCHES,
        MIN(NULLIF(TRIM(MSNFP_PACKAGEID), '')) AS D365_ID
    FROM RAW.DYNAMICS.VW_ODS_MSNFP_PACKAGES
    WHERE NULLIF(TRIM(MHA_SOURCEID), '') IS NOT NULL
    GROUP BY TRIM(MHA_SOURCEID)
),
CHECKED AS (
    SELECT
        L.RE_GIFT_ID,
        L.RE_SPLIT_ID,
        L.RE_CAMPAIGN_ID,
        L.RE_APPEAL_ID,
        L.RE_PACKAGE_ID,
        DC.D365_ID AS CAMPAIGN_D365_ID,
        DA.D365_ID AS APPEAL_D365_ID,
        DP.D365_ID AS PACKAGE_D365_ID,
        ARRAY_CONSTRUCT_COMPACT(
            IFF(L.RE_CAMPAIGN_ID IS NOT NULL AND (
                COALESCE(RC.ROWS_PER_ID, 0) <> 1
                OR COALESCE(RCC.MATCHES, 0) <> 1
                OR COALESCE(DC.MATCHES, 0) <> 1
                OR NOT COALESCE(REGEXP_LIKE(
                    LOWER(DC.D365_ID),
                    '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
                ), FALSE)
            ), 'CAMPAIGN_UNRESOLVED_OR_AMBIGUOUS', NULL),
            IFF(L.RE_APPEAL_ID IS NOT NULL AND (
                COALESCE(RA.ROWS_PER_ID, 0) <> 1
                OR COALESCE(DA.MATCHES, 0) <> 1
                OR NOT COALESCE(REGEXP_LIKE(
                    LOWER(DA.D365_ID),
                    '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
                ), FALSE)
            ), 'APPEAL_UNRESOLVED_OR_AMBIGUOUS', NULL),
            IFF(L.RE_PACKAGE_ID IS NOT NULL AND (
                COALESCE(RP.ROWS_PER_ID, 0) <> 1
                OR COALESCE(DP.MATCHES, 0) <> 1
                OR NOT COALESCE(REGEXP_LIKE(
                    LOWER(DP.D365_ID),
                    '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
                ), FALSE)
            ), 'PACKAGE_UNRESOLVED_OR_AMBIGUOUS', NULL),
            IFF(L.RE_CAMPAIGN_ID IS NOT NULL AND L.RE_APPEAL_ID IS NOT NULL
                AND RA.CAMPAIGN_ID IS DISTINCT FROM L.RE_CAMPAIGN_ID,
                'APPEAL_CAMPAIGN_MISMATCH', NULL),
            IFF(L.RE_APPEAL_ID IS NOT NULL AND L.RE_PACKAGE_ID IS NOT NULL
                AND RP.APPEAL_ID IS DISTINCT FROM L.RE_APPEAL_ID,
                'PACKAGE_APPEAL_MISMATCH', NULL)
        ) AS BLOCKERS
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_MSNFP_DESIGNATEDCREDIT AS L
    INNER JOIN INTEGRATION_DB.DYNAMICS.VW_D365_MSNFP_TRANSACTION AS T
        ON T.RE_GIFT_ID = L.RE_GIFT_ID
    LEFT JOIN RE_CAMPAIGNS AS RC ON L.RE_CAMPAIGN_ID = RC.ID
    LEFT JOIN RE_CAMPAIGN_CODES AS RCC ON RC.CODE_KEY = RCC.CODE_KEY
    LEFT JOIN D365_CAMPAIGNS AS DC ON RC.CODE_KEY = DC.CODE_KEY
    LEFT JOIN RE_APPEALS AS RA ON L.RE_APPEAL_ID = RA.ID
    LEFT JOIN D365_APPEALS AS DA ON TO_VARCHAR(L.RE_APPEAL_ID) = DA.SOURCE_ID
    LEFT JOIN RE_PACKAGES AS RP ON L.RE_PACKAGE_ID = RP.ID
    LEFT JOIN D365_PACKAGES AS DP ON TO_VARCHAR(L.RE_PACKAGE_ID) = DP.SOURCE_ID
    WHERE T.RE_GIFT_TYPE_CODE = 1
      AND T.SPLIT_COUNT = 1
      AND T.DONOR_D365_ID IS NOT NULL
      AND L.DESIGNATION_D365_ID IS NOT NULL
)

SELECT
    RE_GIFT_ID,
    RE_SPLIT_ID,
    RE_CAMPAIGN_ID,
    RE_APPEAL_ID,
    RE_PACKAGE_ID,
    CAMPAIGN_D365_ID,
    APPEAL_D365_ID,
    PACKAGE_D365_ID,
    IFF(ARRAY_SIZE(BLOCKERS) = 0, 'RESOLVED_IN_EXTRACT', 'HOLD') AS STATUS,
    ARRAY_TO_STRING(BLOCKERS, ', ') AS BLOCKERS,
    IFF(
        ARRAY_SIZE(BLOCKERS) = 0,
        OBJECT_CONSTRUCT(
            'msnfp_OriginatingCampaignId@odata.bind',
                IFF(RE_CAMPAIGN_ID IS NOT NULL, '/campaigns(' || CAMPAIGN_D365_ID || ')', NULL),
            'msnfp_AppealId@odata.bind',
                IFF(RE_APPEAL_ID IS NOT NULL, '/msnfp_appeals(' || APPEAL_D365_ID || ')', NULL),
            'msnfp_PackageId@odata.bind',
                IFF(RE_PACKAGE_ID IS NOT NULL, '/msnfp_packages(' || PACKAGE_D365_ID || ')', NULL)
        ),
        NULL
    ) AS DRAFT_ATTRIBUTION
FROM CHECKED;
