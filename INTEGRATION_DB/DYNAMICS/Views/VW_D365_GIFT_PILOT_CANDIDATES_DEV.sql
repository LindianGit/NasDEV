CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_GIFT_PILOT_CANDIDATES_DEV AS

-- Candidate selection only. A live Dynamics duplicate check is still required.
-- Split attribution is permitted only for the approved single-Gift DEV pilot.
WITH GIFT_COUNTS AS (
    SELECT ID, COUNT(*) AS ROWS_PER_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_GIFTS
    WHERE ID IS NOT NULL
    GROUP BY ID
),

SPLIT_COUNTS AS (
    SELECT ID, COUNT(*) AS ROWS_PER_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_GIFTSPLITS
    WHERE ID IS NOT NULL
    GROUP BY ID
),

GIFT_TYPE_MAP AS (
    SELECT RE_GIFT_TYPE_CODE, COUNT(DISTINCT D365_TARGET) AS TARGET_COUNT
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_REF_GIFT_TYPE
    GROUP BY RE_GIFT_TYPE_CODE
),

MAPPED AS (
    SELECT
        T.RE_GIFT_ID,
        T.RE_IMPORT_ID,
        T.RE_GIFT_DATE,
        T.RE_AMOUNT,
        T.DONOR_TYPE,
        T.DONOR_D365_ID,
        T.POSSIBLE_MATCHES_BY_GIFT_ID,
        T.POSSIBLE_MATCHES_BY_IMPORT_ID,
        L.RE_SPLIT_ID,
        L.RE_SPLIT_AMOUNT,
        L.DESIGNATION_D365_ID,
        A.CAMPAIGN_D365_ID,
        A.APPEAL_D365_ID,
        A.PACKAGE_D365_ID,
        A.DRAFT_ATTRIBUTION,
        TRY_TO_DATE(LEFT(TRIM(T.RE_GIFT_DATE), 10), 'YYYY-MM-DD') AS BOOK_DATE,
        TRY_TO_DECIMAL(TO_VARCHAR(T.RE_AMOUNT), 38, 2) AS GIFT_AMOUNT,
        TRY_TO_DECIMAL(TO_VARCHAR(L.RE_SPLIT_AMOUNT), 38, 2) AS SPLIT_AMOUNT
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_MSNFP_TRANSACTION AS T
    INNER JOIN INTEGRATION_DB.DYNAMICS.VW_D365_MSNFP_DESIGNATEDCREDIT AS L
        ON T.RE_GIFT_ID = L.RE_GIFT_ID
    INNER JOIN GIFT_COUNTS AS G
        ON T.RE_GIFT_ID = G.ID AND G.ROWS_PER_ID = 1
    INNER JOIN SPLIT_COUNTS AS S
        ON L.RE_SPLIT_ID = S.ID AND S.ROWS_PER_ID = 1
    INNER JOIN GIFT_TYPE_MAP AS M
        ON T.RE_GIFT_TYPE_CODE = M.RE_GIFT_TYPE_CODE AND M.TARGET_COUNT = 1
    LEFT JOIN INTEGRATION_DB.DYNAMICS.VW_D365_GIFT_PILOT_ATTRIBUTION_DEV AS A
        ON L.RE_GIFT_ID = A.RE_GIFT_ID AND L.RE_SPLIT_ID = A.RE_SPLIT_ID
    WHERE T.RE_GIFT_TYPE_CODE = 1
      AND T.D365_TARGET = 'TRANSACTION'
      AND T.SPLIT_COUNT = 1
      AND T.DONOR_TYPE IN ('contact', 'account')
      AND T.DONOR_D365_ID IS NOT NULL
      AND L.PARENT_ROWS = 1
      AND L.PARENT_TARGET = 'TRANSACTION'
      AND L.DESIGNATION_D365_ID IS NOT NULL
      AND (
          (L.RE_CAMPAIGN_ID IS NULL
           AND L.RE_APPEAL_ID IS NULL
           AND L.RE_PACKAGE_ID IS NULL)
          OR (
              T.RE_GIFT_ID = 50628
              AND L.RE_SPLIT_ID = 213112
              AND A.STATUS = 'RESOLVED_IN_EXTRACT'
          )
      )
      AND NULLIF(TRIM(TO_VARCHAR(T.RE_CONSTITUENT_ID)), '') IS NOT NULL
      AND TRIM(TO_VARCHAR(T.RE_CONSTITUENT_ID)) =
          TRIM(TO_VARCHAR(L.RE_CONSTITUENT_ID))
      AND REGEXP_LIKE(TO_VARCHAR(T.RE_GIFT_ID), '[0-9]+')
      AND REGEXP_LIKE(TO_VARCHAR(L.RE_SPLIT_ID), '[0-9]+')
      AND REGEXP_LIKE(TO_VARCHAR(T.RE_AMOUNT), '[0-9]+([.][0-9]{1,2})?')
      AND REGEXP_LIKE(TO_VARCHAR(L.RE_SPLIT_AMOUNT), '[0-9]+([.][0-9]{1,2})?')
)

SELECT
    RE_GIFT_ID,
    RE_IMPORT_ID,
    RE_SPLIT_ID,
    BOOK_DATE,
    GIFT_AMOUNT,
    SPLIT_AMOUNT,
    DONOR_TYPE,
    DONOR_D365_ID,
    DESIGNATION_D365_ID,
    CAMPAIGN_D365_ID,
    APPEAL_D365_ID,
    PACKAGE_D365_ID,
    DRAFT_ATTRIBUTION
FROM MAPPED
WHERE BOOK_DATE IS NOT NULL
  AND GIFT_AMOUNT > 0
  AND GIFT_AMOUNT = SPLIT_AMOUNT
  AND POSSIBLE_MATCHES_BY_GIFT_ID = 0
  AND COALESCE(POSSIBLE_MATCHES_BY_IMPORT_ID, 0) = 0
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.XREF AS X
      WHERE X.SOURCE_SYSTEM = 'DYNAMICS'
        AND X.GOLDEN_RECORD_ID IN (
            'TRANSACTION:' || TO_VARCHAR(MAPPED.RE_GIFT_ID),
            'DESIGNATEDCREDIT:' || TO_VARCHAR(MAPPED.RE_SPLIT_ID)
        )
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.GIFT_D365_IDENTITY AS I
      WHERE (I.ENTITY_ID = 'TRANSACTION'
             AND I.SOURCE_RECORD_ID = TO_VARCHAR(MAPPED.RE_GIFT_ID))
         OR (I.ENTITY_ID = 'DESIGNATEDCREDIT'
             AND I.SOURCE_RECORD_ID = TO_VARCHAR(MAPPED.RE_SPLIT_ID))
  );
