CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_GIFT_REQUESTS AS

-- This outbox is separate from the shared dispatcher, which performs ordinary
-- PATCH updates. Gift creates require If-None-Match: * and ID capture.
WITH SOURCE_REQUESTS AS (
    SELECT
        M.PIPELINE_ID,
        M.SOURCE_INSTANCE,
        M.ENTITY_ID,
        TO_VARCHAR(T.RE_GIFT_ID) AS SOURCE_RECORD_ID,
        TO_VARCHAR(T.RE_GIFT_ID) AS RE_GIFT_ID,
        M.API_BASE_URL,
        'msnfp_transactions' AS ENTITY_SET,
        T.PAYLOAD AS REQUEST_BODY
    FROM AUDIT_DB.CONFIG.PIPELINE_METADATA AS M
    CROSS JOIN INTEGRATION_DB.DYNAMICS.VW_D365_MSNFP_TRANSACTION AS T
    WHERE M.PIPELINE_ID = 'D365_GIFT_WRITEBACK'
      AND M.ENTITY_ID = 'TRANSACTION'
      AND M.ENABLED
      AND M.API_BASE_URL IS NOT NULL
      AND T.RE_GIFT_ID IS NOT NULL
      AND T.LOAD_ACTION = 'CREATE'
      AND T.HOLD_REASON IS NULL
      AND T.PAYLOAD IS NOT NULL
      -- Do not enable until existing-record checks, reconciliation and the
      -- conditional-create dispatcher have been validated.
      AND FALSE

    UNION ALL

    SELECT
        M.PIPELINE_ID,
        M.SOURCE_INSTANCE,
        M.ENTITY_ID,
        TO_VARCHAR(D.RE_SPLIT_ID) AS SOURCE_RECORD_ID,
        TO_VARCHAR(D.RE_GIFT_ID) AS RE_GIFT_ID,
        M.API_BASE_URL,
        'msnfp_designatedcredits' AS ENTITY_SET,
        D.PAYLOAD AS REQUEST_BODY
    FROM AUDIT_DB.CONFIG.PIPELINE_METADATA AS M
    CROSS JOIN INTEGRATION_DB.DYNAMICS.VW_D365_MSNFP_DESIGNATEDCREDIT AS D
    WHERE M.PIPELINE_ID = 'D365_GIFT_WRITEBACK'
      AND M.ENTITY_ID = 'DESIGNATEDCREDIT'
      AND M.ENABLED
      AND M.API_BASE_URL IS NOT NULL
      AND D.RE_SPLIT_ID IS NOT NULL
      AND D.RE_GIFT_ID IS NOT NULL
      AND D.LOAD_ACTION = 'CREATE'
      AND D.HOLD_REASON IS NULL
      AND D.PAYLOAD IS NOT NULL
      AND D.TRANSACTION_D365_ID IS NOT NULL
      AND FALSE
),

KEYED AS (
    SELECT
        *,
        ENTITY_ID || ':' || SOURCE_RECORD_ID AS GOLDEN_RECORD_ID,
        -- This namespace and name format must not change after a deployment.
        UUID_STRING(
            '6ba7b810-9dad-11d1-80b4-00c04fd430c8',
            'nas:raisers_edge:' || LOWER(ENTITY_ID) || ':' || SOURCE_RECORD_ID
        ) AS TARGET_GUID
    FROM SOURCE_REQUESTS
    QUALIFY COUNT(*) OVER (
        PARTITION BY PIPELINE_ID, SOURCE_INSTANCE, ENTITY_ID, SOURCE_RECORD_ID
    ) = 1
)

SELECT
    K.PIPELINE_ID,
    K.SOURCE_INSTANCE,
    K.ENTITY_ID,
    K.SOURCE_RECORD_ID,
    K.RE_GIFT_ID,
    K.GOLDEN_RECORD_ID,
    K.TARGET_GUID,
    RTRIM(K.API_BASE_URL, '/') || '/' || K.ENTITY_SET ||
        '(' || K.TARGET_GUID || ')' AS REQUEST_URL,
    K.REQUEST_BODY,
    MD5(TO_VARCHAR(K.REQUEST_BODY)) AS PAYLOAD_MD5
FROM KEYED AS K
WHERE NOT EXISTS (
    SELECT 1
    FROM MDM_DB.GOLD.XREF AS X
    WHERE X.GOLDEN_RECORD_ID = K.GOLDEN_RECORD_ID
      AND X.SOURCE_SYSTEM = 'DYNAMICS'
)
AND NOT EXISTS (
    SELECT 1
    FROM MDM_DB.GOLD.GIFT_D365_IDENTITY AS I
    WHERE I.ENTITY_ID = K.ENTITY_ID
      AND I.SOURCE_RECORD_ID = K.SOURCE_RECORD_ID
);
