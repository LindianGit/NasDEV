CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_HISTORICACTIVITY_PILOT_PREVIEW_DEV AS

-- Read-only technical preview. Subject and source ID are provisional.
-- Midnight UTC is a pilot date choice, not an approved full-load rule.
WITH SOURCE AS (
    SELECT
        ID AS RE_ACTION_ID,
        TRIM(CONSTITUENTID) AS RE_CONSTITUENT_ID,
        TRY_TO_DATE(LEFT(TRIM(DATE), 10)) AS ACTIVITY_DATE,
        COUNT(*) OVER () AS SOURCE_ROWS
    FROM RAW.RAISERS_EDGE.VW_ODS_T_ACTIONS
    WHERE ID = 24
),
PILOT AS (
    SELECT DISTINCT
        S.RE_ACTION_ID,
        S.ACTIVITY_DATE,
        LOWER(NULLIF(TRIM(G.D365_ACCOUNT_ID), '')) AS D365_ACCOUNT_ID
    FROM SOURCE S
    JOIN INTEGRATION_DB.DYNAMICS.VW_D365_HISTORICACTIVITY_PILOT_CANDIDATES_DEV C
        ON C.RE_ACTION_ID = S.RE_ACTION_ID
       AND C.CUSTOMER_TYPE = 'ACCOUNT'
    JOIN MDM_DB.GOLD.XREF X
        ON X.SOURCE_SYSTEM = 'RAISERS_EDGE'
       AND TRIM(X.SOURCE_RECORD_ID) = S.RE_CONSTITUENT_ID
    JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS G
        ON G.GOLDEN_RECORD_ID = X.GOLDEN_RECORD_ID
    WHERE S.SOURCE_ROWS = 1
      AND S.ACTIVITY_DATE IS NOT NULL
      AND G.IS_GDPR_SUPPRESSED = FALSE
      AND NULLIF(TRIM(G.D365_ACCOUNT_ID), '') IS NOT NULL
)
SELECT
    RE_ACTION_ID,
    ACTIVITY_DATE,
    D365_ACCOUNT_ID,
    FALSE AS PREVIEW_DISPATCH_ALLOWED,
    OBJECT_CONSTRUCT(
        'mha_subject', 'RE Action 24',
        'mha_source', 'Raisers Edge',
        'mha_sourceid', '24',
        'mha_activitydate', TO_CHAR(ACTIVITY_DATE, 'YYYY-MM-DD') || 'T00:00:00Z',
        'mha_CustomerId_account@odata.bind', '/accounts(' || D365_ACCOUNT_ID || ')'
    ) AS DRAFT_PAYLOAD
FROM PILOT
QUALIFY COUNT(*) OVER (PARTITION BY RE_ACTION_ID) = 1;
