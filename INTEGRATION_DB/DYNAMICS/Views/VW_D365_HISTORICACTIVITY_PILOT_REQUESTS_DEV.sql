CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_HISTORICACTIVITY_PILOT_REQUESTS_DEV AS

-- One notes-free DEV technical pilot. Recheck live duplicates and customer
-- before dispatch; reconcile uncertain POSTs. These guards are not atomic.
WITH PILOT AS (
    SELECT
        'HISTORICACTIVITY:' || TO_VARCHAR(RE_ACTION_ID) AS GOLDEN_RECORD_ID,
        DRAFT_PAYLOAD AS REQUEST_BODY
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_HISTORICACTIVITY_PILOT_PREVIEW_DEV
    WHERE RE_ACTION_ID = 24
      AND ACTIVITY_DATE = DATE '1999-09-01'
      AND D365_ACCOUNT_ID = '199c60cd-02e1-f111-84ea-70a8a575b5fc'
      AND ARRAY_SIZE(OBJECT_KEYS(DRAFT_PAYLOAD)) = 5
      AND DRAFT_PAYLOAD:"mha_subject"::VARCHAR = 'RE Action 24'
      AND DRAFT_PAYLOAD:"mha_source"::VARCHAR = 'Raisers Edge'
      AND DRAFT_PAYLOAD:"mha_sourceid"::VARCHAR = '24'
      AND DRAFT_PAYLOAD:"mha_activitydate"::VARCHAR = '1999-09-01T00:00:00Z'
      AND DRAFT_PAYLOAD:"mha_CustomerId_account@odata.bind"::VARCHAR =
          '/accounts(199c60cd-02e1-f111-84ea-70a8a575b5fc)'
)
SELECT
    'D365_HISTORICACTIVITY_PILOT' AS PIPELINE_ID,
    M.SOURCE_INSTANCE,
    'HISTORICACTIVITY' AS ENTITY_ID,
    P.GOLDEN_RECORD_ID,
    CAST(NULL AS VARCHAR) AS TARGET_GUID,
    'POST' AS HTTP_METHOD,
    M.API_BASE_URL || '/mha_historicactivities' AS REQUEST_URL,
    P.REQUEST_BODY,
    M.AUTH_METHOD,
    M.AUTH_CONFIG,
    MD5(TO_VARCHAR(P.REQUEST_BODY)) AS PAYLOAD_MD5
FROM AUDIT_DB.CONFIG.PIPELINE_METADATA AS M
CROSS JOIN PILOT AS P
WHERE M.PIPELINE_ID = 'D365_WRITEBACK'
  AND M.SOURCE_INSTANCE = 'SNOWFLAKE_DEV'
  AND M.ENTITY_ID = 'CAMPAIGN'
  AND M.API_BASE_URL = 'https://nasdatamig.crm11.dynamics.com/api/data/v9.2'
  AND NOT EXISTS (
      SELECT 1
      FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE AS S
      WHERE S.ENTITY_ID = 'HISTORICACTIVITY'
        AND S.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.XREF AS X
      WHERE X.SOURCE_SYSTEM = 'DYNAMICS'
        AND X.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
  )
QUALIFY COUNT(*) OVER (PARTITION BY P.GOLDEN_RECORD_ID) = 1;
