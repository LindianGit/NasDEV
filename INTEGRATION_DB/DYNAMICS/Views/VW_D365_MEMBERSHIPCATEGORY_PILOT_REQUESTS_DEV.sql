CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_MEMBERSHIPCATEGORY_PILOT_REQUESTS_DEV AS

-- One DEV pilot only. The live Dynamics check found no Individual Life row.
-- Amount and duration remain unmapped; this request creates the name only.
WITH PILOT AS (
    SELECT
        'MEMBERSHIPCATEGORY:2113' AS GOLDEN_RECORD_ID,
        OBJECT_CONSTRUCT('msnfp_name', 'Individual Life') AS REQUEST_BODY
    WHERE EXISTS (
        SELECT 1
        FROM RAW.RAISERS_EDGE.VW_ODS_T_MEMBERSHIP
        WHERE MEMBERSHIPCATEGORYCODE = 2113
          AND UPPER(TRIM(MEMBERSHIPCATEGORYDESCRIPTION)) = 'INDIVIDUAL LIFE'
    )
      AND (
          SELECT COUNT(DISTINCT TRIM(MEMBERSHIPCATEGORYDESCRIPTION))
          FROM RAW.RAISERS_EDGE.VW_ODS_T_MEMBERSHIP
          WHERE MEMBERSHIPCATEGORYCODE = 2113
            AND NULLIF(TRIM(MEMBERSHIPCATEGORYDESCRIPTION), '') IS NOT NULL
      ) = 1
)
SELECT
    'D365_MEMBERSHIPCATEGORY_PILOT' AS PIPELINE_ID,
    M.SOURCE_INSTANCE,
    'MEMBERSHIPCATEGORY' AS ENTITY_ID,
    P.GOLDEN_RECORD_ID,
    CAST(NULL AS VARCHAR) AS TARGET_GUID,
    'POST' AS HTTP_METHOD,
    M.API_BASE_URL || '/msnfp_membershipcategories' AS REQUEST_URL,
    P.REQUEST_BODY,
    M.AUTH_METHOD,
    M.AUTH_CONFIG,
    MD5(TO_VARCHAR(P.REQUEST_BODY)) AS PAYLOAD_MD5
FROM AUDIT_DB.CONFIG.PIPELINE_METADATA AS M
CROSS JOIN PILOT AS P
WHERE M.PIPELINE_ID = 'D365_WRITEBACK'
  AND M.SOURCE_INSTANCE = 'SNOWFLAKE_DEV'
  AND M.ENTITY_ID = 'CAMPAIGN'
  AND M.API_BASE_URL = 'https://nasdatamig.crm11.dynamics.com/api/data/v9.2'
  AND NOT EXISTS (
      SELECT 1
      FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE AS S
      WHERE S.ENTITY_ID = 'MEMBERSHIPCATEGORY'
        AND S.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.XREF AS X
      WHERE X.SOURCE_SYSTEM = 'DYNAMICS'
        AND X.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
  )
QUALIFY COUNT(*) OVER (PARTITION BY P.GOLDEN_RECORD_ID) = 1;
