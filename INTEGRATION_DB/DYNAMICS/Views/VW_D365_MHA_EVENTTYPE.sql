CREATE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_MHA_EVENTTYPE AS

-- DEV preview: Community is temporary for every type pending business review.
-- This view does not dispatch requests or update existing Dynamics records.
WITH CATEGORY_POLICY AS (
    SELECT ARRAY_CONSTRUCT(
        -- the default is that no event types are considered charity types.
        -- Add approved Charity type names in uppercase, e.g. 'SPONSORED RUN'.
    ) AS CHARITY_TYPES
),
RE_TYPES AS (
    SELECT
        TRIM(TYPEDESCRIPTION) AS RE_EVENT_TYPE,
        COUNT(*) AS EVENT_COUNT,
        COUNT(*) OVER (
            PARTITION BY UPPER(TRIM(TYPEDESCRIPTION))
        ) AS RE_NAME_VARIANTS
    FROM RAW.RAISERS_EDGE.VW_ODS_T_EVENTS
    WHERE NULLIF(TRIM(TYPEDESCRIPTION), '') IS NOT NULL
    GROUP BY TRIM(TYPEDESCRIPTION)
),
D365_TYPES AS (
    SELECT
        UPPER(TRIM(MHA_NAME)) AS NAME_KEY,
        COUNT(*) AS MATCH_COUNT,
        MIN(MHA_EVENTTYPEID) AS D365_ID
    FROM RAW.DYNAMICS.VW_ODS_MHA_EVENTTYPES
    WHERE NULLIF(TRIM(MHA_NAME), '') IS NOT NULL
    GROUP BY UPPER(TRIM(MHA_NAME))
)
SELECT
    R.RE_EVENT_TYPE,
    R.EVENT_COUNT,
    R.RE_NAME_VARIANTS,
    IFF(D.MATCH_COUNT = 1, D.D365_ID, NULL) AS D365_ID,
    COALESCE(D.MATCH_COUNT, 0) AS D365_MATCH_COUNT,
    CASE
        WHEN R.RE_NAME_VARIANTS > 1 THEN 'HOLD'
        WHEN D.MATCH_COUNT > 1 THEN 'HOLD'
        WHEN D.MATCH_COUNT = 1 THEN 'EXISTS'
        ELSE 'HOLD'
    END AS LOAD_ACTION,
    CASE
        WHEN R.RE_NAME_VARIANTS > 1 THEN 'AMBIGUOUS_RE_NAME'
        WHEN D.MATCH_COUNT > 1 THEN 'DUPLICATE_DYNAMICS_NAME'
        WHEN D.MATCH_COUNT = 1 THEN NULL
        WHEN LENGTH(R.RE_EVENT_TYPE) > 100 THEN 'NAME_TOO_LONG'
        ELSE 'DEV_PREVIEW_ONLY'
    END AS HOLD_REASON,
    OBJECT_CONSTRUCT(
        'mha_name', R.RE_EVENT_TYPE,
        'mha_eventcategory', IFF(
            ARRAY_CONTAINS(TO_VARIANT(UPPER(R.RE_EVENT_TYPE)), P.CHARITY_TYPES),
            862940000,
            862940001
        )
    ) AS PAYLOAD
FROM RE_TYPES AS R
CROSS JOIN CATEGORY_POLICY AS P
LEFT JOIN D365_TYPES AS D
    ON UPPER(R.RE_EVENT_TYPE) = D.NAME_KEY;
