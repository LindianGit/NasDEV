CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_MSNFP_MEMBERSHIP AS
WITH PARTY AS (
    SELECT
        X.SOURCE_RECORD_ID AS RE_CONSTITUENT_ID,
        COUNT(DISTINCT X.GOLDEN_RECORD_ID) AS GOLDEN_RECORDS,
        COUNT(DISTINCT NULLIF(LOWER(TRIM(G.D365_CONTACT_ID)), '')) AS CONTACT_IDS,
        COUNT(DISTINCT NULLIF(LOWER(TRIM(G.D365_ACCOUNT_ID)), '')) AS ACCOUNT_IDS,
        MIN(NULLIF(LOWER(TRIM(G.D365_CONTACT_ID)), '')) AS CONTACT_ID,
        MIN(NULLIF(LOWER(TRIM(G.D365_ACCOUNT_ID)), '')) AS ACCOUNT_ID,
        COUNT_IF(G.GOLDEN_RECORD_ID IS NULL OR G.IS_GDPR_SUPPRESSED IS NULL)
            AS UNKNOWN_GDPR,
        COUNT_IF(G.IS_GDPR_SUPPRESSED = TRUE) AS SUPPRESSED
    FROM MDM_DB.GOLD.XREF X
    LEFT JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS G
        ON X.GOLDEN_RECORD_ID = G.GOLDEN_RECORD_ID
    WHERE X.SOURCE_SYSTEM = 'RAISERS_EDGE'
    GROUP BY X.SOURCE_RECORD_ID
),

CATEGORIES AS (
    SELECT
        UPPER(TRIM(MSNFP_NAME)) AS NAME_KEY,
        COUNT(*) AS MATCHES,
        COUNT_IF(STATECODE = 0) AS ACTIVE_MATCHES,
        MIN(MSNFP_MEMBERSHIPCATEGORYID) AS CATEGORY_ID
    FROM RAW.DYNAMICS.VW_ODS_MSNFP_MEMBERSHIPCATEGORIES
    WHERE NULLIF(TRIM(MSNFP_NAME), '') IS NOT NULL
    GROUP BY UPPER(TRIM(MSNFP_NAME))
),

STATUS_OPTIONS AS (
    SELECT
        UPPER(TRIM(OPTION_LABEL)) AS STATUS_LABEL,
        COUNT(*) AS MATCHES,
        MIN(STATE) AS STATECODE,
        MIN(OPTION_VALUE) AS STATUSCODE
    FROM RAW.DYNAMICS.VW_ODS_METADATA_OPTIONS
    WHERE ENTITY_LOGICALNAME = 'msnfp_membership'
      AND ATTRIBUTE_LOGICALNAME = 'statuscode'
      AND NULLIF(TRIM(OPTION_LABEL), '') IS NOT NULL
    GROUP BY UPPER(TRIM(OPTION_LABEL))
),

CAPTURED_MEMBERSHIPS AS (
    SELECT
        GOLDEN_RECORD_ID,
        COUNT(DISTINCT LOWER(TRIM(SOURCE_RECORD_ID))) AS MATCHES,
        MIN(LOWER(TRIM(SOURCE_RECORD_ID))) AS D365_ID
    FROM MDM_DB.GOLD.XREF
    WHERE SOURCE_SYSTEM = 'DYNAMICS'
      AND GOLDEN_RECORD_ID LIKE 'MEMBERSHIP:%'
      AND NULLIF(TRIM(SOURCE_RECORD_ID), '') IS NOT NULL
    GROUP BY GOLDEN_RECORD_ID
),

TARGET_MEMBERSHIPS AS (
    SELECT
        LOWER(TRIM(MSNFP_MEMBERSHIPID)) AS ID_KEY,
        COUNT(*) AS MATCHES
    FROM RAW.DYNAMICS.VW_ODS_MSNFP_MEMBERSHIPS
    WHERE NULLIF(TRIM(MSNFP_MEMBERSHIPID), '') IS NOT NULL
    GROUP BY LOWER(TRIM(MSNFP_MEMBERSHIPID))
),

GATES AS (
    SELECT NULLIF(
        LISTAGG(GATE_CODE, ',') WITHIN GROUP (ORDER BY GATE_CODE), ''
    ) AS GATE_CODES
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_REF_LOAD_GATE
    WHERE D365_TABLE = 'msnfp_membership'
      AND IS_OPEN
      AND ROW_CONDITION_KEY IS NULL
),

SOURCE_ROWS AS (
    SELECT
        M.*,
        COUNT(*) OVER (PARTITION BY M.ID) AS SOURCE_ID_ROWS,
        -- This namespace is permanent: changing it would change every target ID.
        UUID_STRING(
            '87fdf52c-0b67-4855-a275-cc264d55e1dc',
            'MEMBERSHIP:' || TO_VARCHAR(M.ID)
        ) AS PLANNED_D365_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_MEMBERSHIP M
),

-- Replace placeholders only after approval. NO_EXISTING_MEMBERSHIP must be
-- derived from an agreed reconciliation, not set to TRUE for every row.
-- Do not set DISPATCH_SAFETY_VERIFIED until stable-ID creation and recovery
-- after uncertain outcomes have been tested in the target environment.
BUSINESS_MAPPINGS AS (
    SELECT
        M.*,
        NULL::VARCHAR AS MEMBERSHIP_NAME,
        NULL::VARCHAR AS SUBCATEGORY_D365_ID,
        NULL::VARCHAR AS ADDITIONAL_MEMBER_D365_ID,
        NULL::VARCHAR AS ADDITIONAL_MEMBER_TYPE,
        NULL::BOOLEAN AS COMMUNICATION_PREFERENCE,
        NULL::NUMBER AS DIFFERENCE_MONTHS,
        NULL::VARCHAR AS GIFTER_D365_ID,
        NULL::DATE AS RECORD_CREATED_DATE,
        NULL::BOOLEAN AS NO_EXISTING_MEMBERSHIP,
        FALSE AS BUSINESS_MAPPINGS_APPROVED,
        FALSE AS DISPATCH_SAFETY_VERIFIED
    FROM SOURCE_ROWS M
),

RESOLVED AS (
    SELECT
        M.*,
        'MEMBERSHIP:' || TO_VARCHAR(M.ID) AS GOLDEN_RECORD_ID,
        X.MATCHES AS XREF_MATCHES,
        X.D365_ID,
        T.MATCHES AS PLANNED_ID_MATCHES,
        P.GOLDEN_RECORDS,
        P.CONTACT_IDS,
        P.ACCOUNT_IDS,
        P.UNKNOWN_GDPR,
        P.SUPPRESSED,
        CASE
            WHEN P.CONTACT_IDS = 1 AND P.ACCOUNT_IDS = 0 THEN 'contact'
            WHEN P.ACCOUNT_IDS = 1 AND P.CONTACT_IDS = 0 THEN 'account'
        END AS CUSTOMER_TYPE,
        CASE
            WHEN P.CONTACT_IDS = 1 AND P.ACCOUNT_IDS = 0 THEN P.CONTACT_ID
            WHEN P.ACCOUNT_IDS = 1 AND P.CONTACT_IDS = 0 THEN P.ACCOUNT_ID
        END AS CUSTOMER_D365_ID,
        C.MATCHES AS CATEGORY_MATCHES,
        C.ACTIVE_MATCHES AS CATEGORY_ACTIVE_MATCHES,
        C.CATEGORY_ID,
        S.MATCHES AS STATUS_MATCHES,
        S.STATECODE,
        S.STATUSCODE,
        TRY_TO_DATE(LEFT(TRIM(M.DATESTART), 10)) AS START_DATE,
        TRY_TO_DATE(LEFT(TRIM(M.DATEFINISH), 10)) AS END_DATE,
        G.GATE_CODES
    FROM BUSINESS_MAPPINGS M
    LEFT JOIN PARTY P ON TRIM(M.CONSTITUENTID) = P.RE_CONSTITUENT_ID
    LEFT JOIN CATEGORIES C
        ON UPPER(TRIM(M.MEMBERSHIPCATEGORYDESCRIPTION)) = C.NAME_KEY
    LEFT JOIN STATUS_OPTIONS S ON UPPER(TRIM(M.STANDING)) = S.STATUS_LABEL
    LEFT JOIN CAPTURED_MEMBERSHIPS X
        ON X.GOLDEN_RECORD_ID = 'MEMBERSHIP:' || TO_VARCHAR(M.ID)
    LEFT JOIN TARGET_MEMBERSHIPS T
        ON LOWER(M.PLANNED_D365_ID) = T.ID_KEY
    CROSS JOIN GATES G
),

REASONED AS (
    SELECT
        *,
        NULLIF(ARRAY_TO_STRING(ARRAY_CONSTRUCT_COMPACT(
            IFF(ID IS NULL OR SOURCE_ID_ROWS <> 1, 'INVALID_OR_DUPLICATE_RE_ID', NULL),
            IFF(XREF_MATCHES > 1, 'MULTIPLE_MEMBERSHIP_XREFS', NULL),
            IFF(XREF_MATCHES = 1 AND NOT REGEXP_LIKE(
                D365_ID, '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
            ), 'INVALID_MEMBERSHIP_XREF', NULL),
            IFF(COALESCE(PLANNED_ID_MATCHES, 0) > 0, 'PLANNED_D365_ID_EXISTS_RECONCILE', NULL),
            IFF(GATE_CODES IS NOT NULL, 'GATE:' || GATE_CODES, NULL),
            IFF(COALESCE(GOLDEN_RECORDS, 0) <> 1, 'CUSTOMER_XREF_NOT_UNIQUE', NULL),
            IFF(COALESCE(UNKNOWN_GDPR, 0) > 0 OR GOLDEN_RECORDS IS NULL, 'GDPR_STATUS_UNKNOWN', NULL),
            IFF(COALESCE(SUPPRESSED, 0) > 0, 'GDPR_SUPPRESSED', NULL),
            IFF(COALESCE(CONTACT_IDS, 0) + COALESCE(ACCOUNT_IDS, 0) <> 1, 'CUSTOMER_ID_NOT_UNIQUE', NULL),
            IFF(CUSTOMER_D365_ID IS NOT NULL AND NOT REGEXP_LIKE(
                CUSTOMER_D365_ID, '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
            ), 'CUSTOMER_ID_INVALID', NULL),
            IFF(COALESCE(CATEGORY_MATCHES, 0) <> 1 OR COALESCE(CATEGORY_ACTIVE_MATCHES, 0) <> 1, 'CATEGORY_NOT_UNIQUE_ACTIVE', NULL),
            IFF(CATEGORY_MATCHES = 1 AND (CATEGORY_ID IS NULL OR NOT REGEXP_LIKE(
                LOWER(TRIM(CATEGORY_ID)), '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
            )), 'CATEGORY_ID_INVALID', NULL),
            IFF(COALESCE(STATUS_MATCHES, 0) <> 1 OR STATECODE IS NULL OR STATUSCODE IS NULL, 'STATUS_MAPPING_MISSING', NULL),
            IFF(START_DATE IS NULL, 'START_DATE_MISSING_OR_INVALID', NULL),
            IFF(END_DATE IS NULL, 'END_DATE_MISSING_OR_INVALID', NULL),
            IFF(NULLIF(TRIM(MEMBERSHIP_NAME), '') IS NULL, 'MEMBERSHIP_NAME_MAPPING_PENDING', NULL),
            IFF(SUBCATEGORY_D365_ID IS NULL, 'SUBCATEGORY_MAPPING_PENDING', NULL),
            IFF(SUBCATEGORY_D365_ID IS NOT NULL AND NOT REGEXP_LIKE(
                LOWER(TRIM(SUBCATEGORY_D365_ID)), '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
            ), 'SUBCATEGORY_ID_INVALID', NULL),
            IFF(NO_EXISTING_MEMBERSHIP IS DISTINCT FROM TRUE, 'EXISTING_RECORD_CHECK_PENDING', NULL),
            IFF(NOT BUSINESS_MAPPINGS_APPROVED, 'BUSINESS_MAPPINGS_PENDING', NULL),
            IFF(NOT DISPATCH_SAFETY_VERIFIED, 'DISPATCH_SAFETY_PENDING', NULL)
        ), ','), '') AS PENDING_REASONS
    FROM RESOLVED
)

SELECT
    ID AS RE_MEMBERSHIP_ID,
    CONSTITUENTID AS RE_CONSTITUENT_ID,
    USERDEFINEDMEMBERID AS RE_USER_DEFINED_MEMBER_ID,
    MEMBERSHIPCATEGORYDESCRIPTION AS RE_CATEGORY,
    MEMBERSHIPSUBCATEGORYDESCRIPTION AS RE_SUBCATEGORY,
    STANDING AS RE_STANDING,
    GOLDEN_RECORD_ID,
    D365_ID,
    PLANNED_D365_ID,
    CASE
        WHEN ID IS NULL OR SOURCE_ID_ROWS <> 1 THEN 'HOLD'
        WHEN XREF_MATCHES = 1 AND NOT REGEXP_LIKE(
            D365_ID, '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
        ) THEN 'HOLD'
        WHEN XREF_MATCHES = 1 THEN 'EXISTS'
        WHEN PENDING_REASONS IS NOT NULL THEN 'HOLD'
        ELSE 'CREATE'
    END AS LOAD_ACTION,
    CASE
        WHEN ID IS NULL OR SOURCE_ID_ROWS <> 1 THEN PENDING_REASONS
        WHEN XREF_MATCHES = 1 AND NOT REGEXP_LIKE(
            D365_ID, '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
        ) THEN PENDING_REASONS
        WHEN XREF_MATCHES = 1 THEN NULL
        ELSE PENDING_REASONS
    END AS HOLD_REASON,
    OBJECT_CONSTRUCT(
        'msnfp_membershipid', PLANNED_D365_ID,
        'msnfp_name', MEMBERSHIP_NAME,
        'msnfp_customer_contact@odata.bind', IFF(
            CUSTOMER_TYPE = 'contact', '/contacts(' || CUSTOMER_D365_ID || ')', NULL
        ),
        'msnfp_customer_account@odata.bind', IFF(
            CUSTOMER_TYPE = 'account', '/accounts(' || CUSTOMER_D365_ID || ')', NULL
        ),
        'msnfp_MembershipCategoryId@odata.bind', IFF(
            CATEGORY_MATCHES = 1 AND CATEGORY_ACTIVE_MATCHES = 1,
            '/msnfp_membershipcategories(' || CATEGORY_ID || ')', NULL
        ),
        'mhnas_SubCategory@odata.bind', IFF(
            SUBCATEGORY_D365_ID IS NOT NULL,
            '/mhnas_membershipsubcategories(' || SUBCATEGORY_D365_ID || ')', NULL
        ),
        'mhnas_AdditionalMember_contact@odata.bind', IFF(
            ADDITIONAL_MEMBER_TYPE = 'contact',
            '/contacts(' || ADDITIONAL_MEMBER_D365_ID || ')', NULL
        ),
        'mhnas_AdditionalMember_account@odata.bind', IFF(
            ADDITIONAL_MEMBER_TYPE = 'account',
            '/accounts(' || ADDITIONAL_MEMBER_D365_ID || ')', NULL
        ),
        'mhnas_communicationpreference', COMMUNICATION_PREFERENCE,
        'mhnas_differencemonths', DIFFERENCE_MONTHS,
        'msnfp_startdate', TO_CHAR(START_DATE, 'YYYY-MM-DD'),
        'msnfp_enddate', TO_CHAR(END_DATE, 'YYYY-MM-DD'),
        'overriddencreatedon', TO_CHAR(RECORD_CREATED_DATE, 'YYYY-MM-DD'),
        'statecode', IFF(STATUS_MATCHES = 1, STATECODE, NULL),
        'statuscode', IFF(STATUS_MATCHES = 1, STATUSCODE, NULL)
    ) AS PAYLOAD
FROM REASONED;
