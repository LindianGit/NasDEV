CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_PACKAGE_PILOT_PREVIEW_DEV AS

-- Read-only preparation for Package 71, Appeal 1359 and Campaign 6.
-- These draft fields are not dispatchable; the parent bindings are not included.
WITH PILOT AS (
    SELECT
        P.RE_PACKAGE_ID,
        P.RE_APPEAL_ID,
        A.RE_CAMPAIGN_ID,
        C.RE_CAMPAIGN_CODE,
        P.PAYLOAD AS DRAFT_PACKAGE_FIELDS,
        A.PAYLOAD AS DRAFT_APPEAL_FIELDS,
        C.PAYLOAD AS DRAFT_CAMPAIGN_FIELDS,
        P.HOLD_REASON AS PACKAGE_HOLD_REASON,
        A.HOLD_REASON AS APPEAL_HOLD_REASON,
        C.HOLD_REASON AS CAMPAIGN_HOLD_REASON,
        COUNT(*) OVER () AS JOIN_ROWS
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_MSNFP_PACKAGE P
    JOIN INTEGRATION_DB.DYNAMICS.VW_D365_MSNFP_APPEAL A
        ON P.RE_APPEAL_ID = A.RE_APPEAL_ID
    JOIN INTEGRATION_DB.DYNAMICS.VW_D365_CAMPAIGN C
        ON A.RE_CAMPAIGN_ID = C.RE_CAMPAIGN_ID
    WHERE P.RE_PACKAGE_ID = 71
)
SELECT
    *,
    CASE
        WHEN JOIN_ROWS <> 1 THEN 'HOLD_SOURCE_OR_JOIN_NOT_UNIQUE'
        WHEN RE_APPEAL_ID <> 1359 OR RE_CAMPAIGN_ID <> 6
            OR COALESCE(RE_CAMPAIGN_CODE, '') <> 'EVENTS'
            THEN 'HOLD_SOURCE_CHAIN_CHANGED'
        ELSE 'HOLD_LIVE_CHECKS_AND_TARGET_REQUIREMENTS'
    END AS PREVIEW_STATUS,
    FALSE AS PREVIEW_DISPATCH_ALLOWED
FROM PILOT;
