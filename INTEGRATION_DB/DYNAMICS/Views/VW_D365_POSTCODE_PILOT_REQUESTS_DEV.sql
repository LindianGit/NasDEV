CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_POSTCODE_PILOT_REQUESTS_DEV AS

-- One approved synthetic DEV test; Name is the only business field sent.
-- Before dispatch, check the live marker and planned GUID for duplicates.
-- No Nation/Cross Border mappings or Contact/Account updates are performed.
-- Reconcile uncertain outcomes, never blindly retry. Guards are not atomic.
WITH PILOT AS (
    SELECT
        TEST_KEY AS GOLDEN_RECORD_ID,
        DRAFT_PAYLOAD AS REQUEST_BODY
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_POSTCODE_PILOT_PREVIEW_DEV
    WHERE TEST_KEY = 'POSTCODE_TEST:DEV-001'
      AND SOURCE_EVIDENCE = 'SYNTHETIC_ONLY'
      AND ARRAY_SIZE(OBJECT_KEYS(DRAFT_PAYLOAD)) = 2
      AND DRAFT_PAYLOAD:"mhnas_postcodeid"::VARCHAR =
          '6d60ded3-97a2-409a-bb8f-d62abb08315d'
      AND DRAFT_PAYLOAD:"mhnas_name"::VARCHAR = 'TEST-POSTCODE-DEV-001'
)
SELECT
    'D365_POSTCODE_PILOT' AS PIPELINE_ID,
    M.SOURCE_INSTANCE,
    'POSTCODE_TEST' AS ENTITY_ID,
    P.GOLDEN_RECORD_ID,
    CAST(NULL AS VARCHAR) AS TARGET_GUID,
    'POST' AS HTTP_METHOD,
    M.API_BASE_URL || '/mhnas_postcodes' AS REQUEST_URL,
    P.REQUEST_BODY,
    M.AUTH_METHOD,
    M.AUTH_CONFIG,
    MD5(TO_VARCHAR(P.REQUEST_BODY)) AS PAYLOAD_MD5
FROM AUDIT_DB.CONFIG.PIPELINE_METADATA M
CROSS JOIN PILOT P
WHERE M.PIPELINE_ID = 'D365_WRITEBACK'
  AND M.SOURCE_INSTANCE = 'SNOWFLAKE_DEV'
  AND M.ENTITY_ID = 'CAMPAIGN'
  AND M.API_BASE_URL = 'https://nasdatamig.crm11.dynamics.com/api/data/v9.2'
  AND NOT EXISTS (
      SELECT 1 FROM AUDIT_DB.MONITORING.POSTCODE_PILOT_TRACKING_DEV
      WHERE TEST_KEY = P.GOLDEN_RECORD_ID
         OR LOWER(TRIM(D365_GUID)) = '6d60ded3-97a2-409a-bb8f-d62abb08315d'
  )
  AND NOT EXISTS (
      SELECT 1 FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE
      WHERE GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
  )
  AND NOT EXISTS (
      SELECT 1 FROM MDM_DB.GOLD.XREF
      WHERE SOURCE_SYSTEM = 'DYNAMICS'
        AND (
            GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
            OR LOWER(TRIM(SOURCE_RECORD_ID)) = '6d60ded3-97a2-409a-bb8f-d62abb08315d'
        )
  )
QUALIFY COUNT(*) OVER (PARTITION BY P.GOLDEN_RECORD_ID) = 1;

GRANT SELECT ON VIEW INTEGRATION_DB.DYNAMICS.VW_D365_POSTCODE_PILOT_PREVIEW_DEV
TO ROLE R_NAS_ETL_DEV;
GRANT SELECT ON VIEW INTEGRATION_DB.DYNAMICS.VW_D365_POSTCODE_PILOT_REQUESTS_DEV
TO ROLE R_NAS_ETL_DEV;
