CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_TAXDECLARATION_PILOT_PREVIEW_DEV AS

WITH RE_PARTY AS (
    SELECT
        TRIM(SOURCE_RECORD_ID) AS CONSTITUENT_ID,
        COUNT(DISTINCT GOLDEN_RECORD_ID) AS GOLDEN_RECORDS,
        MIN(GOLDEN_RECORD_ID) AS GOLDEN_RECORD_ID
    FROM MDM_DB.GOLD.XREF
    WHERE SOURCE_SYSTEM = 'RAISERS_EDGE'
      AND TRIM(SOURCE_RECORD_ID) = '379376'
    GROUP BY TRIM(SOURCE_RECORD_ID)
),

DYNAMICS_IDS AS (
    SELECT
        GOLDEN_RECORD_ID,
        COUNT(DISTINCT CASE
            WHEN STANDARDISED_ID LIKE 'D365-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), ''))
        END) AS CONTACT_IDS,
        MIN(CASE
            WHEN STANDARDISED_ID LIKE 'D365-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), ''))
        END) AS CONTACT_ID,
        COUNT(DISTINCT CASE
            WHEN STANDARDISED_ID LIKE 'D365C-%'
            THEN LOWER(NULLIF(TRIM(SOURCE_RECORD_ID), ''))
        END) AS ACCOUNT_IDS
    FROM MDM_DB.GOLD.XREF
    WHERE SOURCE_SYSTEM = 'DYNAMICS'
    GROUP BY GOLDEN_RECORD_ID
),

PILOT AS (
    SELECT
        T.ID AS RE_DECLARATION_ID,
        T.CONSTITUENTID,
        T.DATEDECLARATIONMADE,
        T.DATESTART,
        T.DATEFINISH,
        T.TAXDECLARATIONINDICATORDESCRIPTION,
        T.TAXDECLARATIONSOURCEDESCRIPTION,
        P.GOLDEN_RECORDS,
        G.IS_GDPR_SUPPRESSED,
        LOWER(NULLIF(TRIM(G.D365_CONTACT_ID), '')) AS EXPOSED_CONTACT_ID,
        LOWER(NULLIF(TRIM(G.D365_ACCOUNT_ID), '')) AS EXPOSED_ACCOUNT_ID,
        D.CONTACT_IDS,
        D.CONTACT_ID,
        D.ACCOUNT_IDS,
        COUNT(*) OVER () AS SOURCE_MATCHES
    FROM RAW.RAISERS_EDGE.VW_ODS_T_TAXDECLARATIONS AS T
    LEFT JOIN RE_PARTY AS P
        ON TRIM(T.CONSTITUENTID) = P.CONSTITUENT_ID
    LEFT JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS AS G
        ON P.GOLDEN_RECORD_ID = G.GOLDEN_RECORD_ID
    LEFT JOIN DYNAMICS_IDS AS D
        ON P.GOLDEN_RECORD_ID = D.GOLDEN_RECORD_ID
    WHERE T.ID = 73108
)

SELECT
    RE_DECLARATION_ID,
    CONSTITUENTID,
    CONTACT_ID AS D365_CONTACT_ID,
    DATEDECLARATIONMADE,
    DATESTART,
    DATEFINISH,
    TAXDECLARATIONINDICATORDESCRIPTION,
    TAXDECLARATIONSOURCEDESCRIPTION,
    CASE
        WHEN SOURCE_MATCHES <> 1 THEN 'HOLD_SOURCE_NOT_UNIQUE'
        WHEN COALESCE(GOLDEN_RECORDS, 0) <> 1 THEN 'HOLD_GOLDEN_RECORD_UNRESOLVED'
        WHEN IS_GDPR_SUPPRESSED IS NULL OR IS_GDPR_SUPPRESSED THEN 'HOLD_PRIVACY_REVIEW'
        WHEN COALESCE(CONTACT_IDS, 0) <> 1 OR COALESCE(ACCOUNT_IDS, 0) <> 0
            OR EXPOSED_ACCOUNT_ID IS NOT NULL
            THEN 'HOLD_CUSTOMER_UNRESOLVED'
        WHEN CONTACT_ID <> '6c497cd8-1de1-f111-84ea-002248425074'
            OR COALESCE(EXPOSED_CONTACT_ID, '') <> CONTACT_ID
            THEN 'HOLD_CONTACT_CHANGED'
        ELSE 'PILOT_CANDIDATE'
    END AS PREVIEW_STATUS,
    FALSE AS PREVIEW_DISPATCH_ALLOWED,
    OBJECT_CONSTRUCT(
        'mha_sourceid', TO_VARCHAR(RE_DECLARATION_ID),
        'mha_sourcesystem', 'RE',
        'msnfp_CustomerId_contact@odata.bind',
            IFF(CONTACT_ID IS NOT NULL, '/contacts(' || CONTACT_ID || ')', NULL)
    ) AS DRAFT_PAYLOAD
FROM PILOT;
