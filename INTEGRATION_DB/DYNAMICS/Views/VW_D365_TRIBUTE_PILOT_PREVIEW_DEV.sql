CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_TRIBUTE_PILOT_PREVIEW_DEV AS

-- Read-only preview only. Do not dispatch without live duplicate and safety checks.
WITH SOURCE AS (
    SELECT
        ID AS RE_TRIBUTE_ID,
        NULLIF(TRIM(CONSTITUENTID), '') AS RE_CONSTITUENT_ID,
        TRIBUTETYPEDESCRIPTION,
        NULLIF(TRIM(DESCRIPTION), '') AS TRIBUTE_DESCRIPTION,
        NULLIF(TRIM(NOTES), '') AS TRIBUTE_NOTES,
        ACTIVE,
        COUNT(*) OVER () AS SOURCE_ROWS
    FROM RAW.RAISERS_EDGE.VW_ODS_T_TRIBUTES
    WHERE ID = 1113
),
PRIVACY AS (
    SELECT
        S.RE_TRIBUTE_ID,
        COUNT(DISTINCT X.GOLDEN_RECORD_ID) AS GOLDEN_RECORDS,
        COUNT_IF(G.GOLDEN_RECORD_ID IS NULL OR G.IS_GDPR_SUPPRESSED IS NULL)
            AS UNKNOWN_PRIVACY_ROWS,
        COUNT_IF(G.IS_GDPR_SUPPRESSED = TRUE) AS SUPPRESSED_ROWS
    FROM SOURCE S
    LEFT JOIN MDM_DB.GOLD.XREF X
        ON X.SOURCE_SYSTEM = 'RAISERS_EDGE'
       AND TRIM(X.SOURCE_RECORD_ID) = S.RE_CONSTITUENT_ID
    LEFT JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS G
        ON G.GOLDEN_RECORD_ID = X.GOLDEN_RECORD_ID
    GROUP BY S.RE_TRIBUTE_ID
),
TYPE_OPTION AS (
    SELECT COUNT(*) AS MATCHES
    FROM RAW.DYNAMICS.VW_ODS_METADATA_OPTIONS
    WHERE ENTITY_LOGICALNAME = 'msnfp_tributeormemory'
      AND ATTRIBUTE_LOGICALNAME = 'msnfp_tributeormemorytypecode'
      AND OPTION_VALUE = 844060001
      AND UPPER(TRIM(OPTION_LABEL)) = 'IN MEMORY'
),
STATUS_OPTION AS (
    SELECT COUNT(*) AS MATCHES
    FROM RAW.DYNAMICS.VW_ODS_METADATA_OPTIONS
    WHERE ENTITY_LOGICALNAME = 'msnfp_tributeormemory'
      AND ATTRIBUTE_LOGICALNAME = 'statuscode'
      AND OPTION_VALUE = 1
      AND STATE = 0
),
REVIEWED AS (
    SELECT
        S.*,
        P.GOLDEN_RECORDS,
        P.UNKNOWN_PRIVACY_ROWS,
        P.SUPPRESSED_ROWS,
        T.MATCHES AS TYPE_OPTION_MATCHES,
        O.MATCHES AS STATUS_OPTION_MATCHES,
        CASE
            WHEN S.SOURCE_ROWS <> 1 THEN 'HOLD_SOURCE_NOT_UNIQUE'
            WHEN S.ACTIVE IS DISTINCT FROM TRUE
              OR COALESCE(S.TRIBUTETYPEDESCRIPTION, '') <> 'In memory of'
              OR S.TRIBUTE_DESCRIPTION IS NULL
              OR S.TRIBUTE_NOTES IS NOT NULL
                THEN 'HOLD_SOURCE_CHANGED'
            WHEN S.RE_CONSTITUENT_ID IS NULL
              OR P.GOLDEN_RECORDS <> 1
              OR P.UNKNOWN_PRIVACY_ROWS > 0
              OR P.SUPPRESSED_ROWS > 0
                THEN 'HOLD_PRIVACY_OR_IDENTITY'
            WHEN T.MATCHES <> 1 OR O.MATCHES <> 1
                THEN 'HOLD_TARGET_OPTIONS'
            ELSE 'PILOT_CANDIDATE'
        END AS PREVIEW_STATUS
    FROM SOURCE S
    JOIN PRIVACY P ON P.RE_TRIBUTE_ID = S.RE_TRIBUTE_ID
    CROSS JOIN TYPE_OPTION T
    CROSS JOIN STATUS_OPTION O
)
SELECT
    RE_TRIBUTE_ID,
    RE_CONSTITUENT_ID,
    TRIBUTETYPEDESCRIPTION,
    SOURCE_ROWS,
    GOLDEN_RECORDS,
    UNKNOWN_PRIVACY_ROWS,
    SUPPRESSED_ROWS,
    TYPE_OPTION_MATCHES,
    STATUS_OPTION_MATCHES,
    PREVIEW_STATUS,
    FALSE AS PREVIEW_DISPATCH_ALLOWED,
    IFF(
        PREVIEW_STATUS = 'PILOT_CANDIDATE',
        OBJECT_CONSTRUCT(
            'msnfp_name', 'RE Tribute ID ' || TO_VARCHAR(RE_TRIBUTE_ID),
            'msnfp_identifier', TRIBUTE_DESCRIPTION,
            'msnfp_tributeormemorytypecode', 844060001,
            'statuscode', 1
        ),
        NULL
    ) AS DRAFT_PAYLOAD
FROM REVIEWED;
