CREATE OR REPLACE VIEW INTEGRATION_DB.DYNAMICS.VW_D365_TRIBUTE_PILOT_REQUESTS_DEV AS

-- One DEV technical pilot only. Reconcile live duplicates before dispatch and
-- reconcile any uncertain POST before retrying. These guards are not atomic.
WITH PILOT AS (
    SELECT
        'TRIBUTE:' || TO_VARCHAR(RE_TRIBUTE_ID) AS GOLDEN_RECORD_ID,
        DRAFT_PAYLOAD AS REQUEST_BODY
    FROM INTEGRATION_DB.DYNAMICS.VW_D365_TRIBUTE_PILOT_PREVIEW_DEV
    WHERE PREVIEW_STATUS = 'PILOT_CANDIDATE'
      AND RE_TRIBUTE_ID = 1113
      AND LENGTH(DRAFT_PAYLOAD:"msnfp_identifier"::VARCHAR) = 19
)
SELECT
    'D365_TRIBUTE_PILOT' AS PIPELINE_ID,
    M.SOURCE_INSTANCE,
    'TRIBUTE' AS ENTITY_ID,
    P.GOLDEN_RECORD_ID,
    CAST(NULL AS VARCHAR) AS TARGET_GUID,
    'POST' AS HTTP_METHOD,
    M.API_BASE_URL || '/msnfp_tributeormemories' AS REQUEST_URL,
    P.REQUEST_BODY,
    M.AUTH_METHOD,
    M.AUTH_CONFIG,
    MD5(TO_VARCHAR(P.REQUEST_BODY)) AS PAYLOAD_MD5
FROM AUDIT_DB.CONFIG.PIPELINE_METADATA AS M
CROSS JOIN PILOT AS P
WHERE M.PIPELINE_ID = 'D365_WRITEBACK'
  AND M.SOURCE_INSTANCE = 'SNOWFLAKE_DEV'
  AND M.ENTITY_ID = 'CAMPAIGN'
  AND M.API_BASE_URL = 'https://nasdatamig.crm11.dynamics.com/api/data/v9.2'
  AND NOT EXISTS (
      SELECT 1
      FROM AUDIT_DB.MONITORING.D365_WRITEBACK_STATE AS S
      WHERE S.ENTITY_ID = 'TRIBUTE'
        AND S.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
  )
  AND NOT EXISTS (
      SELECT 1
      FROM MDM_DB.GOLD.XREF AS X
      WHERE X.SOURCE_SYSTEM = 'DYNAMICS'
        AND X.GOLDEN_RECORD_ID = P.GOLDEN_RECORD_ID
  )
QUALIFY COUNT(*) OVER (PARTITION BY P.GOLDEN_RECORD_ID) = 1;
