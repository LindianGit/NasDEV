) as
WITH CTE AS (
    SELECT GOLDEN_RECORD_ID, COUNT(*) AS GOLDENCOUNT
    FROM MDM_DB.STAGING.STANDARDISED_RECORDS
    WHERE SOURCE_SYSTEM = 'RAISERS_EDGE' AND _IS_ACTIVE = TRUE
    GROUP BY GOLDEN_RECORD_ID
    HAVING GOLDENCOUNT > 1
),
GIFT_TOTALS AS (
    SELECT
        CONSTITUENT_ID,
        SUM(AMOUNT) AS TOTAL_GIFT_AMOUNT,
        COUNT(*) AS GIFT_COUNT,
        MIN(GIFTDATE) AS FIRST_GIFT_DATE,
        MAX(GIFTDATE) AS LAST_GIFT_DATE
    FROM RAW.RAISERS_EDGE.ODS_T_GIFTS
    WHERE IS_DELETED = FALSE
    GROUP BY CONSTITUENT_ID
)
SELECT
    sr.STANDARDISED_ID,
    sr.GOLDEN_RECORD_ID,
    sr.SOURCE_SYSTEM,
    sr.SOURCE_RECORD_ID,
    sr.SOURCE_DOMAIN,
    sr.LOOKUP_ID,
    sr.TITLE,
