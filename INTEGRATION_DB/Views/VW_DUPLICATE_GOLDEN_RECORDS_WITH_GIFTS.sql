    sr.IS_CORPORATE,
    sr.IS_ORGANISATION,
    sr.IS_CELEBRITY,
    sr.IS_POLITICIAN,
    sr.IS_MAJOR_DONOR,
    sr.IS_MEMORIAL,
    sr.IN_MEMORY_DONATION_HONOUREE,
    sr.IN_MEMORY_NEXT_OF_KIN,
    sr.BENEVOLENT_FAMILY,
    sr.FOUR_YEAR_RULE,
    sr.LEGACY_SUPPORTER,
    sr.LEGACY_CONSIDERER,
    sr.LEGACY_ENQUIRER,
    sr.LEGACY_INTENDER,
    sr.LEGACY_PLEDGER,
    sr.NAS_BRANCH_CONTACT,
    sr.PR_CASE_STUDY,
    sr.SPECIAL_EVENTER,
    sr.STATUTORY_AUTHORITY,
    sr.TRUSTS,
    sr.SOLICIT_CODES,
    sr.MD5,
    sr._IS_ACTIVE,
    sr._STANDARDISED_AT,
    sr.LAST_UPDATED,
    gt.TOTAL_GIFT_AMOUNT,
    gt.GIFT_COUNT,
    gt.FIRST_GIFT_DATE,
    gt.LAST_GIFT_DATE
FROM INTEGRATION_DB.HUBSPOT.VW_INDIVIDUAL_CONTACTS_DEBUG iv
JOIN CTE ON iv.GOLDEN_RECORD_ID = CTE.GOLDEN_RECORD_ID
JOIN MDM_DB.STAGING.STANDARDISED_RECORDS sr
    ON sr.GOLDEN_RECORD_ID = iv.GOLDEN_RECORD_ID
    AND sr.SOURCE_SYSTEM = 'RAISERS_EDGE'
LEFT JOIN GIFT_TOTALS gt
    ON sr.SOURCE_RECORD_ID = gt.CONSTITUENT_ID;