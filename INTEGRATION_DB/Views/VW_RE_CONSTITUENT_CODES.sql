create or replace view INTEGRATION_DB.RAISERS_EDGE.VW_RE_CONSTITUENT_CODES(
	GOLDEN_RECORD_ID,
	CONSTITUENT_ID,
	SYSTEMRECORDID,
	ACTION,
	PAYLOAD
) as
WITH WINNER AS (
    SELECT
        GR.GOLDEN_RECORD_ID,
        IDS.RE_CONSTITUENT_ID AS CONSTITUENT_ID,
        re_raw.SYSTEMRECORDID,
        GR.IS_MAJOR_DONOR,
        GR.IS_POLITICIAN,
        GR.IS_CELEBRITY,
        GR.IN_MEMORY_DONATION_HONOUREE,
        GR.IN_MEMORY_NEXT_OF_KIN,
        GR.BENEVOLENT_FAMILY,
        GR.IS_CORPORATE,
        GR.NAS_BRANCH_CONTACT,
        GR.PR_CASE_STUDY,
        GR.STATUTORY_AUTHORITY,
        GR.SPECIAL_EVENTER,
        GR.TRUSTS,
        GR.LEGACY_SUPPORTER
    FROM MDM_DB.GOLD.GOLDEN_RECORDS AS GR
    INNER JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS AS IDS
        ON GR.GOLDEN_RECORD_ID = IDS.GOLDEN_RECORD_ID
    LEFT JOIN RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENT AS re_raw
        ON re_raw.CONSTITUENT_ID = IDS.RE_CONSTITUENT_ID
    WHERE
        GR._IS_ACTIVE = TRUE
        AND IDS.IS_GDPR_SUPPRESSED = FALSE
        AND GR.FOUR_YEAR = TRUE
        AND IDS.RE_CONSTITUENT_ID IS NOT NULL
),

RE_CURR AS (
    SELECT
        CONSTITUENT_ID,
        MAX(COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Major Donor' AND DATEEND IS NULL, FALSE)) AS IS_MAJOR_DONOR,
        MAX(COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Politician' AND DATEEND IS NULL, FALSE)) AS IS_POLITICIAN,
        MAX(COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Celebrity' AND DATEEND IS NULL, FALSE)) AS IS_CELEBRITY,
        MAX(COALESCE(CONSTITUENTTYPEDESCRIPTION = 'In Memory Donation Honouree' AND DATEEND IS NULL AND TRY_TO_DATE(DATESTART) >= DATEADD('year', -2, CURRENT_DATE()), FALSE)) AS IN_MEMORY_DONATION_HONOUREE,
        MAX(COALESCE(CONSTITUENTTYPEDESCRIPTION = 'In Memory Next of Kin' AND DATEEND IS NULL AND TRY_TO_DATE(DATESTART) >= DATEADD('year', -2, CURRENT_DATE()), FALSE)) AS IN_MEMORY_NEXT_OF_KIN,
        MAX(COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Benevolent Family' AND DATEEND IS NULL, FALSE)) AS BENEVOLENT_FAMILY,
        MAX(COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Corporate' AND DATEEND IS NULL, FALSE)) AS IS_CORPORATE,
        MAX(COALESCE(CONSTITUENTTYPEDESCRIPTION = 'NAS Branch Contact' AND DATEEND IS NULL, FALSE)) AS NAS_BRANCH_CONTACT,
        MAX(COALESCE(CONSTITUENTTYPEDESCRIPTION = 'PR Case Study' AND DATEEND IS NULL, FALSE)) AS PR_CASE_STUDY,
        MAX(COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Statutory Authority' AND DATEEND IS NULL, FALSE)) AS STATUTORY_AUTHORITY,
        MAX(COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Special Eventer' AND DATEEND IS NULL, FALSE)) AS SPECIAL_EVENTER,
        MAX(COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Trusts' AND DATEEND IS NULL, FALSE)) AS TRUSTS,
        MAX(COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Legacy Supporter' AND DATEEND IS NULL, FALSE)) AS LEGACY_SUPPORTER
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTTYPES
    GROUP BY CONSTITUENT_ID
)

SELECT W.GOLDEN_RECORD_ID, W.CONSTITUENT_ID, W.SYSTEMRECORDID, 'POST' AS ACTION,
    OBJECT_CONSTRUCT('constituent_id', W.SYSTEMRECORDID, 'description', 'Major Donor') AS PAYLOAD
FROM WINNER AS W LEFT JOIN RE_CURR AS RC ON W.CONSTITUENT_ID = RC.CONSTITUENT_ID
WHERE COALESCE(W.IS_MAJOR_DONOR, FALSE) = TRUE AND COALESCE(RC.IS_MAJOR_DONOR, FALSE) = FALSE

UNION ALL

