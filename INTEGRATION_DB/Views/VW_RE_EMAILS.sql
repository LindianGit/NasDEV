create or replace view INTEGRATION_DB.RAISERS_EDGE.VW_RE_EMAILS(
	GOLDEN_RECORD_ID,
	CONSTITUENT_ID,
	SYSTEMRECORDID,
	EMAIL_ID,
	ACTION,
	PAYLOAD
) as
WITH GOLDEN_BASE AS (
    SELECT
        gr.GOLDEN_RECORD_ID,
        ids.RE_CONSTITUENT_ID AS CONSTITUENT_ID,
        re_raw.SYSTEMRECORDID,
        gr.EMAIL,
        gr.ALL_EMAILS
    FROM MDM_DB.GOLD.GOLDEN_RECORDS AS gr
    INNER JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS AS ids
        ON ids.GOLDEN_RECORD_ID = gr.GOLDEN_RECORD_ID
    LEFT JOIN RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENT AS re_raw
        ON re_raw.CONSTITUENT_ID = ids.RE_CONSTITUENT_ID
    WHERE
        --gr._IS_ACTIVE = TRUE
        ids.IS_GDPR_SUPPRESSED = FALSE
        AND gr.FOUR_YEAR = TRUE
        AND ids.RE_CONSTITUENT_ID IS NOT NULL
),

WORK_EMAIL_CTE AS (
    SELECT
        b.GOLDEN_RECORD_ID,
        f.VALUE:EMAIL::VARCHAR AS WORK_EMAIL
    FROM GOLDEN_BASE AS b,
        LATERAL FLATTEN(INPUT => b.ALL_EMAILS, OUTER => TRUE) f
    WHERE
        f.VALUE:EMAIL_TYPE::VARCHAR = 'Work Email'
        AND f.VALUE:IS_ACTIVE::INTEGER = 1
        AND NULLIF(TRIM(f.VALUE:EMAIL::VARCHAR), '') IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY b.GOLDEN_RECORD_ID
        ORDER BY f.VALUE:IS_PRIMARY::INTEGER DESC, f.VALUE:SOURCE_EMAIL_ID::INTEGER DESC
    ) = 1
),

RE_EMAIL_CTE AS (
    SELECT
        CONSTITUENTID,
        MAX(CASE WHEN ISPRIMARY = 1 THEN ID END) AS EMAIL_ID,
        MAX(CASE WHEN ISPRIMARY = 1 THEN EMAILADDRESS END) AS EMAILADDRESS,
        MAX(CASE WHEN ISPRIMARY = 1 THEN TYPEDESCRIPTION END)
            AS TYPEDESCRIPTION,
        MAX(
            CASE WHEN TYPEDESCRIPTION = 'Work Email' THEN ID END
        ) AS BUSINESS_EMAIL_ID,
        MAX(
            CASE WHEN TYPEDESCRIPTION = 'Work Email' THEN EMAILADDRESS END
        ) AS BUSINESS_EMAILADDRESS
    FROM RAW.RAISERS_EDGE.VW_ODS_T_EMAILADDRESSES
    WHERE ISACTIVE = 1
    GROUP BY CONSTITUENTID
),

EXISTING_EMAIL_CTE AS (
    SELECT DISTINCT
        CONSTITUENTID,
        LOWER(NULLIF(TRIM(EMAILADDRESS), '')) AS EMAIL_NORM
    FROM RAW.RAISERS_EDGE.VW_ODS_T_EMAILADDRESSES
    WHERE ISACTIVE = 1 AND NULLIF(TRIM(EMAILADDRESS), '') IS NOT NULL
),

RE_ANY_EMAIL_CTE AS (
    SELECT DISTINCT CONSTITUENTID FROM EXISTING_EMAIL_CTE
)

SELECT DISTINCT * FROM (
SELECT
    BASE.GOLDEN_RECORD_ID,
    BASE.CONSTITUENT_ID,
    CO.SYSTEMRECORDID,
    EM.EMAIL_ID,
    IFF(EM.EMAIL_ID IS NULL, 'POST', 'PATCH') AS ACTION,
    CASE
        WHEN EM.EMAIL_ID IS NULL
            THEN
                OBJECT_CONSTRUCT(
                    'address', NULLIF(TRIM(BASE.EMAIL), ''),
                    'constituent_id', CO.SYSTEMRECORDID,
                    'type', 'Email',
                    'primary', TRUE
                )
        ELSE
            OBJECT_CONSTRUCT(
                'address', NULLIF(TRIM(BASE.EMAIL), ''),
                'type', COALESCE(NULLIF(TRIM(EM.TYPEDESCRIPTION), ''), 'Email'),
                'primary', TRUE
            )
    END AS PAYLOAD
FROM GOLDEN_BASE AS BASE
LEFT JOIN RE_EMAIL_CTE AS EM
    ON BASE.CONSTITUENT_ID = EM.CONSTITUENTID
LEFT JOIN EXISTING_EMAIL_CTE AS EXIST
    ON
        BASE.CONSTITUENT_ID = EXIST.CONSTITUENTID
        AND LOWER(NULLIF(TRIM(BASE.EMAIL), '')) = EXIST.EMAIL_NORM
LEFT JOIN RE_ANY_EMAIL_CTE AS ANY_EM
    ON BASE.CONSTITUENT_ID = ANY_EM.CONSTITUENTID
LEFT JOIN RAW_PROD.RAISERS_EDGE.ODS_T_CONSTITUENT AS CO 
    ON CO.CONSTITUENT_ID = BASE.CONSTITUENT_ID
WHERE
    NULLIF(TRIM(BASE.EMAIL), '') IS NOT NULL
    AND ANY_EM.CONSTITUENTID IS NULL
    AND EXIST.EMAIL_NORM IS NULL

UNION ALL

SELECT
    BASE.GOLDEN_RECORD_ID,
    BASE.CONSTITUENT_ID,
    CO.SYSTEMRECORDID,
    EM.BUSINESS_EMAIL_ID AS EMAIL_ID,
    IFF(EM.BUSINESS_EMAIL_ID IS NULL, 'POST', 'PATCH') AS ACTION,
    CASE
        WHEN EM.BUSINESS_EMAIL_ID IS NULL
            THEN
                OBJECT_CONSTRUCT(
                    'address', NULLIF(TRIM(WE.WORK_EMAIL), ''),
                    'constituent_id', CO.SYSTEMRECORDID,
                    'type', 'Work Email',
                    'primary', FALSE
                )
        ELSE
            OBJECT_CONSTRUCT(
                'address', NULLIF(TRIM(WE.WORK_EMAIL), ''),
                'type', 'Work Email',
                'primary', FALSE
            )
    END AS PAYLOAD
FROM GOLDEN_BASE AS BASE
INNER JOIN WORK_EMAIL_CTE AS WE ON BASE.GOLDEN_RECORD_ID = WE.GOLDEN_RECORD_ID
LEFT JOIN RE_EMAIL_CTE AS EM
    ON BASE.CONSTITUENT_ID = EM.CONSTITUENTID
LEFT JOIN EXISTING_EMAIL_CTE AS EXIST
    ON
        BASE.CONSTITUENT_ID = EXIST.CONSTITUENTID
        AND LOWER(NULLIF(TRIM(WE.WORK_EMAIL), '')) = EXIST.EMAIL_NORM
LEFT JOIN RE_ANY_EMAIL_CTE AS ANY_EM
    ON BASE.CONSTITUENT_ID = ANY_EM.CONSTITUENTID
LEFT JOIN RAW_PROD.RAISERS_EDGE.ODS_T_CONSTITUENT AS CO 
    ON CO.CONSTITUENT_ID = BASE.CONSTITUENT_ID
WHERE
    NULLIF(TRIM(WE.WORK_EMAIL), '') IS NOT NULL
    AND LOWER(NULLIF(TRIM(WE.WORK_EMAIL), ''))
    IS DISTINCT FROM LOWER(NULLIF(TRIM(BASE.EMAIL), ''))
    AND ANY_EM.CONSTITUENTID IS NULL
    AND EXIST.EMAIL_NORM IS NULL
);