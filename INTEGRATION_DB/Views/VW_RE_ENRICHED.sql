TELEPHONE_CTE AS (
    SELECT
        CONSTITUENT_ID,
        PHONENUMBER AS TELEPHONE
    FROM RAW.RAISERS_EDGE.VW_ODS_T_PHONENUMBERS
    WHERE PHONETYPEDESCRIPTION = 'Telephone' AND ISACTIVE = 1
    QUALIFY
        ROW_NUMBER()
            OVER (PARTITION BY CONSTITUENT_ID ORDER BY ISPRIMARY DESC, ID DESC)
        = 1
),

WORK_EMAIL_CTE AS (
    SELECT
        EA.CONSTITUENTID,
        EA.EMAILADDRESS AS WORK_EMAIL
    FROM RAW.RAISERS_EDGE.VW_ODS_T_EMAILADDRESSES AS EA
    WHERE
        EA.TYPEDESCRIPTION = 'Work Email'
        AND EA.ISACTIVE = 1
        AND NOT EXISTS (
            SELECT 1 FROM RAW.RAISERS_EDGE.VW_ODS_T_EMAILADDRESSES AS EXCL
            WHERE
                EXCL.CONSTITUENTID = EA.CONSTITUENTID
                AND LOWER(TRIM(EXCL.EMAILADDRESS))
                = LOWER(TRIM(EA.EMAILADDRESS))
                AND EXCL.TYPEDESCRIPTION IN (
                    'Hard Bounce', 'Hard Bounce 2', 'Invalid Email'
                )
        )
    QUALIFY
        ROW_NUMBER()
            OVER (
                PARTITION BY EA.CONSTITUENTID
                ORDER BY EA.ISPRIMARY DESC, EA.ID DESC
            )
        = 1
),

ATTRIBUTES_CTE AS (
    SELECT
        CONSTITUENT_ID,
        NULLIF(LISTAGG(DISTINCT CASE
            WHEN ATTRIBUTENAME = 'Subscriber Type'
                THEN ATTRIBUTEVALUE
        END, ';')
        WITHIN GROUP (ORDER BY CASE
            WHEN ATTRIBUTENAME = 'Subscriber Type'
                THEN ATTRIBUTEVALUE
        END), '') AS SUBSCRIBER_TYPE,
        NULLIF(LISTAGG(DISTINCT CASE
            WHEN ATTRIBUTENAME = 'Postal Preferences'
                THEN ATTRIBUTEVALUE
        END, ';')
        WITHIN GROUP (ORDER BY CASE
            WHEN ATTRIBUTENAME = 'Postal Preferences'
                THEN ATTRIBUTEVALUE
        END), '') AS POSTAL_PREFERENCE,
        NULLIF(LISTAGG(DISTINCT CASE
            WHEN ATTRIBUTENAME = 'Email Preferences'
                THEN ATTRIBUTEVALUE
        END, ';')
        WITHIN GROUP (ORDER BY CASE
            WHEN ATTRIBUTENAME = 'Email Preferences'
                THEN ATTRIBUTEVALUE
        END), '') AS EMAIL_PREFERENCE,
        NULLIF(LISTAGG(DISTINCT CASE
            WHEN ATTRIBUTENAME = 'SMS Preferences'
                THEN ATTRIBUTEVALUE
        END, ';')
        WITHIN GROUP (ORDER BY CASE
            WHEN ATTRIBUTENAME = 'SMS Preferences'
                THEN ATTRIBUTEVALUE
        END), '') AS SMS_PREFERENCE,
        NULLIF(LISTAGG(DISTINCT CASE
            WHEN ATTRIBUTENAME = 'Telephone Preferences'
                THEN ATTRIBUTEVALUE
        END, ';')
        WITHIN GROUP (ORDER BY CASE
            WHEN ATTRIBUTENAME = 'Telephone Preferences'
                THEN ATTRIBUTEVALUE
        END), '') AS TELEPHONE_PREFERENCE,
        NULLIF(LISTAGG(DISTINCT CASE
            WHEN ATTRIBUTENAME = 'Contact Exclusions'
                THEN ATTRIBUTEVALUE
        END, ';')
        WITHIN GROUP (ORDER BY CASE
            WHEN ATTRIBUTENAME = 'Contact Exclusions'
                THEN ATTRIBUTEVALUE
        END), '') AS CONTACT_EXCLUSION,
        MAX(CASE
            WHEN ATTRIBUTENAME = 'Licensed User Type'
                THEN ATTRIBUTEVALUE
        END) AS LICENCED_USER_TYPE,
        NULLIF(LISTAGG(DISTINCT CASE
            WHEN ATTRIBUTENAME = 'Professional - Work Sector'
                THEN ATTRIBUTEVALUE
        END, ';')
        WITHIN GROUP (ORDER BY CASE
            WHEN ATTRIBUTENAME = 'Professional - Work Sector'
                THEN ATTRIBUTEVALUE
        END), '') AS PROFESSIONAL_WORK_SECTOR,
        MAX(CASE
            WHEN ATTRIBUTENAME = 'Professional - Job Title'
                THEN ATTRIBUTEVALUE
        END) AS JOB_TITLE,
        MAX(CASE
            WHEN ATTRIBUTENAME = 'Legacy Intender'
                THEN ATTRIBUTEVALUE
        END) AS LEGACY_INTENDER,
        MAX(CASE
            WHEN ATTRIBUTENAME = 'Legacy Pledger'
                THEN ATTRIBUTEVALUE
        END) AS LEGACY_PLEDGER,
        MAX(CASE
            WHEN ATTRIBUTENAME = 'Legacy Considerer'
                THEN ATTRIBUTEVALUE
        END) AS LEGACY_CONSIDERER,
        MAX(CASE
            WHEN ATTRIBUTENAME = 'Legacy Enquirer'
                THEN ATTRIBUTEVALUE
        END) AS LEGACY_ENQUIRER
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTATTRIBUTES
    GROUP BY CONSTITUENT_ID
),

SOLICIT_CODES_CTE AS (
    SELECT
        CONSTITUENT_ID,
        MAX(
            COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Major Donor'
            AND DATEEND IS NULL,
            FALSE)
        ) AS IS_MAJOR_DONOR,
        MAX(
            COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Politician'
            AND DATEEND IS NULL,
            FALSE)
        ) AS IS_POLITICIAN,
        MAX(
            COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Celebrity'
            AND DATEEND IS NULL,
            FALSE)
        ) AS IS_CELEBRITY,
        MAX(
            COALESCE(CONSTITUENTTYPEDESCRIPTION = 'In Memory Donation Honouree'
            AND DATEEND IS NULL
            AND TRY_TO_DATE(DATESTART) >= DATEADD('year', -2, CURRENT_DATE()),
            FALSE)
        ) AS IN_MEMORY_DONATION_HONOUREE,
        MAX(
            COALESCE(CONSTITUENTTYPEDESCRIPTION = 'In Memory Next of Kin'
            AND DATEEND IS NULL
            AND TRY_TO_DATE(DATESTART) >= DATEADD('year', -2, CURRENT_DATE()),
            FALSE)
        ) AS IN_MEMORY_NEXT_OF_KIN,
        MAX(
            COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Benevolent Family'
            AND DATEEND IS NULL,
            FALSE)
        ) AS BENEVOLENT_FAMILY,
        MAX(
            COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Corporate'
            AND DATEEND IS NULL,
            FALSE)
        ) AS IS_CORPORATE,
        MAX(
            COALESCE(CONSTITUENTTYPEDESCRIPTION = 'NAS Branch Contact'
            AND DATEEND IS NULL,
            FALSE)
        ) AS NAS_BRANCH_CONTACT,
        MAX(
            COALESCE(CONSTITUENTTYPEDESCRIPTION = 'PR Case Study'
            AND DATEEND IS NULL,
            FALSE)
        ) AS PR_CASE_STUDY,
        MAX(
            COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Statutory Authority'
            AND DATEEND IS NULL,
            FALSE)
        ) AS STATUTORY_AUTHORITY,
        MAX(
            COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Special Eventer'
            AND DATEEND IS NULL,
            FALSE)
        ) AS SPECIAL_EVENTER,
        MAX(
            COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Trusts' AND DATEEND IS NULL,
            FALSE)
        ) AS TRUSTS,
        MAX(
            COALESCE(CONSTITUENTTYPEDESCRIPTION = 'Legacy Supporter'
            AND DATEEND IS NULL,
            FALSE)
        ) AS LEGACY_SUPPORTER
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTTYPES
    GROUP BY CONSTITUENT_ID
),

SOLICIT_CODES_REAL_CTE AS (
    SELECT
        CONSTITUENTID AS CONSTITUENT_ID,
        LISTAGG(DISTINCT SOLICITCODEDESCRIPTION, ';')
        WITHIN GROUP (ORDER BY SOLICITCODEDESCRIPTION) AS SOLICIT_CODES
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTSOLICITCODES
    GROUP BY CONSTITUENTID
),

CONNECTION_TO_AUTISM_CTE AS (
    SELECT
        CONSTITUENTID,
        NULLIF(LISTAGG(
            DISTINCT
            CASE CONSTITUENTTYPEDESCRIPTION
                WHEN 'Person with Autism' THEN 'I am Autistic'
                WHEN 'Parent/Guardian' THEN 'Parent/ Guardian'
                WHEN 'Relative' THEN 'Relative'
                WHEN 'Friend' THEN 'Friend'
                WHEN 'Professional' THEN 'Professional'
                WHEN 'Other Autism Connection' THEN 'Other'
                WHEN 'No Autism Connection' THEN 'No Connection'
                WHEN 'Prefer Not to Say' THEN 'Prefer Not to Say'
            END, ';'
        )
        WITHIN GROUP (
            ORDER BY
                CASE CONSTITUENTTYPEDESCRIPTION
                    WHEN 'Person with Autism' THEN 'I am Autistic'
                    WHEN 'Parent/Guardian' THEN 'Parent/ Guardian'
                    WHEN 'Relative' THEN 'Relative'
                    WHEN 'Friend' THEN 'Friend'
                    WHEN 'Professional' THEN 'Professional'
                    WHEN 'Other Autism Connection' THEN 'Other'
                    WHEN 'No Autism Connection' THEN 'No Connection'
                    WHEN 'Prefer Not to Say' THEN 'Prefer Not to Say'
                END
        ), '') AS CONNECTION_TO_AUTISM
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTCONNECTIONWITHAUTISM
    WHERE DATETO IS NULL
    GROUP BY CONSTITUENTID
),

UK_COUNTRY_CTE AS (
    SELECT
        C_INNER.CONSTITUENT_ID,
        CAA.VALUE AS UK_COUNTRY
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENT AS C_INNER
    INNER JOIN RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTADDRESSES AS CA_INNER
        ON
            C_INNER.PREFERRED_ADDRESS_ID = CA_INNER.ADDRESS_ID
            AND C_INNER.CONSTITUENT_ID = CA_INNER.CONSTITUENT_ID
    INNER JOIN RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTADDRESSATTRIBUTES AS CAA
        ON CA_INNER.ID = CAA.CONSTITUENTADDRESSID
    WHERE CAA.CATEGORY = 'Country (UK)'
    QUALIFY
        ROW_NUMBER()
            OVER (PARTITION BY C_INNER.CONSTITUENT_ID ORDER BY (SELECT NULL))
        = 1
),

ACTIVE_REGULAR_GIVER_CTE AS (
    SELECT DISTINCT RG.CONSTITUENT_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_REGULARGIVING AS RG
    INNER JOIN RAW.RAISERS_EDGE.VW_ODS_T_APPEALS AS AP ON RG.APPEALID = AP.ID
    WHERE
        RG.STATUS = 'Active'
        AND RG.AMOUNT > 0
        AND AP.APPEALCATEGORYDESCRIPTION IN (
            'Individual Giving (Direct Mail Appeals)',
            'Individual Giving (Door to Door)',
            'Individual Giving (Face to Face)', 'Individual Giving (Helpline)',
            'Individual Giving (Newsletters)',
            'Individual Giving (Payroll Giving)',
            'Individual Giving (Raffles)', 'Individual Giving (Regular Giving)',
            'Individual Giving (Solicited Online)',
            'Individual Giving (Telephone Upgrade/Cash Conv/Cross sell)',
            'Individual Giving (Together Gifts)',
            'Individual Giving (Unsolicited Online)',
            'Individual Giving (Unsolicited)'
        )
),

ACTIVE_PAYROLL_GIVER_CTE AS (
    SELECT DISTINCT G.CONSTITUENT_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_GIFTS AS G
    INNER JOIN RAW.RAISERS_EDGE.VW_ODS_T_GIFTSPLITS AS GS ON G.ID = GS.GIFTID
    INNER JOIN RAW.RAISERS_EDGE.VW_ODS_T_APPEALS AS AP ON GS.APPEALCODE = AP.ID
    WHERE
        G.GIFTTYPEDESCRIPTION IN ('Cash', 'Pledge Pay Cash')
        AND G.AMOUNT > 0
        AND TRY_TO_DATE(G.GIFTDATE) >= DATEADD('year', -2, CURRENT_DATE())
        AND AP.APPEALCATEGORYDESCRIPTION = 'Individual Giving (Payroll Giving)'
),

CASH_GIVER_CTE AS (
    SELECT DISTINCT G.CONSTITUENT_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_GIFTS AS G
    INNER JOIN RAW.RAISERS_EDGE.VW_ODS_T_GIFTSPLITS AS GS ON G.ID = GS.GIFTID
    INNER JOIN RAW.RAISERS_EDGE.VW_ODS_T_APPEALS AS AP ON GS.APPEALCODE = AP.ID
    WHERE
        G.GIFTTYPEDESCRIPTION IN ('Cash', 'Pledge Pay Cash')
        AND G.AMOUNT > 0
        AND AP.APPEALCATEGORYDESCRIPTION IN (
            'Individual Donation (Membership)',
            'Individual Giving (Direct Mail Appeals)',
            'Individual Giving (Door to Door)',
            'Individual Giving (Face to Face)',
            'Individual Giving (Helpline)', 'Individual Giving (Newsletters)',
            'Individual Giving (Regular Giving)',
            'Individual Giving (Solicited Online)',
            'Individual Giving (Unsolicited In Memory)',
            'Individual Giving (Telephone Upgrade/Cash Conv/Cross sell)',
            'Individual Giving (Together Gifts)',
            'Individual Giving (Unsolicited Online)',
            'Individual Giving (Unsolicited)'
        )
),

LOTTERY_PLAYER_CTE AS (
    SELECT DISTINCT CA.CONSTITUENT_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTATTRIBUTES AS CA
    INNER JOIN
        RAW.RAISERS_EDGE.VW_ODS_T_GIFTS AS G
        ON CA.CONSTITUENT_ID = G.CONSTITUENT_ID
    INNER JOIN RAW.RAISERS_EDGE.VW_ODS_T_GIFTSPLITS AS GS ON G.ID = GS.GIFTID
    INNER JOIN RAW.RAISERS_EDGE.VW_ODS_T_APPEALS AS AP ON GS.APPEALCODE = AP.ID
    WHERE
        CA.ATTRIBUTENAME = 'Unity Lottery Player Status'
        AND CA.ATTRIBUTEVALUE = 'Active'
        AND G.GIFTTYPEDESCRIPTION IN ('Cash', 'Pledge Pay Cash')
        AND G.AMOUNT > 0
        AND AP.APPEALCATEGORYDESCRIPTION = 'Individual Giving (Raffles)'
),

CAMPAIGNER_CTE AS (
    SELECT DISTINCT CONSTITUENT_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTATTRIBUTES
    WHERE
        ATTRIBUTENAME = 'Subscriber Type'
        AND ATTRIBUTEVALUE = 'Campaigns Email Updates'
        AND TRY_TO_DATE(ATTRIBUTEDATE) >= DATEADD('year', -2, CURRENT_DATE())
    UNION DISTINCT
    SELECT DISTINCT A.CONSTITUENTID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_ACTIONS AS A
    INNER JOIN
        RAW.RAISERS_EDGE.VW_ODS_T_ACTIONATTRIBUTES AS AA
        ON A.ID = AA.ACTIONID
    WHERE
        A.COMMUNICATIONTYPEDESCRIPTION IN ('Campaigns', 'Campaigns Email')
        AND A.STATUSDESCRIPTION = 'Action Taken'
        AND TRY_TO_DATE(A.DATE) >= DATEADD('year', -2, CURRENT_DATE())
        AND AA.CATEGORY = 'Campaigns Action'
        AND AA.VALUE != 'NAS Enquiry Form'
),

IN_MEMORY_DONOR_CTE AS (
    SELECT DISTINCT CONSTITUENT_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTATTRIBUTES
    WHERE
        ATTRIBUTENAME = 'Ad Hoc Donor Type'
        AND ATTRIBUTEVALUE = 'In Memory Donor'
        AND TRY_TO_DATE(ATTRIBUTEDATE) >= DATEADD('year', -2, CURRENT_DATE())
    QUALIFY
        ROW_NUMBER()
            OVER (PARTITION BY CONSTITUENT_ID ORDER BY ATTRIBUTEDATE DESC)
        = 1
),

VOLUNTEER_CTE AS (
    SELECT
        CONSTITUENTID,
        CASE
            WHEN
                VOLTYPEDESCRIPTION LIKE 'z%'
                OR NULLIF(VOLTYPEDESCRIPTION, '') IS NULL
                THEN 'Volunteer Other'
            ELSE VOLTYPEDESCRIPTION
        END AS VOLUNTEER_TYPE,
        NULLIF(VOLSTATUSDESCRIPTION, '') AS VOLUNTEER_STATUS
    FROM RAW.RAISERS_EDGE.VW_ODS_T_VOLUNTEERS
    WHERE
        NULLIF(VOLTYPEDESCRIPTION, '') IS NOT NULL
        OR NULLIF(VOLSTATUSDESCRIPTION, '') IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CONSTITUENTID
        ORDER BY
            CASE VOLSTATUSDESCRIPTION
                WHEN 'Active' THEN 1
                WHEN 'Applicant' THEN 2
                WHEN 'Enquirer' THEN 3
                WHEN 'Speaker' THEN 4
                WHEN 'Inactive' THEN 5
                ELSE 6
            END,
            TRY_TO_DATE(VOLDATESTARTED, 'YYYYMMDD') DESC NULLS LAST
    ) = 1
),

SR AS (
    SELECT
        SOURCE_RECORD_ID,
        FOUR_YEAR_RULE
    FROM MDM_DB.STAGING.STANDARDISED_RECORDS
    WHERE
        SOURCE_SYSTEM = 'RAISERS_EDGE'
        AND _IS_ACTIVE = TRUE
    QUALIFY
        ROW_NUMBER()
            OVER (PARTITION BY SOURCE_RECORD_ID ORDER BY _STANDARDISED_AT DESC)
        = 1
)

SELECT
    GR.GOLDEN_RECORD_ID,
    XC.CONSTITUENT_ID,
    C.ISORGANISATION AS IS_ORGANISATION,
    GR.FIRST_NAME,
    GR.LAST_NAME AS SURNAME,
    GR.FULL_NAME,
    C.MIDDLE_NAME,
    C.TITLE1 AS TITLE,
    C.TITLE2 AS TITLE_2,
    C.SUFFIX1 AS SUFFIX,
    C.SUFFIX2 AS SUFFIX_2,
    C.GENDER,
    C.DOB AS DATE_OF_BIRTH,
    C.DECEASED::BOOLEAN AS DECEASED,
    C.DATEDECEASED AS DATE_DECEASED,
    C.ISHONOURMEMORIAL AS IS_MEMORIAL,
    C.ORGANISATIONNAME AS ORGANISATION_NAME,
    C.IMPORTID AS LOOKUP_ID,
    A.ADDRESSLINE1 AS ADDRESS_LINE_1,
    A.ADDRESSLINE2 AS ADDRESS_LINE_2,
    A.ADDRESSLINE3 AS ADDRESS_LINE_3,
    A.ADDRESSLINE4 AS ADDRESS_LINE_4,
    A.CITY,
    A.COUNTYDESCRIPTION AS COUNTY,
    A.POSTCODE,
    A.COUNTRYDESCRIPTION AS COUNTRY,
    C.PREFERRED_ADDRESS_ID,
    GR.EMAIL,
    HP.HOME_PHONE,
    MP.MOBILE_PHONE,
    WP.WORK_PHONE,
    WE.WORK_EMAIL,
    TEL.TELEPHONE,
    ATT.SUBSCRIBER_TYPE,
    ATT.POSTAL_PREFERENCE,
    ATT.EMAIL_PREFERENCE,
    ATT.SMS_PREFERENCE,
    ATT.TELEPHONE_PREFERENCE,
    ATT.CONTACT_EXCLUSION,
    ATT.LICENCED_USER_TYPE,
    ATT.PROFESSIONAL_WORK_SECTOR,
    ATT.JOB_TITLE,
    ATT.LEGACY_INTENDER,
    ATT.LEGACY_PLEDGER,
    ATT.LEGACY_CONSIDERER,
    ATT.LEGACY_ENQUIRER,
    UKC.UK_COUNTRY,
    CAUT.CONNECTION_TO_AUTISM,
    SC.IS_MAJOR_DONOR,
    SC.IS_POLITICIAN,
    SC.IS_CELEBRITY,
    SC.IN_MEMORY_DONATION_HONOUREE,
    SC.IN_MEMORY_NEXT_OF_KIN,
    SC.BENEVOLENT_FAMILY,
    SC.IS_CORPORATE,
    SC.NAS_BRANCH_CONTACT,
    SC.PR_CASE_STUDY,
    SC.STATUTORY_AUTHORITY,
    SC.SPECIAL_EVENTER,
    SC.TRUSTS,
    SC.LEGACY_SUPPORTER,
    COALESCE(
        REPLACE(LOWER(SCR.SOLICIT_CODES), ' ', '_') LIKE '%do_not_contact%',
        FALSE
    ) AS DO_NOT_CONTACT,
    SCR.SOLICIT_CODES,
    (IMD.CONSTITUENT_ID IS NOT NULL) AS IN_MEMORY_DONOR,
    (ARG.CONSTITUENT_ID IS NOT NULL) AS ACTIVE_REGULAR_GIVER,
    (APG.CONSTITUENT_ID IS NOT NULL) AS ACTIVE_PAYROLL_GIVER,
    (CG.CONSTITUENT_ID IS NOT NULL) AS CASH_GIVER,
    (LP.CONSTITUENT_ID IS NOT NULL) AS LOTTERY_PLAYER,
    (CAMP.CONSTITUENT_ID IS NOT NULL) AS CAMPAIGNER,
    VOL.VOLUNTEER_TYPE,
    VOL.VOLUNTEER_STATUS,
    SR.FOUR_YEAR_RULE,
    XC.LAST_UPDATED,
    1 AS _SOURCE_RANK
FROM MDM_DB.GOLD.GOLDEN_RECORDS AS GR
INNER JOIN XREF_CANONICAL AS XC ON GR.GOLDEN_RECORD_ID = XC.GOLDEN_RECORD_ID
INNER JOIN
    RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENT AS C
    ON XC.CONSTITUENT_ID = C.CONSTITUENT_ID
LEFT JOIN
    RAW.RAISERS_EDGE.VW_ODS_T_ADDRESSES AS A
    ON C.PREFERRED_ADDRESS_ID = A.ID
LEFT JOIN SR ON XC.CONSTITUENT_ID = SR.SOURCE_RECORD_ID
LEFT JOIN HOME_PHONE_CTE AS HP ON C.CONSTITUENT_ID = HP.CONSTITUENT_ID
LEFT JOIN MOBILE_PHONE_CTE AS MP ON C.CONSTITUENT_ID = MP.CONSTITUENT_ID
LEFT JOIN WORK_PHONE_CTE AS WP ON C.CONSTITUENT_ID = WP.CONSTITUENT_ID
LEFT JOIN TELEPHONE_CTE AS TEL ON C.CONSTITUENT_ID = TEL.CONSTITUENT_ID
