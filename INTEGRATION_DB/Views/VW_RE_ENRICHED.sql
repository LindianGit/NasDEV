WORK_PHONE_CTE AS (
    SELECT
        CONSTITUENT_ID,
        PHONENUMBER AS WORK_PHONE
    FROM RAW.RAISERS_EDGE.VW_ODS_T_PHONENUMBERS
    WHERE PHONETYPEDESCRIPTION = 'Work' AND ISACTIVE = 1
    QUALIFY
        ROW_NUMBER()
            OVER (PARTITION BY CONSTITUENT_ID ORDER BY ISPRIMARY DESC, ID DESC)
