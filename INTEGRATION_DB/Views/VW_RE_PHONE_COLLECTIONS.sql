create or replace view INTEGRATION_DB.RAISERS_EDGE.VW_RE_PHONE_COLLECTIONS(
	GOLDEN_RECORD_ID,
	CONSTITUENT_ID,
	SYSTEMRECORDID,
	PHONES
) as
WITH GOLDEN_PHONES AS (
    SELECT
        gr.GOLDEN_RECORD_ID,
        ids.RE_CONSTITUENT_ID AS CONSTITUENT_ID,
        co.SYSTEMRECORDID,
        gr.HOME_PHONE,
        gr.MOBILE_PHONE,
        gr.WORK_PHONE,
        gr.TELEPHONE
    FROM MDM_DB.GOLD.GOLDEN_RECORDS AS gr
    INNER JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS AS ids
        ON ids.GOLDEN_RECORD_ID = gr.GOLDEN_RECORD_ID
    LEFT JOIN RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENT AS re_raw
        ON re_raw.CONSTITUENT_ID = ids.RE_CONSTITUENT_ID
    LEFT JOIN RAW_PROD.RAISERS_EDGE.ODS_T_CONSTITUENT AS CO 
        ON CO.CONSTITUENT_ID = ids.RE_CONSTITUENT_ID
    WHERE
        gr._IS_ACTIVE = TRUE
        AND ids.IS_GDPR_SUPPRESSED = FALSE
        AND gr.FOUR_YEAR = TRUE
        AND ids.RE_CONSTITUENT_ID IS NOT NULL
),

PHONE_SOURCE AS (
    SELECT
        GOLDEN_RECORD_ID,
        CONSTITUENT_ID,
        SYSTEMRECORDID,
        'Home' AS PHONE_TYPE,
        HOME_PHONE AS PHONE_NUMBER
    FROM GOLDEN_PHONES
    WHERE NULLIF(TRIM(HOME_PHONE), '') IS NOT NULL
    UNION ALL
    SELECT
        GOLDEN_RECORD_ID,
        CONSTITUENT_ID,
        SYSTEMRECORDID,
        'Mobile' AS PHONE_TYPE,
        MOBILE_PHONE AS PHONE_NUMBER
    FROM GOLDEN_PHONES
    WHERE NULLIF(TRIM(MOBILE_PHONE), '') IS NOT NULL
    UNION ALL
    SELECT
        GOLDEN_RECORD_ID,
        CONSTITUENT_ID,
        SYSTEMRECORDID,
        'Work' AS PHONE_TYPE,
        WORK_PHONE AS PHONE_NUMBER
    FROM GOLDEN_PHONES
    WHERE NULLIF(TRIM(WORK_PHONE), '') IS NOT NULL
    UNION ALL
    SELECT
        GOLDEN_RECORD_ID,
        CONSTITUENT_ID,
        SYSTEMRECORDID,
        'Telephone' AS PHONE_TYPE,
        TELEPHONE AS PHONE_NUMBER
    FROM GOLDEN_PHONES
    WHERE NULLIF(TRIM(TELEPHONE), '') IS NOT NULL
),

RE_PHONE_CTE AS (
    SELECT
        CONSTITUENT_ID,
        ID AS PHONE_ID,
        PHONETYPEDESCRIPTION
    FROM RAW.RAISERS_EDGE.VW_ODS_T_PHONENUMBERS
    WHERE ISACTIVE = 1
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CONSTITUENT_ID, PHONETYPEDESCRIPTION
        ORDER BY ISPRIMARY DESC, ID DESC
    ) = 1
),

RE_PHONE_NUMBERS AS (
    SELECT DISTINCT
        CONSTITUENT_ID,
        REGEXP_REPLACE(PHONENUMBER, '[^0-9]', '') AS NUMBER_NORM
    FROM RAW.RAISERS_EDGE.VW_ODS_T_PHONENUMBERS
    WHERE
        ISACTIVE = 1
        AND NULLIF(REGEXP_REPLACE(PHONENUMBER, '[^0-9]', ''), '') IS NOT NULL
)

SELECT
    PS.GOLDEN_RECORD_ID,
    PS.CONSTITUENT_ID,
    PS.SYSTEMRECORDID,
    ARRAY_AGG(
        OBJECT_CONSTRUCT(
            'number', NULLIF(TRIM(PS.PHONE_NUMBER), ''),
            'type', PS.PHONE_TYPE
        )
    ) WITHIN GROUP (ORDER BY PS.PHONE_TYPE) AS PHONES
FROM PHONE_SOURCE AS PS
LEFT JOIN RE_PHONE_CTE AS PH
    ON
        PS.CONSTITUENT_ID = PH.CONSTITUENT_ID
        AND PS.PHONE_TYPE = PH.PHONETYPEDESCRIPTION
LEFT JOIN RE_PHONE_NUMBERS AS RN
    ON
        PS.CONSTITUENT_ID = RN.CONSTITUENT_ID
        AND REGEXP_REPLACE(PS.PHONE_NUMBER, '[^0-9]', '') = RN.NUMBER_NORM
WHERE
    PH.PHONE_ID IS NULL
    AND RN.NUMBER_NORM IS NULL
GROUP BY
    PS.GOLDEN_RECORD_ID,
    PS.CONSTITUENT_ID,
    PS.SYSTEMRECORDID;