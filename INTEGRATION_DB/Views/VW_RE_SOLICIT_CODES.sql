create or replace view INTEGRATION_DB.RAISERS_EDGE.VW_RE_SOLICIT_CODES(
	GOLDEN_RECORD_ID,
	CONSTITUENT_ID,
	SYSTEMRECORDID,
	COMMUNICATION_PREFERENCE_ID,
	ACTION,
	PAYLOAD
) as
WITH GOLDEN_BASE AS (
    SELECT
        GR.GOLDEN_RECORD_ID,
        IDS.RE_CONSTITUENT_ID AS CONSTITUENT_ID,
        re_raw.SYSTEMRECORDID,
        GR.SOLICIT_CODES
    FROM MDM_DB.GOLD.GOLDEN_RECORDS AS GR
    INNER JOIN MDM_DB.GOLD.VW_GOLDEN_RECORD_IDS AS IDS
        ON GR.GOLDEN_RECORD_ID = IDS.GOLDEN_RECORD_ID
    LEFT JOIN RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENT AS re_raw
        ON re_raw.CONSTITUENT_ID = IDS.RE_CONSTITUENT_ID
    WHERE
        GR._IS_ACTIVE = TRUE
        AND IDS.IS_GDPR_SUPPRESSED = FALSE
        AND GR.FOUR_YEAR = TRUE
        AND IDS.RE_CONSTITUENT_ID IS NOT NULL
),

DESIRED AS (
    SELECT
        GOLDEN_RECORD_ID,
        CONSTITUENT_ID,
        SYSTEMRECORDID,
        SOLICIT_CODES,
        COALESCE(
            REPLACE(LOWER(SOLICIT_CODES), ' ', '_') LIKE '%do_not_contact%',
            FALSE
        ) AS WANT_DNC,
        COALESCE(
            SOLICIT_CODES LIKE '%Contact Canvasser for ALL Contact%', FALSE
        ) AS WANT_CANVASSER
    FROM GOLDEN_BASE
),

RE_SOLICIT AS (
    SELECT
        CONSTITUENTID AS CONSTITUENT_ID,
        BOOLOR_AGG(SOLICITCODEDESCRIPTION = 'Do NOT Contact') AS HAS_DNC,
        BOOLOR_AGG(
            SOLICITCODEDESCRIPTION = 'Contact Canvasser for ALL Contact'
        ) AS HAS_CANVASSER,
        MAX(
            CASE
                WHEN
                    SOLICITCODEDESCRIPTION = 'Contact Canvasser for ALL Contact'
                    THEN ID
            END
        ) AS CANVASSER_CODE_ID
    FROM RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTSOLICITCODES
    WHERE
        SOLICITCODEDESCRIPTION IN (
            'Do NOT Contact', 'Contact Canvasser for ALL Contact'
        )
    GROUP BY CONSTITUENTID
)

-- POST 'Do NOT Contact'
SELECT
    D.GOLDEN_RECORD_ID,
    D.CONSTITUENT_ID,
    D.SYSTEMRECORDID,
    CAST(NULL AS NUMBER) AS COMMUNICATION_PREFERENCE_ID,
    'POST' AS ACTION,
    OBJECT_CONSTRUCT(
        'constituent_id', D.SYSTEMRECORDID,
        'solicit_code', 'Do NOT Contact',
        'start',
        TO_VARCHAR(CURRENT_DATE(), 'YYYY-MM-DD') || 'T00:00:00.0000000+00:00'
    ) AS PAYLOAD
FROM DESIRED AS D
LEFT JOIN RE_SOLICIT AS RS ON D.CONSTITUENT_ID = RS.CONSTITUENT_ID
WHERE D.WANT_DNC AND NOT COALESCE(RS.HAS_DNC, FALSE)

UNION ALL

-- POST 'Contact Canvasser for ALL Contact'
SELECT
    D.GOLDEN_RECORD_ID,
    D.CONSTITUENT_ID,
    D.SYSTEMRECORDID,
    CAST(NULL AS NUMBER) AS COMMUNICATION_PREFERENCE_ID,
    'POST' AS ACTION,
    OBJECT_CONSTRUCT(
        'constituent_id', D.SYSTEMRECORDID,
        'solicit_code', 'Contact Canvasser for ALL Contact',
        'start',
        TO_VARCHAR(CURRENT_DATE(), 'YYYY-MM-DD') || 'T00:00:00.0000000+00:00'
    ) AS PAYLOAD
FROM DESIRED AS D
LEFT JOIN RE_SOLICIT AS RS ON D.CONSTITUENT_ID = RS.CONSTITUENT_ID
WHERE D.WANT_CANVASSER AND NOT COALESCE(RS.HAS_CANVASSER, FALSE)

UNION ALL

-- PATCH retire 'Contact Canvasser for ALL Contact'
SELECT
    D.GOLDEN_RECORD_ID,
    D.CONSTITUENT_ID,
    D.SYSTEMRECORDID,
    RS.CANVASSER_CODE_ID AS COMMUNICATION_PREFERENCE_ID,
    'PATCH' AS ACTION,
    OBJECT_CONSTRUCT(
        'solicit_code', 'Contact Canvasser for ALL Contact',
        'end',
        TO_VARCHAR(CURRENT_DATE(), 'YYYY-MM-DD') || 'T00:00:00.0000000+00:00'
    ) AS PAYLOAD
FROM DESIRED AS D
INNER JOIN RE_SOLICIT AS RS ON D.CONSTITUENT_ID = RS.CONSTITUENT_ID
WHERE
    D.SOLICIT_CODES IS NOT NULL
    AND COALESCE(RS.HAS_CANVASSER, FALSE)
    AND NOT D.WANT_CANVASSER;