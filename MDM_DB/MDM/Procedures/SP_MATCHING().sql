CREATE OR REPLACE PROCEDURE MDM_DB.MDM.SP_MATCHING()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
    LET rows_candidates INT := 0;
    LET rows_components INT := 0;
    LET rows_groups     INT := 0;
    LET rows_members    INT := 0;
    TRUNCATE TABLE MDM_DB.STAGING.MATCH_CANDIDATES;
    TRUNCATE TABLE MDM_DB.STAGING.MATCH_COMPONENTS;
    TRUNCATE TABLE MDM_DB.MDM.MATCH_GROUPS;
    TRUNCATE TABLE MDM_DB.MDM.MATCH_GROUP_MEMBERS;

    INSERT INTO MDM_DB.STAGING.MATCH_CANDIDATES (
        STANDARDISED_ID_A, STANDARDISED_ID_B, MATCH_METHOD, MATCH_SCORE
    )
    WITH flat_emails AS (
        SELECT r.STANDARDISED_ID, LOWER(e.VALUE:EMAIL::VARCHAR) AS EMAIL
        FROM MDM_DB.STAGING.STANDARDISED_RECORDS r,
            LATERAL FLATTEN(INPUT => r.ALL_EMAILS) e
        WHERE r._IS_ACTIVE = TRUE AND e.VALUE:EMAIL::VARCHAR IS NOT NULL
    ),
    flat_phones AS (
        SELECT r.STANDARDISED_ID, p.VALUE:PHONE::VARCHAR AS PHONE
        FROM MDM_DB.STAGING.STANDARDISED_RECORDS r,
            LATERAL FLATTEN(INPUT => r.ALL_PHONES) p
        WHERE r._IS_ACTIVE = TRUE AND p.VALUE:PHONE::VARCHAR IS NOT NULL
            AND LENGTH(p.VALUE:PHONE::VARCHAR) >= 7
    ),
    flat_addresses AS (
        SELECT r.STANDARDISED_ID, r.FIRST_NAME, r.LAST_NAME,
            a.VALUE:ADDRESS_LINE1::VARCHAR AS ADDRESS_LINE1,
            a.VALUE:POSTCODE::VARCHAR      AS POSTCODE,
            a.VALUE:IS_PREFERRED::NUMBER   AS IS_PREFERRED
        FROM MDM_DB.STAGING.STANDARDISED_RECORDS r,
            LATERAL FLATTEN(INPUT => r.ALL_ADDRESSES) a
        WHERE r._IS_ACTIVE = TRUE
    ),
    exact_email AS (
        SELECT DISTINCT e1.STANDARDISED_ID AS ID_A, e2.STANDARDISED_ID AS ID_B,
            ''EXACT_EMAIL'' AS MATCH_METHOD, 100.0 AS MATCH_SCORE
        FROM flat_emails e1
        INNER JOIN flat_emails e2 ON e1.EMAIL = e2.EMAIL AND e1.STANDARDISED_ID < e2.STANDARDISED_ID
    ),
    exact_phone AS (
        SELECT DISTINCT p1.STANDARDISED_ID AS ID_A, p2.STANDARDISED_ID AS ID_B,
            ''EXACT_PHONE'' AS MATCH_METHOD, 95.0 AS MATCH_SCORE
        FROM flat_phones p1
        INNER JOIN flat_phones p2 ON p1.PHONE = p2.PHONE AND p1.STANDARDISED_ID < p2.STANDARDISED_ID
    ),
    exact_name_postcode AS (
        SELECT a1.STANDARDISED_ID AS ID_A, a2.STANDARDISED_ID AS ID_B,
            ''EXACT_NAME_POSTCODE'' AS MATCH_METHOD, 90.0 AS MATCH_SCORE
        FROM flat_addresses a1
        INNER JOIN flat_addresses a2
            ON  a1.POSTCODE    = a2.POSTCODE
            AND a1.FIRST_NAME  = a2.FIRST_NAME
            AND a1.LAST_NAME   = a2.LAST_NAME
            AND a1.STANDARDISED_ID < a2.STANDARDISED_ID
        WHERE a1.POSTCODE IS NOT NULL AND a1.FIRST_NAME IS NOT NULL AND a1.LAST_NAME IS NOT NULL
        GROUP BY a1.STANDARDISED_ID, a2.STANDARDISED_ID
    ),
    fuzzy_name_address AS (
        SELECT a1.STANDARDISED_ID AS ID_A, a2.STANDARDISED_ID AS ID_B,
            ''FUZZY_NAME_ADDRESS'' AS MATCH_METHOD,
            (
                JAROWINKLER_SIMILARITY(a1.FIRST_NAME, a2.FIRST_NAME) +
                JAROWINKLER_SIMILARITY(a1.LAST_NAME, a2.LAST_NAME) +
                JAROWINKLER_SIMILARITY(COALESCE(a1.ADDRESS_LINE1, ''''), COALESCE(a2.ADDRESS_LINE1, ''''))
            ) / 3.0 AS MATCH_SCORE
        FROM flat_addresses a1
        INNER JOIN flat_addresses a2
            ON  a1.POSTCODE = a2.POSTCODE
            AND a1.STANDARDISED_ID < a2.STANDARDISED_ID
            AND a2.IS_PREFERRED = 1
        WHERE a1.IS_PREFERRED = 1
            AND a1.POSTCODE IS NOT NULL AND a1.FIRST_NAME IS NOT NULL AND a1.LAST_NAME IS NOT NULL
            AND JAROWINKLER_SIMILARITY(a1.LAST_NAME, a2.LAST_NAME) >= 85
            AND JAROWINKLER_SIMILARITY(a1.FIRST_NAME, a2.FIRST_NAME) >= 80
    )
    -- ,
    -- exact_name_only AS (
    --     SELECT r1.STANDARDISED_ID AS ID_A, r2.STANDARDISED_ID AS ID_B,
    --         ''EXACT_NAME'' AS MATCH_METHOD, 70.0 AS MATCH_SCORE
    --     FROM MDM_DB.STAGING.STANDARDISED_RECORDS r1
    --     INNER JOIN MDM_DB.STAGING.STANDARDISED_RECORDS r2
    --         ON r1.FIRST_NAME = r2.FIRST_NAME AND r1.LAST_NAME = r2.LAST_NAME
    --         AND r1.STANDARDISED_ID < r2.STANDARDISED_ID
    --         AND r1._IS_ACTIVE = TRUE AND r2._IS_ACTIVE = TRUE
    --     WHERE r1.FIRST_NAME IS NOT NULL AND r1.LAST_NAME IS NOT NULL
    --         AND LENGTH(r1.FIRST_NAME) >= 2 AND LENGTH(r1.LAST_NAME) >= 2
    -- )
    SELECT ID_A, ID_B, MATCH_METHOD, MATCH_SCORE FROM exact_email
    UNION SELECT ID_A, ID_B, MATCH_METHOD, MATCH_SCORE FROM exact_phone
    UNION SELECT ID_A, ID_B, MATCH_METHOD, MATCH_SCORE FROM exact_name_postcode
    UNION SELECT ID_A, ID_B, MATCH_METHOD, MATCH_SCORE FROM fuzzy_name_address
    -- UNION SELECT ID_A, ID_B, MATCH_METHOD, MATCH_SCORE FROM exact_name_only
    ;
    rows_candidates := SQLROWCOUNT;

    INSERT INTO MDM_DB.STAGING.MATCH_COMPONENTS (STANDARDISED_ID, MATCH_GROUP_LABEL)
    SELECT STANDARDISED_ID_A, STANDARDISED_ID_A FROM MDM_DB.STAGING.MATCH_CANDIDATES
    UNION
    SELECT STANDARDISED_ID_B, STANDARDISED_ID_B FROM MDM_DB.STAGING.MATCH_CANDIDATES;
    rows_components := SQLROWCOUNT;

    CALL MDM_DB.STAGING.BUILD_MATCH_COMPONENTS();

    UPDATE MDM_DB.STAGING.MATCH_COMPONENTS SET MATCH_GROUP_ID = ''MG-'' || MATCH_GROUP_LABEL;

    INSERT INTO MDM_DB.MDM.MATCH_GROUPS (
        MATCH_GROUP_ID, DOMAIN, MATCH_SCORE, MATCH_METHOD, RECORD_COUNT, STATUS, CREATED_AT, UPDATED_AT
    )
    WITH group_counts AS (
        SELECT MATCH_GROUP_ID, COUNT(*) AS RECORD_COUNT
        FROM MDM_DB.STAGING.MATCH_COMPONENTS
        GROUP BY MATCH_GROUP_ID
        HAVING COUNT(*) > 1
    ),
    group_scores AS (
        SELECT c1.MATCH_GROUP_ID,
            AVG(cand.MATCH_SCORE)                            AS AVG_SCORE,
            MAX_BY(cand.MATCH_METHOD, cand.MATCH_SCORE)      AS BEST_METHOD
        FROM MDM_DB.STAGING.MATCH_CANDIDATES cand
        INNER JOIN MDM_DB.STAGING.MATCH_COMPONENTS c1 ON cand.STANDARDISED_ID_A = c1.STANDARDISED_ID
        INNER JOIN MDM_DB.STAGING.MATCH_COMPONENTS c2
            ON cand.STANDARDISED_ID_B = c2.STANDARDISED_ID AND c1.MATCH_GROUP_ID = c2.MATCH_GROUP_ID
        GROUP BY c1.MATCH_GROUP_ID
    )
    SELECT
        gc.MATCH_GROUP_ID,
        ''CONTACT'',
        gs.AVG_SCORE,
        gs.BEST_METHOD,
        gc.RECORD_COUNT,
        CASE
            WHEN gs.AVG_SCORE >= 95 THEN ''Auto-Approved''
            WHEN gs.AVG_SCORE >= 85 THEN ''Pending Review''
            ELSE ''Low Confidence''
        END,
        CURRENT_TIMESTAMP(),
        CURRENT_TIMESTAMP()
    FROM group_counts gc
    INNER JOIN group_scores gs ON gc.MATCH_GROUP_ID = gs.MATCH_GROUP_ID;
    rows_groups := SQLROWCOUNT;

    INSERT INTO MDM_DB.MDM.MATCH_GROUP_MEMBERS (
        MATCH_GROUP_ID, SOURCE_SYSTEM, SOURCE_RECORD_ID, STANDARDISED_ID,
        MATCH_PROBABILITY, IS_SURVIVING_RECORD, ADDED_AT
    )
    SELECT
        mc.MATCH_GROUP_ID,
        sr.SOURCE_SYSTEM,
        sr.SOURCE_RECORD_ID,
        mc.STANDARDISED_ID,
        mg.MATCH_SCORE,
        ROW_NUMBER() OVER (PARTITION BY mc.MATCH_GROUP_ID ORDER BY sr.LAST_UPDATED DESC NULLS LAST) = 1,
        CURRENT_TIMESTAMP()
    FROM MDM_DB.STAGING.MATCH_COMPONENTS mc
    INNER JOIN MDM_DB.STAGING.STANDARDISED_RECORDS sr ON mc.STANDARDISED_ID = sr.STANDARDISED_ID
    INNER JOIN MDM_DB.MDM.MATCH_GROUPS mg ON mc.MATCH_GROUP_ID = mg.MATCH_GROUP_ID;
    rows_members := SQLROWCOUNT;

    RETURN ''Matching complete. Candidates: '' || rows_candidates || '', Components: '' || rows_components || '', Groups: '' || rows_groups || '', Members: '' || rows_members;
END;
';