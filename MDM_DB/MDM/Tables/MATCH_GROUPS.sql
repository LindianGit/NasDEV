create or replace TABLE MDM_DB.MDM.MATCH_GROUPS (
	MATCH_GROUP_ID VARCHAR(100) NOT NULL,
	DOMAIN VARCHAR(50),
	MATCH_SCORE FLOAT,
	MATCH_METHOD VARCHAR(50),
	RECORD_COUNT NUMBER(38,0),
	STATUS VARCHAR(50),
	IS_AUTO_APPROVED BOOLEAN DEFAULT FALSE,
	IS_MANUALLY_REVIEWED BOOLEAN DEFAULT FALSE,
	REVIEWED_BY VARCHAR(200),
	REVIEWED_AT TIMESTAMP_NTZ(9),
	CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	UPDATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	constraint PK_MATCH_GROUPS primary key (MATCH_GROUP_ID)
);