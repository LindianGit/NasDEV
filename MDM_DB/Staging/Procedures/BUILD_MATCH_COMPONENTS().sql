CREATE OR REPLACE PROCEDURE MDM_DB.STAGING.BUILD_MATCH_COMPONENTS()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
    LET rows_updated INT := 0;
    LET iteration    INT := 0;
    LOOP
        iteration := iteration + 1;
        UPDATE MDM_DB.STAGING.MATCH_COMPONENTS tgt
        SET MATCH_GROUP_LABEL = sub.NEW_LABEL
        FROM (
            SELECT mc.STANDARDISED_ID, LEAST(mc.MATCH_GROUP_LABEL, mn.MIN_NEIGHBOUR) AS NEW_LABEL
            FROM MDM_DB.STAGING.MATCH_COMPONENTS mc
            INNER JOIN (
                SELECT STANDARDISED_ID_A AS NODE, MIN(nb.MATCH_GROUP_LABEL) AS MIN_NEIGHBOUR
                FROM MDM_DB.STAGING.MATCH_CANDIDATES c
                INNER JOIN MDM_DB.STAGING.MATCH_COMPONENTS nb ON c.STANDARDISED_ID_B = nb.STANDARDISED_ID
                GROUP BY STANDARDISED_ID_A
                UNION ALL
                SELECT STANDARDISED_ID_B AS NODE, MIN(nb.MATCH_GROUP_LABEL) AS MIN_NEIGHBOUR
                FROM MDM_DB.STAGING.MATCH_CANDIDATES c
                INNER JOIN MDM_DB.STAGING.MATCH_COMPONENTS nb ON c.STANDARDISED_ID_A = nb.STANDARDISED_ID
                GROUP BY STANDARDISED_ID_B
            ) mn ON mc.STANDARDISED_ID = mn.NODE
            WHERE LEAST(mc.MATCH_GROUP_LABEL, mn.MIN_NEIGHBOUR) < mc.MATCH_GROUP_LABEL
        ) sub
        WHERE tgt.STANDARDISED_ID = sub.STANDARDISED_ID;
        rows_updated := SQLROWCOUNT;
        IF (rows_updated = 0 OR iteration >= 20) THEN
            RETURN ''Converged after '' || iteration || '' iterations'';
        END IF;
    END LOOP;
END;
';