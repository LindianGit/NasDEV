create or replace TABLE MDM_DB.STAGING.MATCH_CANDIDATES (
	STANDARDISED_ID_A VARCHAR(100) NOT NULL,
	STANDARDISED_ID_B VARCHAR(100) NOT NULL,
	MATCH_METHOD VARCHAR(50) NOT NULL,
	MATCH_SCORE FLOAT,
	CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	IS_LINKING BOOLEAN DEFAULT TRUE,
	IS_IDENTITY BOOLEAN DEFAULT FALSE,
	IS_STRONG BOOLEAN DEFAULT FALSE,
	constraint PK_MATCH_CANDIDATES primary key (STANDARDISED_ID_A, STANDARDISED_ID_B, MATCH_METHOD)
);