create or replace TABLE MDM_DB.STAGING.MATCH_PROPOSALS (
	STANDARDISED_ID_A VARCHAR(100) NOT NULL,
	STANDARDISED_ID_B VARCHAR(100) NOT NULL,
	MATCH_METHOD VARCHAR(50),
	MATCH_SCORE FLOAT,
	CORE_GROUP_ID_A VARCHAR(100),
	CORE_GROUP_ID_B VARCHAR(100),
	CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
