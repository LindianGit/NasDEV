create or replace view RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENT(
	CONSTITUENT_ID,
	GENERICNAME,
	ORGANISATIONNAME,
	FIRST_NAME,
	LAST_NAME,
	TITLE1,
	TITLE2,
	SUFFIX1,
	SUFFIX2,
	GENDER,
	DOB,
	AGE,
	DECEASED,
	DATEDECEASED,
	PREFERRED_ADDRESS_ID,
	ISCANVASSER,
	ISORGANISATION,
	ISHONOURMEMORIAL,
	EMAIL,
	WEBUSERNAME,
	SALSUPPORTER,
	SALMEMBER,
	SALCOLLEAGUE,
	PRIMARYADDRESSEE,
	PRIMARYSALUTATION,
	ISMEMBER,
	ISSTAFF,
	DATEADDED,
	ADDEDBY,
	DATECHANGED,
	CHANGEDBY,
	IMPORTID,
	SYSTEMRECORDID,
	MIDDLE_NAME,
	MD5_HASH,
	EXTRACT_TS
) as
SELECT
    CONSTITUENT_ID,
    GENERICNAME,
    NULLIF(TRIM(ORGANISATIONNAME), '')                                                              AS ORGANISATIONNAME,
    FIRST_NAME,
    LAST_NAME,
    NULLIF(TRIM(TITLE1), '')                                                                        AS TITLE1,
    NULLIF(TRIM(TITLE2), '')                                                                        AS TITLE2,
    NULLIF(TRIM(SUFFIX1), '')                                                                       AS SUFFIX1,
    NULLIF(TRIM(SUFFIX2), '')                                                                       AS SUFFIX2,
    NULLIF(TRIM(GENDER), '')                                                                        AS GENDER,
    DOB,
    AGE,
    DECEASED,
    DATEDECEASED,
    PREFERRED_ADDRESS_ID,
    ISCANVASSER,
    ISORGANISATION,
    ISHONOURMEMORIAL,
    NULLIF(TRIM(EMAIL), '')                                                                         AS EMAIL,
    NULLIF(TRIM(WEBUSERNAME), '')                                                                   AS WEBUSERNAME,
    SALSUPPORTER,
    SALMEMBER,
    SALCOLLEAGUE,
    NULLIF(TRIM(PRIMARYADDRESSEE), '')                                                              AS PRIMARYADDRESSEE,
    NULLIF(TRIM(PRIMARYSALUTATION), '')                                                             AS PRIMARYSALUTATION,
    ISMEMBER,
    ISSTAFF,
    DATEADDED,
    NULLIF(TRIM(ADDEDBY), '')                                                                       AS ADDEDBY,
    DATECHANGED,
    NULLIF(TRIM(CHANGEDBY), '')                                                                     AS CHANGEDBY,
    NULLIF(TRIM(IMPORTID), '')                                                                      AS IMPORTID,
    NULLIF(TRIM(SYSTEMRECORDID), '')                                                                AS SYSTEMRECORDID,
    NULLIF(TRIM(MIDDLE_NAME), '')                                                                   AS MIDDLE_NAME,
    MD5_HASH,
    EXTRACT_TS
FROM RAW.RAISERS_EDGE.ODS_T_CONSTITUENT
WHERE NOT IS_DELETED;