create or replace view RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTADDRESSATTRIBUTES(
	ID,
	CONSTITUENTADDRESSID,
	SEQUENCE,
	CATEGORY,
	VALUE,
	DATE,
	COMMENTS
) as
SELECT
    ID,
    CONSTITUENTADDRESSID,
    SEQUENCE,
    CATEGORY,
    VALUE,
    DATE,
    COMMENTS
