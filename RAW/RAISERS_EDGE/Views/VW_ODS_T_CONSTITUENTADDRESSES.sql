create or replace view RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTADDRESSES(
	ID,
	CONSTITUENT_ID,
	ADDRESS_ID,
	DATE_ADDED,
	DATE_FROM,
	DATE_TO,
	INFOSOURCECODE,
	INFOSOURCEDESCRIPTION,
	ADDRESSTYPECODE,
	ADDRESSTYPEDESCRIPTION,
	PREFERRED,
	SENDMAIL,
	IMPORT_ID
) as
SELECT
    ID,
    CONSTITUENT_ID,
    ADDRESS_ID,
    DATE_ADDED,
    DATE_FROM,
    DATE_TO,
    INFOSOURCECODE,
    INFOSOURCEDESCRIPTION,
    ADDRESSTYPECODE,
    ADDRESSTYPEDESCRIPTION,
    PREFERRED,
    SENDMAIL,
    IMPORT_ID
FROM RAW.RAISERS_EDGE.ODS_T_CONSTITUENTADDRESSES
WHERE NOT IS_DELETED;