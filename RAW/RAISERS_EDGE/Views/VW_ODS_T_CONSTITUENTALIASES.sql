create or replace view RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTALIASES(
	ID,
	CONSTITUENT_ID,
	ALIASTYPECODE,
	ALIASTYPEDESCRIPTION,
	ALIASNAME
) as
SELECT
    ID,
    CONSTITUENT_ID,
    ALIASTYPECODE,
    ALIASTYPEDESCRIPTION,
    ALIASNAME
FROM RAW.RAISERS_EDGE.ODS_T_CONSTITUENTALIASES
WHERE NOT IS_DELETED;