create or replace view RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTATTRIBUTES(
	ID,
	CONSTITUENT_ID,
	ATTRIBUTENAME,
	ATTRIBUTEVALUE,
	ATTRIBUTECOMMENT,
	ATTRIBUTEDATE
) as
SELECT
    ID,
    CONSTITUENT_ID,
    ATTRIBUTENAME,
    ATTRIBUTEVALUE,
    ATTRIBUTECOMMENT,
    ATTRIBUTEDATE
FROM RAW.RAISERS_EDGE.ODS_T_CONSTITUENTATTRIBUTES
