create or replace view RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTNOTES(
	ID,
	CONSTITUENTID,
	SEQUENCE,
	DATE,
	NOTETYPECODE,
	NOTETYPEDESCRIPTION,
	TITLE,
	DESCRIPTION,
	AUTHOR,
	ACTUALNOTES
) as
SELECT
    ID,
    CONSTITUENTID,
    SEQUENCE,
    DATE,
    NOTETYPECODE,
    NOTETYPEDESCRIPTION,
    TITLE,
    DESCRIPTION,
    AUTHOR,
    ACTUALNOTES
FROM RAW.RAISERS_EDGE.ODS_T_CONSTITUENTNOTES
WHERE NOT IS_DELETED;