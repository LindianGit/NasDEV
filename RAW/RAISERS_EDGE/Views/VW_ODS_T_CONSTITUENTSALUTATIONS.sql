create or replace view RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTSALUTATIONS(
	ID,
	CONSTITUENTID,
	SALUTATIONTYPECODE,
	SALUTATIONTYPEDESCRIPTION,
	SALUTATION
) as
SELECT
    ID,
    CONSTITUENTID,
    SALUTATIONTYPECODE,
    SALUTATIONTYPEDESCRIPTION,
    SALUTATION
FROM RAW.RAISERS_EDGE.ODS_T_CONSTITUENTSALUTATIONS
WHERE NOT IS_DELETED;