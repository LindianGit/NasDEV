create or replace view RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTSALUTATION_EXTRACTS(
	CONSTITUENTID,
	PRIMARY_ADDRESSEE,
	PRIMARY_SALUTATION,
	DATEUPDATED
) as
SELECT
    CONSTITUENTID,
    PRIMARY_ADDRESSEE,
    PRIMARY_SALUTATION,
    DATEUPDATED
FROM RAW.RAISERS_EDGE.ODS_T_CONSTITUENTSALUTATION_EXTRACTS
WHERE NOT IS_DELETED;