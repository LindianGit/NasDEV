create or replace view RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTSALUTATION_EXTRACTS_TASKS(
	ID,
	CONSTITUENTSYSTEMRECORDID,
	CONSTITUENTID,
	DATECREATED,
	PROCESSED,
	DATEPROCESSED,
	ERRORTEXT
) as
SELECT
    ID,
    CONSTITUENTSYSTEMRECORDID,
    CONSTITUENTID,
    DATECREATED,
    PROCESSED,
    DATEPROCESSED,
    ERRORTEXT
FROM RAW.RAISERS_EDGE.ODS_T_CONSTITUENTSALUTATION_EXTRACTS_TASKS
WHERE NOT IS_DELETED;