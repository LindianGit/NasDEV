create or replace view RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTSOLICITCODES(
	ID,
	CONSTITUENTID,
	SEQUENCE,
	SOLICITCODE,
	SOLICITCODEDESCRIPTION
) as
