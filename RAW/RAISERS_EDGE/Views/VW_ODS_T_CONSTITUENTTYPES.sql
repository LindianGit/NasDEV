create or replace view RAW.RAISERS_EDGE.VW_ODS_T_CONSTITUENTTYPES(
	ID,
	CONSTITUENT_ID,
	CONSTITUENTTYPECODE,
	CONSTITUENTTYPEDESCRIPTION,
	DATESTART,
	DATEEND
) as
SELECT
    ID,
    CONSTITUENT_ID,
    CONSTITUENTTYPECODE,
    CONSTITUENTTYPEDESCRIPTION,
    DATESTART,
    DATEEND
FROM RAW.RAISERS_EDGE.ODS_T_CONSTITUENTTYPES
WHERE NOT IS_DELETED;